// Blank imports.
//
// A test file that blank-imports a package (_ "modernc.org/sqlite")
// depends on the package's init side effect: registering a database/sql
// driver, embedding the time zone database, and so on. Other files rely on
// that side effect without importing anything (sql.Open("sqlite", ...)),
// so the use graph has no edge for it. A shard in which no file imports the
// package compiles, then fails at run time (sql: unknown driver "sqlite").
//
// The generator therefore adds untagged imports files to the overlay that
// blank-import every package a test file of the package blank-imports.
// They compile in every shard build (the plain tree has none). A package goes into the file for its build condition: the OR
// of the importing files' own constraints (without the hubshard clause),
// each including the GOOS/GOARCH constraint of its file name.
// So a shard build links them under the same conditions as the plain
// build.

// importsPrefix names the generated imports files: importsPrefix_test.go
// holds the packages imported without a condition, importsPrefix_K_test.go
// (K = 1, 2, ...) one file per other condition, in the order of the
// condition's text.
const importsPrefix = "zz_hubshard_drivers"

var importsFileRE = regexp.MustCompile(`^` + importsPrefix + `(_[0-9]+)?_test\.go$`)

// isImportsFile reports whether name is a generated imports file.
func isImportsFile(name string) bool {
	return importsFileRE.MatchString(name)
}

const importsHeader = `// Copyright 2026 Google LLC
//
// Licensed under the Apache License, Version 2.0 (the "License");
// you may not use this file except in compliance with the License.
// You may obtain a copy of the License at
//
//     http://www.apache.org/licenses/LICENSE-2.0
//
// Unless required by applicable law or agreed to in writing, software
// distributed under the License is distributed on an "AS IS" BASIS,
// WITHOUT WARRANTIES OR CONDITIONS OF ANY KIND, either express or implied.
// See the License for the specific language governing permissions and
// limitations under the License.

`

const importsBody = `// Code generated by go run ./hack/hubshard; DO NOT EDIT.

// Some test files of this package blank-import the packages below for their
// init side effects (database/sql drivers, time zone data). This untagged
// file imports them too, so that every -tags hubshard,hubshard_K build links
// them, under the same build condition as the default build.

package %s

import (
%s)
`

// testPackage returns the package name the imports files use: the package
// clause of the test files that are not an external _test package (the
// most frequent one, then the first by name), else the most frequent one.
func testPackage(files map[string]*fileInfo) string {
	count := map[string]int{}
	for _, f := range files {
		count[f.pkgName]++
	}
	best := ""
	for _, p := range sortedKeys(count) {
		better := best == "" ||
			(!strings.HasSuffix(p, "_test") && strings.HasSuffix(best, "_test")) ||
			(strings.HasSuffix(p, "_test") == strings.HasSuffix(best, "_test") && count[p] > count[best])
		if better {
			best = p
		}
	}
	return best
}

// importsFiles returns the generated imports files (name -> contents) for
// the blank imports of files (the generated files excluded). Only files of
// package pkg count: an external test package may import packages that
// import pkg itself. The output is deterministic and gofmt-clean.
func importsFiles(files map[string]*fileInfo, pkg string) map[string][]byte {
	uncond := map[string]bool{}
	conds := map[string]map[string]constraint.Expr{} // path -> constraint text -> constraint
	for _, n := range sortedNames(files) {
		f := files[n]
		if f.pkgName != pkg {
			continue
		}
		for _, p := range f.blankImports {
			c := f.cond()
			if c == nil {
				uncond[p] = true
				continue
			}
			if conds[p] == nil {
				conds[p] = map[string]constraint.Expr{}
			}
			conds[p][c.String()] = c
		}
	}
	byCond := map[string][]string{} // condition text ("" = none) -> paths
	for p := range uncond {
		byCond[""] = append(byCond[""], p)
	}
	for p, cs := range conds {
		if uncond[p] {
			continue
		}
		var e constraint.Expr
		for _, text := range sortedKeys(cs) {
			if e == nil {
				e = cs[text]
			} else {
				e = &constraint.OrExpr{X: e, Y: cs[text]}
			}
		}
		key := e.String()
		byCond[key] = append(byCond[key], p)
	}

	out := map[string][]byte{}
	k := 0
	for _, cond := range sortedKeys(byCond) {
		paths := byCond[cond]
		sort.Strings(paths)
		var imports strings.Builder
		for _, p := range paths {
			fmt.Fprintf(&imports, "\t_ %q\n", p)
		}
		var b bytes.Buffer
		b.WriteString(importsHeader)
		name := importsPrefix + "_test.go"
		if cond != "" {
			k++
			name = fmt.Sprintf("%s_%d_test.go", importsPrefix, k)
			fmt.Fprintf(&b, "//go:build %s\n\n", cond)
		}
		fmt.Fprintf(&b, importsBody, pkg, imports.String())
		out[name] = b.Bytes()
	}
	return out
}

// importBreakage lists the blank imports of tagged files that no untagged
// file covers. An untagged file (a common test file, or a generated
// imports file in gen) covers a tagged file's import when it imports the same
// package under a build constraint that the tagged file's own constraint
// implies, so every build that compiles the tagged file links the package
// in every shard. Only files of package pkg count (see importsFiles);
// sideEffectWarnings covers the external test package.
func importBreakage(files, gen map[string]*fileInfo, pkg string) []string {
	importers := map[string][]*fileInfo{} // path -> untagged files importing it
	for _, m := range []map[string]*fileInfo{files, gen} {
		for _, n := range sortedNames(m) {
			if f := m[n]; f.diskShard == 0 {
				for _, p := range f.blankImports {
					importers[p] = append(importers[p], f)
				}
			}
		}
	}
	var problems []string
	for _, n := range sortedNames(files) {
		f := files[n]
		if f.diskShard <= 0 || f.pkgName != pkg {
			continue
		}
		for _, p := range f.blankImports {
			covered := false
			for _, g := range importers[p] {
				if implies(f.cond(), g.cond()) {
					covered = true
					break
				}
			}
			if !covered {
				problems = append(problems, fmt.Sprintf("%s (shard %d) blank-imports %s, and no untagged file imports it under a build constraint the file implies: other shards lose its init side effect (sql: unknown driver)", n, f.diskShard, p))
			}
		}
	}
	return problems
}

// maxImplyTags bounds the truth table implies evaluates.
const maxImplyTags = 16

// implies reports whether every tag assignment that satisfies a also
// satisfies b. A nil constraint is always true. Past maxImplyTags distinct
// tags it answers false, which is conservative (a reported problem).
func implies(a, b constraint.Expr) bool {
	if b == nil {
		return true
	}
	tags := map[string]bool{}
	collectTags(a, tags)
	collectTags(b, tags)
	if len(tags) > maxImplyTags {
		return false
	}
	names := sortedKeys(tags)
	for mask := 0; mask < 1<<len(names); mask++ {
		val := map[string]bool{}
		for i, t := range names {
			val[t] = mask&(1<<i) != 0
		}
		ok := func(tag string) bool { return val[tag] }
		if (a == nil || a.Eval(ok)) && !b.Eval(ok) {
			return false
		}
	}
	return true
}

func collectTags(e constraint.Expr, tags map[string]bool) {
	switch e := e.(type) {
	case *constraint.TagExpr:
		tags[e.Tag] = true
	case *constraint.NotExpr:
		collectTags(e.X, tags)
	case *constraint.AndExpr:
		collectTags(e.X, tags)
		collectTags(e.Y, tags)
	case *constraint.OrExpr:
		collectTags(e.X, tags)
		collectTags(e.Y, tags)
	}
}

// sideEffectWarnings lists what -parity cannot judge and a reviewer should:
//   - a tagged file with an init function that does more than discard
//     values: the init runs only in that shard's binary, and another shard
//     may rely on its effect (the generator makes such a file common, so
//     this appears only if that rule changes);
//   - a blank import in a tagged file of an external test package (not
//     pkg): the imports files do not copy it, because the imported package
//     may import pkg itself.
func sideEffectWarnings(files map[string]*fileInfo, pkg string) []string {
	var warnings []string
	for _, n := range sortedNames(files) {
		f := files[n]
		if f.diskShard <= 0 {
			continue
		}
		if f.hasInit {
			warnings = append(warnings, fmt.Sprintf("warning: %s: init function in a file tagged for shard %d runs only in that shard; review whether other files rely on it", n, f.diskShard))
		}
		if f.pkgName != pkg {
			for _, p := range f.blankImports {
				warnings = append(warnings, fmt.Sprintf("warning: %s: package %s, tagged for shard %d, blank-imports %s, which the imports files do not copy; review whether other shards rely on its init side effect", n, f.pkgName, f.diskShard, p))
			}
		}
	}
	return warnings
}

// cond returns the condition under which the default build compiles f:
// its build line (without the hubshard clause) AND its file-name
// GOOS/GOARCH constraint. nil means always.
func (f *fileInfo) cond() constraint.Expr {
	switch {
	case f.constraint == nil:
		return f.nameCond
	case f.nameCond == nil:
		return f.constraint
	}
	return &constraint.AndExpr{X: f.constraint, Y: f.nameCond}
}

// knownOS and knownArch are the GOOS and GOARCH values go/build recognizes
// in file names (go/build/syslist.go; "unix" is a build tag only, never a
// file-name suffix).
var (
	knownOS = map[string]bool{
		"aix": true, "android": true, "darwin": true, "dragonfly": true, "freebsd": true,
		"hurd": true, "illumos": true, "ios": true, "js": true, "linux": true, "nacl": true,
		"netbsd": true, "openbsd": true, "plan9": true, "solaris": true, "wasip1": true,
		"windows": true, "zos": true,
	}
	knownArch = map[string]bool{
		"386": true, "amd64": true, "amd64p32": true, "arm": true, "armbe": true,
		"arm64": true, "arm64be": true, "loong64": true, "mips": true, "mipsle": true,
		"mips64": true, "mips64le": true, "mips64p32": true, "mips64p32le": true,
		"ppc": true, "ppc64": true, "ppc64le": true, "riscv": true, "riscv64": true,
		"s390": true, "s390x": true, "sparc": true, "sparc64": true, "wasm": true,
	}
)

// fileNameConstraint returns the GOOS/GOARCH constraint that go/build
// derives from a file name (go/build goodOSArchFile): after dropping the
// extension, the part before the first underscore and a final _test, a
// trailing _GOOS_GOARCH, _GOOS or _GOARCH restricts the file. Returns nil
// when the name has none. As a build tag, GOOS linux also holds on
// android (and so on), which matches go/build's file-name rule.
func fileNameConstraint(name string) constraint.Expr {
	name, _, _ = strings.Cut(name, ".")
	i := strings.Index(name, "_")
	if i < 0 {
		return nil
	}
	l := strings.Split(name[i:], "_")
	if n := len(l); n > 0 && l[n-1] == "test" {
		l = l[:n-1]
	}
	n := len(l)
	if n >= 2 && knownOS[l[n-2]] && knownArch[l[n-1]] {
		return &constraint.AndExpr{X: &constraint.TagExpr{Tag: l[n-2]}, Y: &constraint.TagExpr{Tag: l[n-1]}}
	}
	if n >= 1 && (knownOS[l[n-1]] || knownArch[l[n-1]]) {
		return &constraint.TagExpr{Tag: l[n-1]}
	}
	return nil
}
