// Markers of the generated alias files whose declarations export may see
// through. Hand-written forwarding declarations are never resolved: a
// hand-written wrapper or var may be a hook.
const (
	extractAliasMarker = "(generated by hack/hubshard/extract export)"
	pkgmoveAliasMarker = "by hack/pkgmove, so existing references in package"
)

// isAliasFile reports whether f is a generated alias file (zz_alias_*.go
// written by extract export or by hack/pkgmove).
func isAliasFile(f *srcFile) bool {
	if !strings.HasPrefix(f.name, "zz_alias_") {
		return false
	}
	return strings.Contains(string(f.src), extractAliasMarker) || strings.Contains(string(f.src), pkgmoveAliasMarker)
}

// resolution is a staying alias that moved code references, resolved to the
// declaration it forwards to.
type resolution struct {
	kind  aliasKind // aliasType, aliasConst or aliasFunc
	file  string    // the alias file
	path  string    // import path of the target's package
	imp   importKey // the alias file's import of that package
	qual  string    // the package name the alias file uses for it
	name  string    // the target's name
	same  bool      // the target is in the export target package: spelled bare
	helps bool      // a wrapper that calls Helper() (and so does its target)
}

// text is the spelling of the target in the export target package.
func (r *resolution) text() string {
	if r.same {
		return r.name
	}
	return r.qual + "." + r.name
}

// tokens is text as a token sequence, for verify-export.
func (r *resolution) tokens() []tok {
	if r.same {
		return []tok{{token.IDENT, r.name}}
	}
	return []tok{{token.IDENT, r.qual}, {token.PERIOD, ""}, {token.IDENT, r.name}}
}

func (r *resolution) describe() string {
	s := fmt.Sprintf("%s in %s -> %s.%s", r.kind, r.file, r.path, r.name)
	if r.helps {
		s += " (both call Helper() on the same parameter)"
	}
	return s
}

// locate returns the directory holding the source of the package with
// import path ip, for packages under the source package's import path
// (pkg/hub/internal/hubtestutil and pkg/hub/internal/principal under
// pkg/hub). The directory is taken relative to the source package's own
// directory, so an archive of the before tree resolves against its own
// subpackages, not the working tree.
func (ep *exportPlan) locate(ip string) (string, bool) {
	rest, ok := strings.CutPrefix(ip, ep.srcImport+"/")
	if !ok || ep.srcImport == "" || rest == "" {
		return "", false
	}
	dir := filepath.Join(ep.p.dir, filepath.FromSlash(rest))
	if st, err := os.Stat(dir); err != nil || !st.IsDir() {
		return "", false
	}
	return dir, true
}

// loadLocated parses the package at import path ip (cached). Only its
// non-test files count.
func (ep *exportPlan) loadLocated(ip string) (*pkgInfo, error) {
	if q, ok := ep.located[ip]; ok {
		return q, nil
	}
	dir, ok := ep.locate(ip)
	if !ok {
		return nil, fmt.Errorf("cannot locate the source of package %s under %s", ip, ep.p.dir)
	}
	q, err := loadPackage(dir)
	if err != nil {
		return nil, err
	}
	q = filterPkg(q, func(d *declInfo) bool { return !d.file.isTest }, "")
	ep.located[ip] = q
	return q, nil
}

// fileImport returns the import of f that binds name.
func fileImport(f *srcFile, name string) (*ast.ImportSpec, error) {
	if err := validateImportNames(f); err != nil {
		return nil, err
	}
	for _, s := range f.ast.Imports {
		if importName(s) == name {
			return s, nil
		}
	}
	return nil, fmt.Errorf("%s: no import named %s", f.name, name)
}

// qualified returns pkg and Name when e is exactly pkg.Name with pkg a
// package qualifier (not a local or package-level object).
func qualified(e ast.Expr) (string, string, bool) {
	se, ok := e.(*ast.SelectorExpr)
	if !ok {
		return "", "", false
	}
	x, ok := se.X.(*ast.Ident)
	if !ok || x.Obj != nil {
		return "", "", false
	}
	return x.Name, se.Sel.Name, true
}

// resolveAlias resolves a staying declaration that moved code references.
// It returns the resolution, or the reason it cannot be resolved. Only
// declarations of a generated alias file resolve, and only these shapes:
//
//   - a type alias `type x = pkg.X` (no type parameters);
//   - a const alias `const x = pkg.X` (one name, no type, one value);
//   - a wrapper `func x(params) results { [p.Helper()]; return pkg.F(params) }`
//     (or without return when there are no results) that forwards exactly
//     its parameters, in order, to a func of a package it can locate, whose
//     signature is the same after resolving aliases, and which calls
//     Helper() on the same parameter as the wrapper does (or neither does).
//
// Var aliases are a copy, not an alias, and are never resolved.
func (ep *exportPlan) resolveAlias(d *declInfo) (*resolution, string) {
	if !isAliasFile(d.file) {
		return nil, ""
	}
	if d.recv != "" {
		return nil, "a method"
	}
	r := &resolution{file: d.file.name}
	var qual string
	switch n := d.node.(type) {
	case *ast.GenDecl:
		switch n.Tok {
		case token.TYPE:
			ts := typeSpec(d, d.key)
			if ts == nil || !ts.Assign.IsValid() {
				return nil, "a type definition, not an alias"
			}
			if ts.TypeParams != nil {
				return nil, "a generic type alias"
			}
			q, name, ok := qualified(ts.Type)
			if !ok {
				return nil, "a type alias whose target is not pkg.Name"
			}
			r.kind, qual, r.name = aliasType, q, name
		case token.CONST:
			vs := valueSpec(n, d.key)
			if vs == nil || len(vs.Names) != 1 || vs.Type != nil || len(vs.Values) != 1 {
				return nil, "a const that is not a single untyped pkg.Name alias"
			}
			q, name, ok := qualified(vs.Values[0])
			if !ok {
				return nil, "a const whose value is not pkg.Name"
			}
			r.kind, qual, r.name = aliasConst, q, name
		default:
			return nil, "a var alias is a copy, not an alias"
		}
	case *ast.FuncDecl:
		w, why := ep.resolveWrapper(d, n)
		if w == nil {
			return nil, why
		}
		return w, ""
	default:
		return nil, "unsupported declaration"
	}
	spec, err := fileImport(d.file, qual)
	if err != nil {
		return nil, err.Error()
	}
	if err := ep.fillTarget(r, spec, qual); err != nil {
		return nil, err.Error()
	}
	return r, ""
}

// fillTarget sets the import fields of r.
func (ep *exportPlan) fillTarget(r *resolution, spec *ast.ImportSpec, qual string) error {
	ip, err := strconv.Unquote(spec.Path.Value)
	if err != nil {
		return err
	}
	r.path, r.imp, r.qual = ip, specKey(spec), qual
	r.same = ip == ep.importPath
	return nil
}

func valueSpec(g *ast.GenDecl, name string) *ast.ValueSpec {
	for _, s := range g.Specs {
		if vs, ok := s.(*ast.ValueSpec); ok && hasName(vs.Names, name) {
			return vs
		}
	}
	return nil
}

// paramList flattens a field list: one entry per name (or per unnamed
// field), with its type expression.
type param struct {
	name string // "" when unnamed
	typ  ast.Expr
}

func paramList(fl *ast.FieldList) []param {
	if fl == nil {
		return nil
	}
	var out []param
	for _, f := range fl.List {
		if len(f.Names) == 0 {
			out = append(out, param{typ: f.Type})
			continue
		}
		for _, n := range f.Names {
			out = append(out, param{name: n.Name, typ: f.Type})
		}
	}
	return out
}

func paramIndex(ps []param, name string) int {
	if name == "" {
		return -1
	}
	for i, p := range ps {
		if p.name == name {
			return i
		}
	}
	return -1
}

// resolveWrapper checks the wrapper shape and its target. See resolveAlias.
func (ep *exportPlan) resolveWrapper(d *declInfo, fd *ast.FuncDecl) (*resolution, string) {
	if fd.Type.TypeParams != nil {
		return nil, "a generic wrapper"
	}
	if fd.Body == nil {
		return nil, "a func without a body"
	}
	params := paramList(fd.Type.Params)
	for _, p := range params {
		if p.name == "" || p.name == "_" {
			return nil, "a wrapper with an unnamed or blank parameter"
		}
	}
	h, err := helperReceiver(fd)
	if err != nil {
		return nil, err.Error()
	}
	stmts := fd.Body.List
	if h != "" {
		// helperReceiver accepts the Helper() call anywhere at top level; a
		// wrapper must have it first.
		if len(stmts) == 0 || !isHelperStmt(stmts[0], h) {
			return nil, "the wrapper's Helper() call is not its first statement"
		}
		stmts = stmts[1:]
	}
	if len(stmts) != 1 {
		return nil, "the wrapper body is not a single forwarding call (an extra statement)"
	}
	var call *ast.CallExpr
	hasResults := fd.Type.Results != nil && len(fd.Type.Results.List) > 0
	switch s := stmts[0].(type) {
	case *ast.ReturnStmt:
		if !hasResults || len(s.Results) != 1 {
			return nil, "the wrapper does not return exactly the forwarded call"
		}
		call, _ = s.Results[0].(*ast.CallExpr)
	case *ast.ExprStmt:
		if hasResults {
			return nil, "the wrapper has results but does not return the call"
		}
		call, _ = s.X.(*ast.CallExpr)
	}
	if call == nil {
		return nil, "the wrapper body is not a single forwarding call"
	}
	qual, name, ok := qualified(call.Fun)
	if !ok {
		return nil, "the wrapper does not call pkg.F"
	}
	if len(call.Args) != len(params) {
		return nil, "the wrapper does not forward exactly its parameters"
	}
	for i, a := range call.Args {
		id, ok := a.(*ast.Ident)
		if !ok || id.Name != params[i].name {
			return nil, "the wrapper does not forward exactly its parameters, in order"
		}
	}
	_, variadic := lastType(params).(*ast.Ellipsis)
	if variadic != call.Ellipsis.IsValid() {
		return nil, "the wrapper does not forward its variadic parameter with ..."
	}
	spec, err := fileImport(d.file, qual)
	if err != nil {
		return nil, err.Error()
	}
	r := &resolution{kind: aliasFunc, file: d.file.name, name: name}
	if err := ep.fillTarget(r, spec, qual); err != nil {
		return nil, err.Error()
	}
	tp, err := ep.loadLocated(r.path)
	if err != nil {
		return nil, "target not checkable: " + err.Error()
	}
	td, why := funcDecl(tp, name)
	if td == nil {
		return nil, "target " + r.path + "." + name + ": " + why
	}
	tfd := td.node.(*ast.FuncDecl)
	if why := ep.sameSignature(d.file, fd.Type, td.file, tfd.Type, tp, r.path); why != "" {
		return nil, "target " + r.path + "." + name + " " + why
	}
	th, err := helperReceiver(tfd)
	if err != nil {
		return nil, "target: " + err.Error()
	}
	if wi, ti := paramIndex(params, h), paramIndex(paramList(tfd.Type.Params), th); wi != ti {
		switch {
		case h != "" && th == "":
			return nil, "the wrapper calls " + h + ".Helper() but the target does not call Helper()"
		case h == "" && th != "":
			return nil, "the target calls Helper() but the wrapper does not, so failure attribution would change"
		default:
			return nil, "the wrapper and the target call Helper() on different parameters"
		}
	}
	if why := ep.hazardOf(tp, name); why != "" {
		return nil, "target " + r.path + "." + name + " " + why
	}
	r.helps = h != ""
	return r, ""
}

func lastType(ps []param) ast.Expr {
	if len(ps) == 0 {
		return nil
	}
	return ps[len(ps)-1].typ
}

func isHelperStmt(s ast.Stmt, recv string) bool {
	es, ok := s.(*ast.ExprStmt)
	if !ok {
		return false
	}
	call, ok := es.X.(*ast.CallExpr)
	if !ok || !isHelperCall(call) {
		return false
	}
	id, ok := call.Fun.(*ast.SelectorExpr).X.(*ast.Ident)
	return ok && id.Name == recv
}

// funcDecl returns the single package-level func (not a method) name of q.
func funcDecl(q *pkgInfo, name string) (*declInfo, string) {
	ds := q.byKey[name]
	if len(ds) != 1 {
		return nil, fmt.Sprintf("declared %d times in non-test files, want exactly once", len(ds))
	}
	if _, ok := ds[0].node.(*ast.FuncDecl); !ok || ds[0].recv != "" {
		return nil, "not a package-level func"
	}
	return ds[0], ""
}

// sameSignature compares two func types after normalising every type to
// fully qualified spelling: a's names are resolved through ep (aliases of
// the source package), b's through package q at import path qp. Parameter
// names do not count. It returns "" or the difference.
func (ep *exportPlan) sameSignature(af *srcFile, a *ast.FuncType, bf *srcFile, b *ast.FuncType, q *pkgInfo, qp string) string {
	an := func(e ast.Expr) (string, error) { return ep.normType(e, af, ep.p, "") }
	bn := func(e ast.Expr) (string, error) { return ep.normType(e, bf, q, qp) }
	as, err := sigString(a, an)
	if err != nil {
		return "signature not comparable: " + err.Error()
	}
	bs, err := sigString(b, bn)
	if err != nil {
		return "signature not comparable: " + err.Error()
	}
	if as != bs {
		return fmt.Sprintf("has a different signature: %s, want %s", bs, as)
	}
	return ""
}

func sigString(ft *ast.FuncType, norm func(ast.Expr) (string, error)) (string, error) {
	if ft.TypeParams != nil {
		return "", fmt.Errorf("type parameters")
	}
	list := func(fl *ast.FieldList) (string, error) {
		var parts []string
		for _, p := range paramList(fl) {
			s, err := norm(p.typ)
			if err != nil {
				return "", err
			}
			parts = append(parts, s)
		}
		return "(" + strings.Join(parts, ", ") + ")", nil
	}
	ps, err := list(ft.Params)
	if err != nil {
		return "", err
	}
	rs, err := list(ft.Results)
	if err != nil {
		return "", err
	}
	return "func" + ps + " " + rs, nil
}

// normType spells a type expression of file f in package q fully
// qualified. A package-level name of q is spelled qp.Name when qp is set
// (the target side). On the source side (qp == ""), a package-level name
// must be a resolvable type alias and is spelled as its target; any other
// package-level name is not comparable. Names q does not declare are
// predeclared (int, string, error, any) and stay as they are.
func (ep *exportPlan) normType(e ast.Expr, f *srcFile, q *pkgInfo, qp string) (string, error) {
	rec := func(x ast.Expr) (string, error) { return ep.normType(x, f, q, qp) }
	switch t := e.(type) {
	case *ast.Ident:
		ds := q.byKey[t.Name]
		if len(ds) == 0 {
			return t.Name, nil
		}
		if len(ds) != 1 || !isType(ds[0]) {
			return "", fmt.Errorf("%s is not a single type declaration", t.Name)
		}
		if qp != "" {
			return qp + "." + t.Name, nil
		}
		r, why := ep.resolveAlias(ds[0])
		if r == nil || r.kind != aliasType {
			if why == "" {
				why = "not in a generated alias file"
			}
			return "", fmt.Errorf("%s is a type of the source package (%s)", t.Name, why)
		}
		return r.path + "." + r.name, nil
	case *ast.SelectorExpr:
		qual, name, ok := qualified(t)
		if !ok {
			return "", fmt.Errorf("unsupported selector type")
		}
		spec, err := fileImport(f, qual)
		if err != nil {
			return "", err
		}
		ip, err := strconv.Unquote(spec.Path.Value)
		if err != nil {
			return "", err
		}
		return ip + "." + name, nil
	case *ast.ParenExpr:
		return rec(t.X)
	case *ast.StarExpr:
		s, err := rec(t.X)
		return "*" + s, err
	case *ast.Ellipsis:
		s, err := rec(t.Elt)
		return "..." + s, err
	case *ast.ArrayType:
		s, err := rec(t.Elt)
		if err != nil {
			return "", err
		}
		if t.Len == nil {
			return "[]" + s, nil
		}
		bl, ok := t.Len.(*ast.BasicLit)
		if !ok {
			return "", fmt.Errorf("array length is not a literal")
		}
		return "[" + bl.Value + "]" + s, nil
	case *ast.MapType:
		k, err := rec(t.Key)
		if err != nil {
			return "", err
		}
		v, err := rec(t.Value)
		return "map[" + k + "]" + v, err
	case *ast.ChanType:
		s, err := rec(t.Value)
		switch t.Dir {
		case ast.SEND:
			return "chan<- " + s, err
		case ast.RECV:
			return "<-chan " + s, err
		}
		return "chan " + s, err
	case *ast.FuncType:
		return sigString(t, rec)
	case *ast.InterfaceType:
		if t.Methods == nil || len(t.Methods.List) == 0 {
			return "interface{}", nil
		}
	}
	return "", fmt.Errorf("unsupported type expression %T", e)
}

// mapping is an explicit map-to-existing entry: references in moved code to
// the staying func from are rewritten to the existing func to of the export
// target package. Nothing moves and the staying declaration is left as is.
type mapping struct {
	from, to string
	uses     int // references rewritten in moved code
}

// checkMapping verifies that from (a staying func of the source package) and
// to (an existing func of the export target package, before the export) are
// behaviour-identical: the same signature after resolving aliases, the same
// parameter names, the same Helper() shape, and token-identical bodies that
// reference no package-level declaration of either package.
func (ep *exportPlan) checkMapping(from, to string) error {
	bad := func(format string, a ...any) error {
		return fmt.Errorf("map %s=%s: "+format, append([]any{from, to}, a...)...)
	}
	ds := ep.p.byKey[from]
	if len(ds) != 1 {
		return bad("%s is declared %d times, want exactly once", from, len(ds))
	}
	fd, ok := ds[0].node.(*ast.FuncDecl)
	if !ok || ds[0].recv != "" || fd.Body == nil {
		return bad("only package-level funcs with a body can be mapped")
	}
	if ep.selected[ds[0]] {
		return bad("%s is also requested to move", from)
	}
	tp, err := ep.loadLocated(ep.importPath)
	if err != nil {
		return bad("%v", err)
	}
	td, why := funcDecl(tp, to)
	if td == nil {
		return bad("target %s.%s: %s", ep.importPath, to, why)
	}
	tfd := td.node.(*ast.FuncDecl)
	if why := ep.sameSignature(ds[0].file, fd.Type, td.file, tfd.Type, tp, ep.importPath); why != "" {
		return bad("target %s", why)
	}
	an, bn := paramList(fd.Type.Params), paramList(tfd.Type.Params)
	for i := range an {
		if an[i].name != bn[i].name {
			return bad("parameter %d is %q in %s but %q in %s; bodies are compared verbatim", i, an[i].name, from, bn[i].name, to)
		}
	}
	ar, br := paramList(fd.Type.Results), paramList(tfd.Type.Results)
	for i := range ar {
		if ar[i].name != br[i].name {
			return bad("result %d is %q in %s but %q in %s; bodies are compared verbatim", i, ar[i].name, from, br[i].name, to)
		}
	}
	ah, err := helperReceiver(fd)
	if err != nil {
		return bad("%v", err)
	}
	bh, err := helperReceiver(tfd)
	if err != nil {
		return bad("target: %v", err)
	}
	if ah != bh {
		return bad("Helper() calls differ (%q vs %q)", ah, bh)
	}
	if why := hazardOfOne(ep.p, from); why != "" {
		return bad("%s %s", from, why)
	}
	if why := ep.hazardOf(tp, to); why != "" {
		return bad("%s %s", to, why)
	}
	if refs := bodyRefs(ep.p, ds[0].file, fd.Body); len(refs) > 0 {
		return bad("%s's body uses package-level %s; only self-contained bodies are compared", from, strings.Join(refs, ", "))
	}
	if refs := bodyRefs(tp, td.file, tfd.Body); len(refs) > 0 {
		return bad("%s's body uses package-level %s; only self-contained bodies are compared", to, strings.Join(refs, ", "))
	}
	a := srcText(ep.p, ds[0].file, fd.Body.Pos(), fd.Body.End())
	b := srcText(tp, td.file, tfd.Body.Pos(), tfd.Body.End())
	if diff := codeDiff(a, b); diff != "" {
		return bad("bodies differ: %s", diff)
	}
	return nil
}

// bodyRefs lists the package-level names of q that body (in file f) uses.
func bodyRefs(q *pkgInfo, f *srcFile, body *ast.BlockStmt) []string {
	top := topLevelObjs(f.ast)
	seen := map[string]bool{}
	var out []string
	var visit func(n ast.Node) bool
	visit = func(n ast.Node) bool {
		switch x := n.(type) {
		case *ast.SelectorExpr:
			ast.Inspect(x.X, visit)
			return false
		case *ast.Ident:
			if x.Obj != nil && !top[x.Obj] {
				return true
			}
			if _, ok := q.byKey[x.Name]; ok && !seen[x.Name] {
				seen[x.Name] = true
				out = append(out, x.Name)
			}
		}
		return true
	}
	ast.Inspect(body, visit)
	return out
}

// codeDiff compares two snippets token by token, comments ignored.
func codeDiff(a, b string) string {
	at, err := scanTokens(a)
	if err != nil {
		return err.Error()
	}
	bt, err := scanTokens(b)
	if err != nil {
		return err.Error()
	}
	at, bt = elideClosingSemis(dropAllComments(at)), elideClosingSemis(dropAllComments(bt))
	if len(at) != len(bt) {
		return fmt.Sprintf("%d tokens vs %d", len(at), len(bt))
	}
	for i := range at {
		if at[i] != bt[i] {
			return fmt.Sprintf("token %d: %s %q vs %s %q", i, at[i].t, at[i].lit, bt[i].t, bt[i].lit)
		}
	}
	return ""
}

func dropAllComments(ts []tok) []tok {
	var out []tok
	for _, t := range ts {
		if t.t != token.COMMENT {
			out = append(out, t)
		}
	}
	return out
}

// replacement returns how moved code spells a resolved or mapped staying
// name in the target package.
func (ep *exportPlan) replacement(name string) (string, bool) {
	if m := ep.mappings[name]; m != nil {
		return m.to, true
	}
	if r := ep.resolved[name]; r != nil {
		return r.text(), true
	}
	return "", false
}

// checkSpellings makes sure each new spelling means its target inside the
// moved code: no local of a moved declaration has the name of a new
// qualifier or bare target name, no moved declaration is exported under
// that name, and a qualifier is not also an import of a moved declaration's
// file for another path.
func (ep *exportPlan) checkSpellings() error {
	names := map[string]string{} // spelled name -> what it must mean
	for _, k := range sortedKeys(ep.resolved) {
		r := ep.resolved[k]
		if r.same {
			names[r.name] = ep.importPath + "." + r.name
		} else {
			names[r.qual] = "package " + r.path
		}
	}
	for _, k := range sortedKeys(ep.mappings) {
		names[ep.mappings[k].to] = ep.importPath + "." + ep.mappings[k].to
	}
	if len(names) == 0 {
		return nil
	}
	for _, d := range ep.order {
		if d.recv == "" {
			n := d.key
			if e := ep.exported[d.key]; e != "" {
				n = e
			}
			if want, ok := names[n]; ok {
				return fmt.Errorf("%s is moved as %s, which moved code would also use for %s", d.key, n, want)
			}
		}
		top := topLevelObjs(d.file.ast)
		var err error
		ast.Inspect(d.node, func(n ast.Node) bool {
			id, ok := n.(*ast.Ident)
			if !ok || err != nil || id.Obj == nil || top[id.Obj] {
				return err == nil
			}
			if want, ok := names[id.Name]; ok {
				err = fmt.Errorf("%s has a local %s, which would shadow %s", d.key, id.Name, want)
			}
			return err == nil
		})
		if err != nil {
			return err
		}
		for _, s := range d.file.ast.Imports {
			n := importName(s)
			want, ok := names[n]
			if !ok {
				continue
			}
			ip, _ := strconv.Unquote(s.Path.Value)
			if want != "package "+ip {
				return fmt.Errorf("%s: import %s binds %s, which moved code would also use for %s", d.file.name, s.Path.Value, n, want)
			}
		}
	}
	return nil
}

// checkImportNames refuses a target file whose imports bind one name to two
// paths.
func checkImportNames(file string, imports map[importKey]bool) error {
	byName := map[string]string{}
	for k := range imports {
		ip, err := strconv.Unquote(k.path)
		if err != nil {
			return err
		}
		n := k.name
		if n == "" {
			n = importName(&ast.ImportSpec{Path: &ast.BasicLit{Kind: token.STRING, Value: k.path}})
		}
		if o, ok := byName[n]; ok && o != ip {
			return fmt.Errorf("target file %s: import name %s would bind both %s and %s", file, n, o, ip)
		}
		byName[n] = ip
	}
	return nil
}

// hazardOf explains why calling the func key of q through a wrapper, or in
// place of another func, would change behaviour, or returns "" (after
// hack/pkgmove's wrapperHazard, on syntax only):
//   - it calls recover() directly (outside a func literal): under
//     `defer w(t)`, recover only works when called directly by the deferred
//     func, so resolving the wrapper would let it swallow a panic;
//   - it, or a func or package-level var of q it calls or references by name
//     (a var's initializer is walked like a body, and a var inherits the
//     hazard of every node that assigns it directly (the whole var, an
//     element or a field), takes its address or ranges into it; build-tag
//     variants of a name all count), or a method of q it calls
//     by name (whatever the receiver), selects a frame by depth:
//     runtime.Caller or runtime.Callers (called or referenced as a value),
//     log.Output, or a call of an Output method on any receiver (without
//     type information (*log.Logger).Output cannot be told apart): a wrapper
//     frame shifts which frame is selected.
//
// A stack dump is not a hazard: debug.Stack(), runtime.Stack (one goroutine
// or all) and pprof.Lookup only produce diagnostic text, in which a wrapper
// adds a frame; they select nothing by depth. export lists them as WARN notes
// (collectNotes). A non-call x.Output is not counted either: syntax cannot
// tell a stored Logger.Output method value from a field read such as
// result.Output, which pkg/hub has. Helper() is not a hazard here:
// resolveWrapper, checkMapping and the generated wrappers mirror the
// Helper() shape.
//
// Propagation runs only through the declarations in scope, as hack/pkgmove's
// wrapperHazard runs only through moved functions: for a resolved wrapper's
// target, the whole target package; for export's own wrappers, the moved set
// (hazardOfMoved); for a mapped staying func, that func alone (its body uses
// no package-level name, by rule). A call into a declaration out of scope is
// not followed, so a hazard reached only by dynamic dispatch through an
// interface into a staying type is not seen (the same gap as pkgmove's).
// Calls into other packages are not followed either: a callee in another
// package that selects a frame above its own caller (a logger that skips
// frames with runtime.Callers(2), such as pkg/hub/auditevent's SlogSink.Emit)
// is not seen. A var inherits the hazard of a node only through a direct write
// (the whole var, an element, slice or field of it, also through a
// dereference, parentheses or a type assertion, a range target, or &v); a
// write that reaches the var some other way (through a local copy of a map,
// slice, pointer or channel var, a setter method, a channel send, a call
// argument, or a call, conversion or composite-literal root (get().f,
// (*T)(p).f, []*T{p}[0].f = ...)) is not followed. These gaps can miss a real
// hazard; they are documented limits, as hack/pkgmove's wrapperHazard has
// comparable ones.
func (ep *exportPlan) hazardOf(q *pkgInfo, key string) string {
	if ep.hazards == nil {
		ep.hazards = map[*pkgInfo]map[string]string{}
	}
	h, ok := ep.hazards[q]
	if !ok {
		h = hazards(q, nil)
		ep.hazards[q] = h
	}
	return h[key]
}

// hazardOfMoved is hazardOf over the source package with the moved set as
// the scope.
func (ep *exportPlan) hazardOfMoved(key string) string {
	if ep.movedHazards == nil {
		ep.movedHazards = hazards(ep.p, func(d *declInfo) bool { return ep.selected[d] })
	}
	return ep.movedHazards[key]
}

// hazardOfOne is hazardOf for one declaration of q alone, with no
// propagation.
func hazardOfOne(q *pkgInfo, key string) string {
	return hazards(q, func(d *declInfo) bool { return d.key == key })[key]
}

// hazards computes the hazard of every func and method of q in scope (all
// of q when scope is nil).
func hazards(q *pkgInfo, scope func(*declInfo) bool) map[string]string {
	in := func(d *declInfo) bool { return scope == nil || scope(d) }
	methods := map[string][]string{} // method name -> method keys in scope
	for _, d := range q.decls {
		if d.recv != "" && in(d) {
			m := d.key[len(d.recv)+1:]
			methods[m] = append(methods[m], d.key)
		}
	}
	// node reports whether d takes part: an in-scope func with a body, or an
	// in-scope package-level var (its initializer may hold a func literal or
	// a func value, such as var c = runtime.Caller, that a moved func calls).
	node := func(d *declInfo) bool {
		if !in(d) {
			return false
		}
		switch n := d.node.(type) {
		case *ast.FuncDecl:
			return n.Body != nil
		case *ast.GenDecl:
			return n.Tok == token.VAR && valueSpec(n, d.key) != nil
		}
		return false
	}
	direct := map[string]string{}
	stack := map[string]string{}
	calls := map[string][]string{}
	var nodes []string
	for _, d := range q.decls {
		if !node(d) {
			continue
		}
		var bodies []ast.Node
		fd, isFunc := d.node.(*ast.FuncDecl)
		if isFunc {
			bodies = []ast.Node{fd.Body}
		} else {
			for _, v := range valueSpec(d.node.(*ast.GenDecl), d.key).Values {
				bodies = append(bodies, v)
			}
		}
		key := d.key
		nodes = append(nodes, key)
		setStack := func(why string) {
			if stack[key] == "" {
				stack[key] = why
			}
		}
		top := topLevelObjs(d.file.ast)
		imports := map[string]string{}
		for _, s := range d.file.ast.Imports {
			ip, _ := strconv.Unquote(s.Path.Value)
			n := importName(s)
			if n == "." && (ip == "runtime" || ip == "log") {
				// Caller(1) or Output(2, s) would be bare identifiers.
				// (runtime/debug has only stack dumps, which select no frame.)
				setStack("is in a file that dot-imports " + ip + " (its calls cannot be told apart, so it is treated as inspecting its stack)")
			}
			imports[n] = ip
		}
		if isFunc {
			ast.Inspect(fd.Body, func(n ast.Node) bool {
				switch x := n.(type) {
				case *ast.FuncLit:
					return false
				case *ast.CallExpr:
					if id, ok := ast.Unparen(x.Fun).(*ast.Ident); ok && id.Name == "recover" && id.Obj == nil && len(q.byKey["recover"]) == 0 && direct[key] == "" {
						direct[key] = "calls recover() directly (resolving a wrapper around it would let recover() stop a panic under defer)"
					}
				}
				return true
			})
		}
		// Stack inspection counts anywhere in the body or initializer, func
		// literals included, and for references as well as calls
		// (f := runtime.Caller; use(runtime.Callers); a same-package func or
		// var used as a value).
		called := map[*ast.SelectorExpr]bool{} // selectors that are the Fun of a call
		// assignEdge: a package-level var of the scope written here (assigned,
		// range-assigned or address taken) inherits this node's hazard, since
		// its value may come from this node (var c ...; func set() { c =
		// runtime.Caller }). Over-approximates; fails closed.
		assignEdge := func(e ast.Expr) {
			for {
				switch v := e.(type) {
				case *ast.IndexExpr:
					e = v.X
					continue
				case *ast.SelectorExpr:
					e = v.X
					continue
				case *ast.StarExpr:
					e = v.X
					continue
				case *ast.ParenExpr:
					e = v.X
					continue
				case *ast.SliceExpr:
					e = v.X
					continue
				case *ast.TypeAssertExpr:
					e = v.X
					continue
				case *ast.Ident:
					if v.Obj != nil && !top[v.Obj] {
						return // a local
					}
					// Stop only at a var variant: a func variant of the same name
					// (build tags) must not hide a var variant.
					for _, dd := range q.byKey[v.Name] {
						if dd.recv == "" && node(dd) {
							if _, isVar := dd.node.(*ast.GenDecl); isVar {
								if v.Name != key {
									calls[v.Name] = append(calls[v.Name], key)
								}
								break
							}
						}
					}
				}
				return
			}
		}
		for _, body := range bodies {
			ast.Inspect(body, func(n ast.Node) bool {
				switch x := n.(type) {
				case *ast.CallExpr:
					if se, ok := ast.Unparen(x.Fun).(*ast.SelectorExpr); ok {
						called[se] = true
					}
				case *ast.SelectorExpr:
					id, isIdent := x.X.(*ast.Ident)
					if isIdent && id.Obj == nil && imports[id.Name] != "" {
						switch imports[id.Name] + "." + x.Sel.Name {
						case "runtime.Caller", "runtime.Callers":
							setStack("inspects its call stack (runtime." + x.Sel.Name + "; a wrapper frame changes the caller)")
						case "log.Output":
							setStack("uses an Output call depth (log.Output; a wrapper frame changes the caller)")
						}
						return false // a qualified name of another package
					}
					if x.Sel.Name == "Output" && called[x] {
						setStack("uses an Output call depth (an Output method call, e.g. a Logger's; a wrapper frame changes the caller)")
					}
					// A called method of q, followed by name (receiver types are
					// unknown). A non-call x.m is not followed: syntax cannot tell a
					// method value from a field read such as user.ID, whose type may
					// be another package's.
					if called[x] {
						calls[key] = append(calls[key], methods[x.Sel.Name]...)
					}
				case *ast.Ident:
					// Every same-name non-method node (build-tag variants of a
					// func or var in several files count; any of them may run).
					if x.Obj == nil || top[x.Obj] {
						for _, dd := range q.byKey[x.Name] {
							if dd.recv == "" && node(dd) {
								calls[key] = append(calls[key], x.Name)
								break
							}
						}
					}
				case *ast.AssignStmt:
					for _, l := range x.Lhs {
						assignEdge(l)
					}
				case *ast.RangeStmt:
					if x.Key != nil {
						assignEdge(x.Key)
					}
					if x.Value != nil {
						assignEdge(x.Value)
					}
				case *ast.UnaryExpr:
					if x.Op == token.AND {
						assignEdge(x.X)
					}
				}
				return true
			})
		}
	}
	// Stack inspection propagates to the funcs and vars of the scope that
	// reach it (to a fixpoint, so cycles terminate); recover does not.
	for changed := true; changed; {
		changed = false
		for _, f := range nodes {
			if stack[f] != "" {
				continue
			}
			for _, g := range calls[f] {
				if why := stack[g]; why != "" && g != f {
					stack[f] = "calls " + g + ", which " + why
					changed = true
					break
				}
			}
		}
	}
	out := map[string]string{}
	for _, f := range nodes {
		if why := direct[f]; why != "" {
			out[f] = why
		} else if why := stack[f]; why != "" {
			out[f] = why
		}
	}
	return out
}
