func TestVerifyExportCatchesResolutionEdits(t *testing.T) {
	edit := func(rel, old, new string) func(dir string) {
		return func(dir string) {
			p := filepath.Join(dir, filepath.FromSlash(rel))
			b, err := os.ReadFile(p)
			if err != nil || !bytes.Contains(b, []byte(old)) {
				panic("tamper target missing: " + rel + ": " + old)
			}
			_ = os.WriteFile(p, bytes.Replace(b, []byte(old), []byte(new), 1), 0o644)
		}
	}
	type tc struct {
		tamper func(dir string)
		want   string // the check that must fire (a line of the report)
	}
	for name, c := range map[string]tc{
		"resolved const respelled": {edit("internal/hubtestutil/a.go", "principal.BoundaryKindHub", "principal.TokenBoundary"),
			"hubBoundary (a_helpers_test.go -> a.go): token"},
		"resolved wrapper respelled": {edit("internal/hubtestutil/a.go", "id := TID(name)", "id := Pair(name)"),
			"seed (a_helpers_test.go -> a.go): token"},
		"mapped call respelled": {edit("internal/hubtestutil/a.go", `StrPtr("x")`, `IntPtr("x")`),
			"usesPtr (a_helpers_test.go -> a.go): token"},
		"pre-existing target changed": {edit("internal/hubtestutil/id.go", `"id-"`, `"ID-"`),
			"pre-existing target file id.go changed or missing"},
		"pre-existing test changed": {edit("internal/hubtestutil/untouched_test.go", "package hubtestutil\n", "package hubtestutil\n\n// x\n"),
			"pre-existing target file untouched_test.go changed or missing"},
		"mapped func changed": {edit("a_helpers_test.go", "func pvStrPtr(s string) *string { return &s }", "func pvStrPtr(s string) *string { s += \"!\"; return &s }"),
			"pvStrPtr (a_helpers_test.go): token"},
		// Baseline-aware target check: after = before + exactly the moved set.
		"stray decl appended to the generated file": {edit("internal/hubtestutil/a.go", "func UsesPtr()", "func Stray() {}\n\nfunc UsesPtr()"),
			"target declaration Stray (a.go) has no moved origin"},
		"stray decl in an extra target file": {func(dir string) {
			_ = os.WriteFile(filepath.Join(dir, "internal", "hubtestutil", "extra.go"), []byte(hdr+"package hubtestutil\n\nfunc Stray() {}\n"), 0o644)
		}, "target declaration Stray (extra.go) has no moved origin"},
		"pre-existing decl deleted": {edit("internal/hubtestutil/id.go", "func IntPtr(i int) *int { return &i }\n", ""),
			"pre-existing target file id.go changed or missing"},
		"pre-existing file deleted": {func(dir string) {
			_ = os.Remove(filepath.Join(dir, "internal", "hubtestutil", "dot.go"))
		}, "pre-existing target file dot.go changed or missing"},
	} {
		t.Run(name, func(t *testing.T) {
			dir := writeTree(t, rFiles(map[string]string{"a_helpers_test.go": rHelpers, "user_test.go": rUser}))
			before := copyTree(t, dir)
			ep, err := rPlan(t, dir, rSpec())
			if err != nil {
				t.Fatal(err)
			}
			if err := ep.write(filepath.Join(dir, "internal", "hubtestutil")); err != nil {
				t.Fatal(err)
			}
			c.tamper(dir)
			r, err := verifyExport(mustLoad(t, before), mustLoad(t, dir), filepath.Join(dir, "internal", "hubtestutil"), rTarget, rSrcImport, rSpec(), rAlias)
			if err != nil {
				t.Fatal(err)
			}
			var out bytes.Buffer
			r.write(&out)
			if r.ok() {
				t.Fatalf("verify-export passed a tampered tree:\n%s", out.String())
			}
			if !strings.Contains(out.String(), c.want) {
				t.Fatalf("verify-export report lacks the expected check (%s):\n%s", c.want, out.String())
			}
		})
	}
}

