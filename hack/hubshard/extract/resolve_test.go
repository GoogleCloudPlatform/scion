func TestExportResolvesAliasesAndMaps(t *testing.T) {
	dir := writeTree(t, rFiles(map[string]string{"a_helpers_test.go": rHelpers, "user_test.go": rUser}))
	before := copyTree(t, dir)
	ep, err := rPlan(t, dir, rSpec())
	if err != nil {
		t.Fatal(err)
	}
	var rep bytes.Buffer
	ep.report(&rep)
	resolved := map[string]string{}
	for _, l := range strings.Split(rep.String(), "\n") {
		if f := strings.Fields(l); len(f) >= 3 && f[1] == "->" {
			resolved[f[0]] = f[2]
		}
	}
	for k, v := range map[string]string{
		"TokenBoundary":   "principal.TokenBoundary",
		"BoundaryKindHub": "principal.BoundaryKindHub",
		"tid":             "TID",
		"mustUUID":        "MustUUID",
	} {
		if resolved[k] != v {
			t.Errorf("report resolves %s to %q, want %q:\n%s", k, resolved[k], v, rep.String())
		}
	}
	for _, want := range []string{
		"(both call Helper() on the same parameter)",
		"map pvStrPtr -> hubtestutil.StrPtr: equivalent",
		"1 reference(s) in moved code rewritten",
	} {
		if !strings.Contains(rep.String(), want) {
			t.Errorf("report lacks %q:\n%s", want, rep.String())
		}
	}
	if err := ep.write(filepath.Join(dir, "internal", "hubtestutil")); err != nil {
		t.Fatal(err)
	}
	got := readFile(t, filepath.Join(dir, "internal", "hubtestutil", "a.go"))
	for _, want := range []string{
		`"example.com/m/hub/internal/principal"`,
		// The longer spelling makes gofmt expand the one-line body.
		"func HubBoundary() principal.TokenBoundary {\n\treturn principal.TokenBoundary{Kind: principal.BoundaryKindHub}\n}",
		"\tid := TID(name)\n\tMustUUID(t, id)\n",
		`func UsesPtr() *string { return StrPtr("x") }`,
		"// seed makes an ID.", // doc comments stay verbatim
	} {
		if !strings.Contains(got, want) {
			t.Errorf("target lacks %q:\n%s", want, got)
		}
	}
	if strings.Contains(got, "hubtestutil.") {
		t.Errorf("the target must not qualify its own names:\n%s", got)
	}
	if strings.Contains(got, "pvStrPtr") {
		t.Errorf("a mapped name must not move:\n%s", got)
	}
	// The staying mapped func and the staying alias files are untouched.
	for _, f := range []string{"zz_alias_principal.go", "zz_alias_hubtestutil_test.go"} {
		if readFile(t, filepath.Join(dir, f)) != readFile(t, filepath.Join(before, f)) {
			t.Errorf("%s changed", f)
		}
	}
	if s := readFile(t, filepath.Join(dir, rAlias)); strings.Contains(s, "pvStrPtr") {
		t.Errorf("a mapped func gets no alias:\n%s", s)
	}
	if s := readFile(t, filepath.Join(dir, "a_helpers_test.go")); !strings.Contains(s, "func pvStrPtr(s string) *string { return &s }") {
		t.Errorf("the mapped func must stay as is:\n%s", s)
	}

	r, err := verifyExport(mustLoad(t, before), mustLoad(t, dir), filepath.Join(dir, "internal", "hubtestutil"), rTarget, rSrcImport, rSpec(), rAlias)
	if err != nil {
		t.Fatal(err)
	}
	var out bytes.Buffer
	r.write(&out)
	if !r.ok() {
		t.Fatalf("verify-export failed:\n%s", out.String())
	}
}

