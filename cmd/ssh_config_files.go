// File layout managed by scion ssh-config, one include file and one
// known-hosts file per hub:
//
//	~/.ssh/config            gains one "Include ~/.ssh/config.d/scion-*" line
//	~/.ssh/config.d/scion-<hub>
//	~/.scion/ssh/known_hosts-<hub>
const (
	sshIncludeArg         = "~/.ssh/config.d/scion-*"
	sshIncludeLine        = "Include " + sshIncludeArg
	sshIncludePrefix      = "scion-"
	sshKnownHostsPrefix   = "known_hosts-"
	sshHeaderEndpointKey  = "# scion-hub-endpoint: "
	sshHeaderLabelKey     = "# scion-hub-label: "
	sshHeaderGeneratedTag = "# Generated by scion ssh-config. The file is rewritten as a whole; manual edits are lost."
	sshTempPrefix         = ".scion-tmp-"
	sshDirMode            = 0o700
	sshFileMode           = 0o600
)

// sshPaths derives every path ssh-config touches from one home directory,
// so tests can point it at a temporary directory.
type sshPaths struct {
	home string
}

// The directories ssh-config creates, relative to the home directory
// (slash-separated, constant): ensureSSHDir takes these, never a path.
const (
	sshDirRel           = ".ssh"
	sshIncludeDirRel    = ".ssh/config.d"
	sshKnownHostsDirRel = ".scion/ssh"
)

func (p sshPaths) sshDir() string     { return filepath.Join(p.home, filepath.FromSlash(sshDirRel)) }
func (p sshPaths) userConfig() string { return filepath.Join(p.sshDir(), "config") }
func (p sshPaths) includeDir() string {
	return filepath.Join(p.home, filepath.FromSlash(sshIncludeDirRel))
}
func (p sshPaths) knownHostsDir() string {
	return filepath.Join(p.home, filepath.FromSlash(sshKnownHostsDirRel))
}

func (p sshPaths) includeFile(label string) string {
	return filepath.Join(p.includeDir(), sshIncludePrefix+label)
}

func (p sshPaths) knownHostsFile(label string) string {
	return filepath.Join(p.knownHostsDir(), sshKnownHostsPrefix+label)
}

// sshKnownHostsRef is the known-hosts path as written into a Host block. ssh
// expands the leading tilde itself.
func sshKnownHostsRef(label string) string {
	return "~/.scion/ssh/" + sshKnownHostsPrefix + label
}

// sshHostName returns the Host name for an agent. Slugs never contain a dot,
// so the name is unambiguous.
func sshHostName(label, projectSlug, agentSlug string) string {
	return "scion." + label + "." + projectSlug + "." + agentSlug
}

// sshEndpointURL parses a normalized hub endpoint for the hub label, which
// needs its host and port. Only http and https endpoints with a host, and
// without user info, query or fragment, are accepted.
func sshEndpointURL(endpoint string) (*url.URL, error) {
	if hasSpaceOrControl(endpoint) {
		return nil, fmt.Errorf("invalid hub endpoint %q: contains whitespace or control characters", config.RedactURL(endpoint))
	}
	u, err := url.Parse(endpoint)
	if err != nil {
		// The parse error quotes the URL; show it without user info.
		var ue *url.Error
		if errors.As(err, &ue) {
			ue.URL = config.RedactURL(ue.URL)
		}
		return nil, fmt.Errorf("invalid hub endpoint %q: %w", config.RedactURL(endpoint), err)
	}
	if u.Scheme != "http" && u.Scheme != "https" {
		return nil, fmt.Errorf("invalid hub endpoint %q: scheme must be http or https", config.RedactURL(endpoint))
	}
	if u.Hostname() == "" {
		return nil, fmt.Errorf("invalid hub endpoint %q: missing host", config.RedactURL(endpoint))
	}
	if u.User != nil || u.RawQuery != "" || u.ForceQuery || u.Fragment != "" {
		return nil, fmt.Errorf("invalid hub endpoint %q: user info, query and fragment are not allowed", config.RedactURL(endpoint))
	}
	if r, ok := sshEndpointUnsafeRune(endpoint, u); ok {
		return nil, fmt.Errorf("invalid hub endpoint %q: contains %q; a hub endpoint may contain only ASCII letters, digits and -._:/ (and [ ] around an IPv6 address)", config.RedactURL(endpoint), r)
	}
	return u, nil
}

// sshEndpointUnsafeRune returns the first character of endpoint outside the
// characters a hub endpoint is written with: ASCII letters, digits and
// -._:/, plus one [ ] pair when the host is an IPv6 literal. The endpoint is
// written into ProxyCommand lines and ssh options, so it is held to this
// set on every OS.
func sshEndpointUnsafeRune(endpoint string, u *url.URL) (rune, bool) {
	ipv6 := strings.HasPrefix(u.Host, "[") && strings.Count(endpoint, "[") == 1 && strings.Count(endpoint, "]") == 1
	for _, r := range endpoint {
		switch {
		case (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') || (r >= '0' && r <= '9') || strings.ContainsRune("-._:/", r):
		case ipv6 && (r == '[' || r == ']'):
		default:
			return r, true
		}
	}
	return 0, false
}

// sshHubLabelCandidates returns the preferred hub label and the fallback
// used when another hub already holds the preferred one. The preferred label
// is the first DNS label of the host; for an IP address or localhost it is
// the whole host, with the port when it is not the default. The fallback is
// the whole host and port. A port that is the scheme default (443 for https,
// 80 for http) is left out.
func sshHubLabelCandidates(u *url.URL) (preferred, fallback string) {
	host := u.Hostname()
	port := u.Port()
	if (u.Scheme == "https" && port == "443") || (u.Scheme == "http" && port == "80") {
		port = ""
	}
	full := host
	if port != "" {
		full = host + "-" + port
	}
	fallback = api.Slugify(full)
	if net.ParseIP(host) != nil || strings.EqualFold(host, "localhost") {
		preferred = fallback
	} else {
		first, _, _ := strings.Cut(host, ".")
		preferred = api.Slugify(first)
	}
	if preferred == "" {
		preferred = fallback
	}
	if fallback == "" {
		fallback = "hub"
		if preferred == "" {
			preferred = fallback
		}
	}
	return preferred, fallback
}

// sshIncludeFileInfo describes an existing scion include file.
type sshIncludeFileInfo struct {
	path     string
	label    string // a slug, or empty when neither header nor name gives one
	endpoint string // recorded endpoint; empty when the header has none
}

// parseSSHIncludeHeader reads the endpoint and label recorded in an include
// file header.
func parseSSHIncludeHeader(content string) (endpoint, label string) {
	sc := bufio.NewScanner(strings.NewReader(content))
	for sc.Scan() {
		line := sc.Text()
		if !strings.HasPrefix(line, "#") {
			if strings.TrimSpace(line) == "" {
				continue
			}
			break
		}
		if v, ok := strings.CutPrefix(line, sshHeaderEndpointKey); ok {
			endpoint = strings.TrimSpace(v)
		}
		if v, ok := strings.CutPrefix(line, sshHeaderLabelKey); ok {
			label = strings.TrimSpace(v)
		}
	}
	return endpoint, label
}

// listSSHIncludeFiles returns the scion include files in ~/.ssh/config.d,
// sorted by path. A missing directory yields no files.
func listSSHIncludeFiles(p sshPaths) ([]sshIncludeFileInfo, error) {
	entries, err := os.ReadDir(p.includeDir())
	if err != nil {
		if errors.Is(err, fs.ErrNotExist) {
			return nil, nil
		}
		return nil, err
	}
	var out []sshIncludeFileInfo
	for _, e := range entries {
		name := e.Name()
		if !strings.HasPrefix(name, sshIncludePrefix) || e.IsDir() {
			continue
		}
		path := filepath.Join(p.includeDir(), name)
		data, err := os.ReadFile(path)
		if err != nil {
			return nil, err
		}
		endpoint, label := parseSSHIncludeHeader(string(data))
		if !isSSHSlug(label) {
			// A recorded label that is not a slug is ignored; the file name
			// is used instead, and only if it is a slug.
			label = strings.TrimPrefix(name, sshIncludePrefix)
			if !isSSHSlug(label) {
				label = ""
			}
		}
		out = append(out, sshIncludeFileInfo{path: path, label: label, endpoint: endpoint})
	}
	sort.Slice(out, func(i, j int) bool { return out[i].path < out[j].path })
	return out, nil
}

// resolveSSHHubLabel returns the label for endpoint. A label recorded for the
// same endpoint is reused, so it never changes once written. Otherwise the
// preferred label is used unless another file holds it, then the fallback.
func resolveSSHHubLabel(endpoint string, u *url.URL, files []sshIncludeFileInfo) (string, error) {
	for _, f := range files {
		if f.endpoint == endpoint && f.label != "" {
			return f.label, nil
		}
	}
	taken := func(label string) bool {
		for _, f := range files {
			if (f.label != "" && f.label == label) || filepath.Base(f.path) == sshIncludePrefix+label {
				return true
			}
		}
		return false
	}
	preferred, fallback := sshHubLabelCandidates(u)
	if !taken(preferred) {
		return preferred, nil
	}
	if !taken(fallback) {
		return fallback, nil
	}
	return "", fmt.Errorf("hub label %q and %q are both used by other scion include files in %s", preferred, fallback, filepath.Dir(files[0].path))
}

// ~/.ssh is deliberately NOT a refuse-reparse tree. Dotfile managers
// (chezmoi, stow, yadm) symlink ~/.ssh or the files in it, so refusing
// links there would break legitimate setups. Instead links are followed
// and the trust decision is made on handles after following (the
// follow-then-verify rule, privatefs.ReplaceFollowing): the target's
// parent directory and an existing target must pass
// CheckNoForeignWriters; a foreign-owned target or a foreign-writable
// parent is refused; a target the user owns but left too open is replaced
// by a private temporary file through a handle rename; the old security
// descriptor is never copied, because a writable ssh config is code
// execution via ProxyCommand. The same writer and directory rule serve
// ~/.scion/ssh and ~/.scion/vscode, which ssh and VS Code read the same way.

// ensureSSHDir creates the directory rel below home, and any missing
// parents, private (mode 0700 on unix; an owner-only ACL on Windows).
// Existing directories are left as they are, and existing links on the way
// are followed, wherever they lead (a dotfile manager's ~/.ssh or a
// ~/.scion moved to another disk): see the note above.
//
// rel is one of the constant relative paths of sshPaths and vscodePaths
// (sshDirRel, sshIncludeDirRel, sshKnownHostsDirRel, vscodeDirRel,
// vscodeSettingsDirRel), never a caller-supplied path, so there is nothing
// to contain: Tree.MkdirAll opens every component relative to its
// parent's handle (no path-based open on this path) and validates each
// one (pathcanon.ValidName: no "..", no absolute or alias forms).
//
// There is deliberately no pathcanon.Within here. A location check would
// be a proxy: it resolves links, so it would refuse exactly the linked
// layouts FollowLinks exists for. The property it would stand in for
// (nobody else can change what ssh and VS Code will read) is enforced by
// the follow-then-verify rule on the resolved handles of every file
// written below these directories (writeFileAtomic,
// privatefs.ReplaceFollowing), and a failure of that rule is a returned
// error.
//
// Several rels are verified together before any is created
// (Tree.MkdirAllEach): a refused location leaves no side effect, not even
// a directory created for another rel of the same call.
//
// A followed link whose target sits in a directory another user can
// change is warned about on stderr (sshLinkWarning), not refused: that is
// an accepted residual (the follow-then-verify rule protects the target,
// not the path to it; see privatefs.TreeOptions.FollowLinks).
func ensureSSHDir(home string, rels ...string) error {
	t, err := privatefs.OpenTree(home, privatefs.TreeOptions{FollowLinks: true, Warn: sshLinkWarning})
	if err != nil {
		return err
	}
	defer func() { _ = t.Close() }()
	return t.MkdirAllEach(privatefs.ForMode(sshDirMode), rels...)
}

// preflightSSHWrites runs privatefs.CheckReplaceTarget (writeFileAtomic's
// checks, writing nothing) on every file an operation is about to write,
// so a file that would be refused is found before the first directory is
// created or the first file written. writeFileAtomic still checks each
// file itself; this is in addition, not instead. Callers list only the
// files they will write: a file the operation leaves alone is never
// refused.
func preflightSSHWrites(paths ...string) error {
	for _, path := range paths {
		if err := privatefs.CheckReplaceTarget(path); err != nil {
			return err
		}
	}
	return nil
}

// sshIncludeLineNeeded reports whether ~/.ssh/config lacks the scion
// Include line, i.e. whether ensureSSHIncludeLine will write it. A missing
// file needs it.
func sshIncludeLineNeeded(p sshPaths) (bool, error) {
	data, err := os.ReadFile(p.userConfig())
	if errors.Is(err, fs.ErrNotExist) {
		return true, nil
	}
	if err != nil {
		return false, err
	}
	return !hasSSHIncludeLine(string(data)), nil
}

// sshWarnOut receives sshLinkWarning's lines; tests replace it.
var sshWarnOut io.Writer = os.Stderr

var (
	sshWarnedMu sync.Mutex
	sshWarned   = map[string]bool{}
)

// sshLinkWarning prints a privatefs FollowLinks warning once per process
// (several ensureSSHDir calls in one command walk the same link).
func sshLinkWarning(msg string) {
	sshWarnedMu.Lock()
	defer sshWarnedMu.Unlock()
	if sshWarned[msg] {
		return
	}
	sshWarned[msg] = true
	_, _ = fmt.Fprintf(sshWarnOut, "scion: warning: %s\n", msg)
}

// writeFileAtomic replaces path with data through a temporary file in the
// same directory and a rename, so readers see the old or the new file and
// never a partial one. When path is a symlink, the file it points to is
// replaced and the link is kept (see the ~/.ssh note above). On unix an
// existing file keeps its mode and a new file gets newMode; on Windows the
// result is always private, a foreign-owned target or a foreign-writable
// directory is refused, and a hard-linked target is refused on both
// (privatefs.ReplaceFollowing).
func writeFileAtomic(path string, data []byte, newMode fs.FileMode) error {
	return privatefs.ReplaceFollowing(path, data, newMode, sshTempPrefix)
}

// hasSSHIncludeLine reports whether content already has the scion Include
// line before its first Host or Match block, where it applies globally.
func hasSSHIncludeLine(content string) bool {
	sc := bufio.NewScanner(strings.NewReader(content))
	for sc.Scan() {
		fields := strings.Fields(sc.Text())
		if len(fields) == 0 {
			continue
		}
		if strings.EqualFold(fields[0], "host") || strings.EqualFold(fields[0], "match") {
			return false
		}
		if strings.EqualFold(fields[0], "include") && len(fields) == 2 && fields[1] == sshIncludeArg {
			return true
		}
	}
	return false
}

// ensureSSHIncludeLine adds the scion Include line at the top of ~/.ssh/config
// once. It reports whether the file changed.
func ensureSSHIncludeLine(p sshPaths) (bool, error) {
	if err := ensureSSHDir(p.home, sshDirRel); err != nil {
		return false, err
	}
	data, err := os.ReadFile(p.userConfig())
	if err != nil && !errors.Is(err, fs.ErrNotExist) {
		return false, err
	}
	if err == nil && hasSSHIncludeLine(string(data)) {
		return false, nil
	}
	content := sshIncludeLine + "\n"
	if len(data) > 0 {
		content += "\n" + string(data)
	}
	if err := writeFileAtomic(p.userConfig(), []byte(content), sshFileMode); err != nil {
		return false, err
	}
	return true, nil
}

// parseKnownHosts maps each host alias in a known-hosts file to its key
// ("<type> <base64>"). Comments, blank lines and malformed lines are skipped.
func parseKnownHosts(content string) map[string]string {
	out := map[string]string{}
	sc := bufio.NewScanner(strings.NewReader(content))
	sc.Buffer(make([]byte, 64*1024), 1024*1024)
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		fields := strings.Fields(line)
		if len(fields) < 3 {
			continue
		}
		out[fields[0]] = fields[1] + " " + fields[2]
	}
	return out
}

// readKnownHosts reads and parses a known-hosts file; a missing file yields
// an empty map.
func readKnownHosts(path string) (map[string]string, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		if errors.Is(err, fs.ErrNotExist) {
			return map[string]string{}, nil
		}
		return nil, err
	}
	return parseKnownHosts(string(data)), nil
}

// renderKnownHosts writes one line per alias, sorted.
func renderKnownHosts(keys map[string]string) string {
	aliases := make([]string, 0, len(keys))
	for a := range keys {
		aliases = append(aliases, a)
	}
	sort.Strings(aliases)
	var b strings.Builder
	for _, a := range aliases {
		b.WriteString(a + " " + keys[a] + "\n")
	}
	return b.String()
}

// parseSSHHostBlocks splits an include file into its Host blocks, keyed by
// host name, each kept verbatim. Header lines before the first block are
// dropped.
func parseSSHHostBlocks(content string) map[string]string {
	out := map[string]string{}
	var name string
	var cur strings.Builder
	flush := func() {
		if name != "" {
			out[name] = strings.TrimRight(cur.String(), "\n") + "\n"
		}
		cur.Reset()
	}
	sc := bufio.NewScanner(strings.NewReader(content))
	sc.Buffer(make([]byte, 64*1024), 1024*1024)
	for sc.Scan() {
		line := sc.Text()
		fields := strings.Fields(line)
		if len(fields) >= 2 && strings.EqualFold(fields[0], "host") {
			flush()
			name = fields[1]
		}
		if name != "" {
			cur.WriteString(line + "\n")
		}
	}
	flush()
	return out
}

// renderSSHIncludeFile writes the header and the given blocks, sorted by
// host name.
func renderSSHIncludeFile(endpoint, label string, blocks map[string]string) string {
	names := make([]string, 0, len(blocks))
	for n := range blocks {
		names = append(names, n)
	}
	sort.Strings(names)
	var b strings.Builder
	b.WriteString(sshHeaderGeneratedTag + "\n")
	b.WriteString(sshHeaderEndpointKey + endpoint + "\n")
	b.WriteString(sshHeaderLabelKey + label + "\n")
	for _, n := range names {
		b.WriteString("\n")
		b.WriteString(blocks[n])
	}
	return b.String()
}

// sshQuoteForWindows reports whether ProxyCommand words are quoted for a
// Windows ssh client (sshCmdQuote) rather than for a POSIX shell. It is a
// variable so tests can exercise both forms. (From miller79/scion#189,
// where it was named sshQuoteForCmd.)
var sshQuoteForWindows = runtime.GOOS == "windows"

// sshShellQuote quotes s for the shell ssh runs a ProxyCommand with, and
// doubles '%' so ssh does not expand it as a token. Only the Windows form
// (sshCmdQuote) can return an error; the unix form quotes every word.
func sshShellQuote(s string) (string, error) {
	if sshQuoteForWindows {
		return sshCmdQuote(s)
	}
	s = strings.ReplaceAll(s, "%", "%%")
	safe := s != ""
	for _, r := range s {
		if !isSSHWordSafe(r) && r != '%' {
			safe = false
			break
		}
	}
	if safe {
		return s, nil
	}
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'", nil
}

// isSSHWordSafe reports whether r may appear in a ProxyCommand word on
// either form without quoting: ASCII letters and digits and @+=:,./_-.
func isSSHWordSafe(r rune) bool {
	return (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') || (r >= '0' && r <= '9') || strings.ContainsRune("@+=:,./_-", r)
}

// sshCmdQuote writes s as one word of a Windows ssh client's ProxyCommand.
// The two clients read that command differently:
//   - Win32-OpenSSH runs the expanded ProxyCommand without a shell: it
//     posix_spawnp's the command line (sshconnect.c ssh_proxy_connect,
//     FORK_NOT_SUPPORTED branch, PowerShell/openssh-portable latestw_all
//     274893f8), and CreateProcess splits it with the C runtime's rules, so
//     double quotes group a word with spaces.
//   - Git for Windows' ssh runs it with /bin/sh, which drops unquoted
//     backslashes and treats many characters specially, inside double
//     quotes too.
//
// No single quoting is read the same way by both, so the word is
// validated against an allowlist instead of being escaped. Backslashes
// become forward slashes, which both accept in a Windows path. After that
// a word may contain only:
//   - ASCII letters and digits and @+=:,./_- (left unquoted), and
//   - non-ASCII letters, digits and combining marks (an account name in
//     a path), except those that best-fit to ASCII punctuation
//     (isNonASCIIWordRune), and
//   - spaces and ( ) ~ [ ], in which case the whole word is
//     double-quoted: inside double quotes they are literal for sh and for
//     the C runtime's command-line parser (a "Program Files (x86)" or 8.3
//     "~" path, an IPv6 host).
//
// Any other character, including '%' (ssh expands % tokens in a
// ProxyCommand) and every character that sh or the C runtime's
// command-line parser treats specially inside double quotes, is an error
// that names the character; the caller names the word. (The allowlist replaces
// the quoting from miller79/scion#189; the name is kept from there.)
func sshCmdQuote(s string) (string, error) {
	s = strings.ReplaceAll(s, `\`, "/")
	if s == "" {
		return "", errors.New("is empty")
	}
	quote := false
	for _, r := range s {
		switch {
		case isSSHWordSafe(r):
		case strings.ContainsRune(" ()~[]", r):
			quote = true
		case isNonASCIIWordRune(r):
		default:
			return "", fmt.Errorf("contains %q, which a Windows ssh ProxyCommand cannot carry as written", r)
		}
	}
	if quote {
		return `"` + s + `"`, nil
	}
	return s, nil
}

// isNonASCIIWordRune reports whether r is a non-ASCII letter, digit or
// combining mark allowed in a Windows word (account names in paths,
// including decomposed ones). Refused, because Microsoft's WindowsBestFit
// tables (unicode.org MAPPINGS/VENDORS/MICSFT/WindowsBestFit, code pages
// 874, 932, 936, 949, 950 and 1250-1258) map them to ASCII punctuation
// under a best-fit conversion: every modifier letter (category Lm), and
// the letters and combining marks in sshBestFitPunct. Modifier symbols
// (Sk) and other punctuation and symbols are not letters, digits or
// marks, so they are refused too.
func isNonASCIIWordRune(r rune) bool {
	if r < utf8.RuneSelf || unicode.Is(unicode.Lm, r) || sshBestFitPunct[r] {
		return false
	}
	return unicode.IsLetter(r) || unicode.IsDigit(r) || unicode.IsMark(r)
}

// sshBestFitPunct lists the non-Lm letters and combining marks that the
// WindowsBestFit tables map to an ASCII character the allowlists refuse.
var sshBestFitPunct = map[rune]bool{
	'\u01C0': true, // LATIN LETTER DENTAL CLICK -> '|'
	'\u01C3': true, // LATIN LETTER RETROFLEX CLICK -> '!'
	'\u0300': true, // COMBINING GRAVE ACCENT -> '`'
	'\u0302': true, // COMBINING CIRCUMFLEX ACCENT -> '^'
	'\u0303': true, // COMBINING TILDE -> '~'
	'\u030E': true, // COMBINING DOUBLE VERTICAL LINE ABOVE -> '"'
}

// sshProxyWord is sshShellQuote for one named ProxyCommand word; the error
// names the word as shown (an endpoint is shown redacted).
func sshProxyWord(kind, shown, s string) (string, error) {
	q, err := sshShellQuote(s)
	if err != nil {
		return "", fmt.Errorf("%s %q %w", kind, shown, err)
	}
	return q, nil
}

// renderSSHHostBlock returns the Host block for one agent. exe must be an
// absolute path; the label, project and agent must be slugs and the endpoint
// must have no whitespace or control characters.
func renderSSHHostBlock(exe, endpoint, label, projectSlug, agentSlug string) (string, error) {
	return renderSSHHostBlockKnown(exe, endpoint, label, projectSlug, agentSlug, sshKnownHostsRef(label))
}

// renderSSHHostBlockKnown is renderSSHHostBlock with knownHostsRef as the
// UserKnownHostsFile line, for host files kept outside ~/.ssh/config.d.
func renderSSHHostBlockKnown(exe, endpoint, label, projectSlug, agentSlug, knownHostsRef string) (string, error) {
	return renderSSHHostBlockPinned(exe, endpoint, label, projectSlug, agentSlug, knownHostsRef, "")
}

// renderSSHHostBlockPinned is renderSSHHostBlockKnown with pinFile, when not
// empty, passed to scion tunnel as --known-hosts together with the block's
// HostKeyAlias as --host-key-alias, so its host-key hint reads the pin this
// block uses. pinFile must be an absolute path. ssh's own check is the same
// either way.
func renderSSHHostBlockPinned(exe, endpoint, label, projectSlug, agentSlug, knownHostsRef, pinFile string) (string, error) {
	if !filepath.IsAbs(exe) {
		return "", fmt.Errorf("scion executable path %q is not absolute", exe)
	}
	if hasControl(exe) {
		return "", fmt.Errorf("scion executable path %q contains control characters", exe)
	}
	if _, err := sshEndpointURL(endpoint); err != nil {
		return "", err
	}
	if err := checkSSHNameParts(label, projectSlug, agentSlug); err != nil {
		return "", err
	}
	if pinFile != "" && (!filepath.IsAbs(pinFile) || hasControl(pinFile)) {
		return "", fmt.Errorf("known-hosts path %q is not a clean absolute path", pinFile)
	}
	host := sshHostName(label, projectSlug, agentSlug)
	proxy, err := sshProxyCommand(exe, endpoint, projectSlug, agentSlug, pinFile, host)
	if err != nil {
		return "", err
	}
	var b strings.Builder
	b.WriteString("Host " + host + "\n")
	b.WriteString("  ProxyCommand " + proxy + "\n")
	b.WriteString("  HostKeyAlias " + host + "\n")
	b.WriteString("  UserKnownHostsFile " + knownHostsRef + "\n")
	b.WriteString("  StrictHostKeyChecking yes\n")
	return b.String(), nil
}

// sshProxyCommand returns the ProxyCommand that runs scion tunnel for an
// agent: exe tunnel --stdio --ssh --hub endpoint --project projectSlug
// [--known-hosts pinFile --host-key-alias host] agentSlug. Every word is
// checked (sshProxyWord), so a word the Windows form cannot carry is an
// error before anything is written.
func sshProxyCommand(exe, endpoint, projectSlug, agentSlug, pinFile, host string) (string, error) {
	type word struct{ kind, shown, value string }
	parts := []word{
		{"scion executable path", exe, exe}, {"", "", "tunnel"}, {"", "", "--stdio"}, {"", "", "--ssh"},
		{"", "", "--hub"}, {"hub endpoint", config.RedactURL(endpoint), endpoint},
		{"", "", "--project"}, {"project", projectSlug, projectSlug},
	}
	if pinFile != "" {
		parts = append(parts, word{"", "", "--known-hosts"}, word{"known-hosts path", pinFile, pinFile},
			word{"", "", "--host-key-alias"}, word{"host key alias", host, host})
	}
	parts = append(parts, word{"agent", agentSlug, agentSlug})
	words := make([]string, 0, len(parts))
	for _, w := range parts {
		if w.kind == "" {
			words = append(words, w.value)
			continue
		}
		q, err := sshProxyWord(w.kind, w.shown, w.value)
		if err != nil {
			return "", err
		}
		words = append(words, q)
	}
	return strings.Join(words, " "), nil
}

// isSSHSlug reports whether v is a non-empty slug, the only form allowed in
// Host names and file names.
func isSSHSlug(v string) bool {
	return v != "" && api.Slugify(v) == v
}

// checkSSHNameParts checks the parts of a Host name.
func checkSSHNameParts(label, projectSlug, agentSlug string) error {
	for _, part := range []struct{ kind, value string }{
		{"hub label", label}, {"project", projectSlug}, {"agent", agentSlug},
	} {
		if !isSSHSlug(part.value) {
			return fmt.Errorf("%s %q is not a slug", part.kind, part.value)
		}
	}
	return nil
}

func hasSpaceOrControl(s string) bool {
	return strings.IndexFunc(s, func(r rune) bool { return unicode.IsSpace(r) || unicode.IsControl(r) }) >= 0
}

func hasControl(s string) bool {
	return strings.IndexFunc(s, unicode.IsControl) >= 0
}

// normalizeSSHHostKey parses an authorized-keys form public key and returns
// it re-serialized as "<type> <base64>", without options or comment.
// Surrounding whitespace is ignored. Anything that is not a single public
// key, such as a fingerprint or several lines, is an error.
func normalizeSSHHostKey(key string) (string, error) {
	key = strings.TrimSpace(key)
	if hasControl(key) {
		return "", errors.New("host key contains control characters")
	}
	pub, _, _, rest, err := ssh.ParseAuthorizedKey([]byte(key))
	if err != nil {
		return "", fmt.Errorf("host key is not a public key: %w", err)
	}
	if len(strings.TrimSpace(string(rest))) > 0 {
		return "", errors.New("host key has trailing data")
	}
	return strings.TrimSpace(string(ssh.MarshalAuthorizedKey(pub))), nil
}

// sshKnownHostsLine returns the known-hosts line pinning key for host.
func sshKnownHostsLine(host, key string) (string, error) {
	norm, err := normalizeSSHHostKey(key)
	if err != nil {
		return "", err
	}
	return host + " " + norm, nil
}

// sshListedAgent is one agent from a hub listing.
type sshListedAgent struct {
	projectSlug string
	agentSlug   string
	hostKey     string // as served by the hub; empty when it has none
}

// sshAgentListing is a hub's agent listing. complete is true only when
// every page of the listing was read.
type sshAgentListing struct {
	complete bool
	agents   []sshListedAgent
}

// sshRegenResult reports what a regeneration produced. Host lists are
// sorted.
type sshRegenResult struct {
	label          string
	includeFile    string
	knownHostsFile string
	includeContent string
	knownContent   string
	hosts          int
	added          []string // listed hosts pinned for the first time
	changed        []string // listed hosts whose pinned key was replaced
	removed        []string // hosts no longer listed: block and pin dropped
	skipped        []string // listed hosts with no key and no existing pin
	invalid        []string // "<host>: <reason>" for listed hosts with an invalid key
	otherHubs      []sshIncludeFileInfo
}

// planSSHHubFiles computes the include and known-hosts files for one hub
// from a complete listing, reading the existing files under p but writing
// nothing.
//
// Every listed agent gets a Host block and a pin built from its parsed host
// key. A listed agent whose listing has no key keeps its existing pin and
// block, so a temporary gap in the listing does not drop a working host; with
// no existing pin it is reported as skipped. A listed agent whose key is
// invalid gets no block and no pin, so any earlier ones are dropped; it is
// reported in invalid with the reason, and the other agents are still
// written. Hosts that are no longer listed are dropped (removed). An
// incomplete listing, or any invalid project, agent, label, endpoint or
// executable path, is an error.
//
// hub is the endpoint exactly as resolved. It is written as the
// ProxyCommand's --hub, because a stored login is found only under the
// spelling it was stored with. Its normalized form is used for the hub
// label, the header and comparisons with other include files.
func planSSHHubFiles(p sshPaths, hub, exe string, l sshAgentListing) (*sshRegenResult, error) {
	if !l.complete {
		return nil, errors.New("the agent listing is incomplete; nothing was written")
	}
	if _, err := sshEndpointURL(hub); err != nil {
		return nil, err
	}
	endpoint := tunnelclient.NormalizeEndpoint(hub)
	u, err := sshEndpointURL(endpoint)
	if err != nil {
		return nil, err
	}
	if !filepath.IsAbs(exe) {
		return nil, fmt.Errorf("scion executable path %q is not absolute", exe)
	}
	files, err := listSSHIncludeFiles(p)
	if err != nil {
		return nil, err
	}
	label, err := resolveSSHHubLabel(endpoint, u, files)
	if err != nil {
		return nil, err
	}
	if !isSSHSlug(label) {
		return nil, fmt.Errorf("hub label %q is not a slug", label)
	}
	existing, err := readKnownHosts(p.knownHostsFile(label))
	if err != nil {
		return nil, err
	}

	res := &sshRegenResult{
		label:          label,
		includeFile:    p.includeFile(label),
		knownHostsFile: p.knownHostsFile(label),
	}
	blocks := map[string]string{}
	keys := map[string]string{}
	listed := map[string]bool{}
	for _, a := range l.agents {
		if err := checkSSHNameParts(label, a.projectSlug, a.agentSlug); err != nil {
			return nil, err
		}
		host := sshHostName(label, a.projectSlug, a.agentSlug)
		if listed[host] {
			return nil, fmt.Errorf("agent %s/%s is listed twice", a.projectSlug, a.agentSlug)
		}
		listed[host] = true
		old, hadPin := existing[host]
		if hadPin {
			if norm, nerr := normalizeSSHHostKey(old); nerr == nil {
				old = norm
			} else {
				hadPin = false
			}
		}
		var key string
		switch {
		case a.hostKey != "":
			var kerr error
			key, kerr = normalizeSSHHostKey(a.hostKey)
			if kerr != nil {
				res.invalid = append(res.invalid, host+": "+kerr.Error())
				continue
			}
		case hadPin:
			key = old
		default:
			res.skipped = append(res.skipped, host)
			continue
		}
		block, berr := renderSSHHostBlock(exe, hub, label, a.projectSlug, a.agentSlug)
		if berr != nil {
			return nil, berr
		}
		blocks[host] = block
		keys[host] = key
		switch {
		case !hadPin:
			res.added = append(res.added, host)
		case old != key:
			res.changed = append(res.changed, host)
		}
	}
	for host := range existing {
		if !listed[host] {
			res.removed = append(res.removed, host)
		}
	}
	for _, f := range files {
		if f.endpoint != endpoint && f.path != res.includeFile {
			res.otherHubs = append(res.otherHubs, f)
		}
	}
	sort.Strings(res.added)
	sort.Strings(res.changed)
	sort.Strings(res.removed)
	sort.Strings(res.skipped)
	sort.Strings(res.invalid)
	res.hosts = len(blocks)
	res.includeContent = renderSSHIncludeFile(endpoint, label, blocks)
	res.knownContent = renderKnownHosts(keys)
	return res, nil
}

// regenerateSSHHubFiles plans the hub's files (see planSSHHubFiles) and
// writes them: only the hub's include file and known-hosts file, plus the
// Include line in ~/.ssh/config. On any planning error nothing is written.
// Other hubs' include files are never changed; they are returned in
// otherHubs so the caller can name them.
func regenerateSSHHubFiles(p sshPaths, hub, exe string, l sshAgentListing) (*sshRegenResult, error) {
	res, err := planSSHHubFiles(p, hub, exe, l)
	if err != nil {
		return nil, err
	}
	if err := writeSSHHubPlan(p, res); err != nil {
		return nil, err
	}
	return res, nil
}

// writeSSHHubPlan writes a planned hub's known-hosts file and include file,
// creating missing directories, and adds the Include line to ~/.ssh/config.
// The known-hosts file is written first, so an installed block never lacks
// its pin.
func writeSSHHubPlan(p sshPaths, res *sshRegenResult) error {
	// A refusal leaves no side effect:
	// first every file this call may write is checked as writeFileAtomic
	// will check it, creating nothing; then both directories are verified
	// together before either is created; only then is anything written.
	leaves := []string{res.knownHostsFile, res.includeFile}
	// ~/.ssh/config only when the Include line is missing, i.e. when
	// ensureSSHIncludeLine will write it: a config the
	// operation leaves alone (a hard-linked one that already has the line,
	// say) is not refused. The read only decides whether to check;
	// writeFileAtomic applies the follow-then-verify and one-name rules on
	// handles if it writes.
	if need, err := sshIncludeLineNeeded(p); err != nil {
		return err
	} else if need {
		leaves = append(leaves, p.userConfig())
	}
	if err := preflightSSHWrites(leaves...); err != nil {
		return err
	}
	if err := ensureSSHDir(p.home, sshKnownHostsDirRel, sshIncludeDirRel); err != nil {
		return err
	}
	if err := writeFileAtomic(res.knownHostsFile, []byte(res.knownContent), sshFileMode); err != nil {
		return err
	}
	if err := writeFileAtomic(res.includeFile, []byte(res.includeContent), sshFileMode); err != nil {
		return err
	}
	if _, err := ensureSSHIncludeLine(p); err != nil {
		return err
	}
	return nil
}
