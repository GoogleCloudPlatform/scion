const (
	// vscodeHeader opens ~/.scion/vscode/ssh_config.
	vscodeHeader = "# Generated by scion vscode. Blocks are updated one agent at a time; manual edits are lost."
	// vscodeKnownHostsRef is the known-hosts path as written into the Host
	// blocks of ~/.scion/vscode/ssh_config; ssh expands the tilde.
	vscodeKnownHostsRef = "~/.scion/vscode/known_hosts"
	// vscodeDefaultFolder is the remote folder VS Code opens.
	vscodeDefaultFolder = "/workspace"
	// vscodeRecreatedLine is printed when an agent's pinned host key changed.
	vscodeRecreatedLine = "agent was recreated; host key updated"
	// vscodeCodeBinary is the VS Code CLI looked up on PATH.
	vscodeCodeBinary = "code"
	// vscodeConfigFileSetting is the Remote-SSH setting that points VS Code
	// at the scion-owned ssh config.
	vscodeConfigFileSetting = "remote.SSH.configFile"
	// vscodeUserDataFlag is how scion vscode gives VS Code its own settings.
	//
	// remote.SSH.configFile is declared with "scope": "application" in the
	// Remote-SSH extension manifest (ms-vscode-remote.remote-ssh
	// 0.129.2026100915, extension/package.json of the marketplace VSIX with
	// sha256 b740aa614637b84c626e4c8c70349fe1f1c4c941056478c29aa578b8c15a3252).
	// Application-scoped settings "apply to all instances of VS Code and can
	// only be configured in user settings"
	// (https://code.visualstudio.com/api/references/contribution-points,
	// configuration scope). The user settings of the default profile are
	// the application settings: "When you're using a non-default profile,
	// you can access the settings.json file that is associated with the
	// default profile by using the Preferences: Open Application Settings
	// (JSON) command" (https://code.visualstudio.com/docs/configure/settings,
	// Profile settings). So a VS Code profile cannot carry the setting on
	// its own. A scion-owned user data directory can: its settings.json sets
	// it, and the user's default user data is never touched. Extensions stay
	// in the default, shared extensions directory. The mechanism is fixed
	// here, never detected at run time.
	vscodeUserDataFlag = "--user-data-dir"
	// vscodePreflightTimeout bounds the preflight tunnel.
	vscodePreflightTimeout = 60 * time.Second
)

// vscodePaths derives every path scion vscode writes from one home
// directory.
type vscodePaths struct{ home string }

func (p vscodePaths) dir() string        { return filepath.Join(p.home, ".scion", "vscode") }
func (p vscodePaths) sshConfig() string  { return filepath.Join(p.dir(), "ssh_config") }
func (p vscodePaths) knownHosts() string { return filepath.Join(p.dir(), "known_hosts") }
func (p vscodePaths) lockFile() string   { return filepath.Join(p.dir(), ".lock") }
func (p vscodePaths) userData() string   { return filepath.Join(p.dir(), "user-data") }
func (p vscodePaths) settings() string   { return filepath.Join(p.userData(), "User", "settings.json") }

var (
	vscodeFolder string
	vscodePrune  bool
)

var vscodeCmd = &cobra.Command{
	Use:   "vscode <agent>",
	Short: "Open VS Code Remote-SSH on an agent's /workspace",
	Long: `Open VS Code Remote-SSH on an agent's /workspace over the hub, without
editing ~/.ssh/config.

The agent is "<agent>" or "<project>/<agent>"; the hub and project are
resolved as for scion tunnel, including the project selected with 'scion
use'. scion vscode writes the agent's Host block and pinned host key into
~/.scion/vscode/ssh_config and ~/.scion/vscode/known_hosts, keeping every
other agent's entries, checks the agent with one SSH tunnel, and then runs

  code --user-data-dir ~/.scion/vscode/user-data --remote ssh-remote+<host> /workspace

That user data directory's settings.json points remote.SSH.configFile at
the scion-owned ssh config; your own VS Code settings are never changed.
Extensions are shared with your default VS Code.

With --prune, Host blocks of agents that no longer exist on this hub are
removed, from a complete listing only. The command never prompts. Exit
codes are those of scion tunnel; 1 when code is missing or fails to start.`,
	Args: func(cmd *cobra.Command, args []string) error {
		if len(args) != 1 {
			return tunnelclient.Errorf(tunnelclient.ExitUsage, "scion vscode takes one agent, got %d arguments", len(args))
		}
		return nil
	},
	RunE: func(cmd *cobra.Command, args []string) error {
		env, err := defaultSSHCommandEnv()
		if err != nil {
			return err
		}
		env.stdout, env.stderr = cmd.OutOrStdout(), cmd.ErrOrStderr()
		return vscodeMain(cmd.Context(), env, args[0], vscodeFolder, vscodePrune)
	},
}

func init() {
	vscodeCmd.Flags().StringVar(&vscodeFolder, "path", vscodeDefaultFolder, "Remote folder to open")
	vscodeCmd.Flags().BoolVar(&vscodePrune, "prune", false, "Remove the Host blocks of this hub's agents that no longer exist")
	vscodeCmd.SetFlagErrorFunc(tunnelFlagError)
	rootCmd.AddCommand(vscodeCmd)
}

// vscodePreflight opens one SSH tunnel to the agent through the same client
// as scion tunnel --ssh and closes it. Tests replace it.
var vscodePreflight = func(ctx context.Context, endpoint, project, agent string, stderr io.Writer) error {
	cfg, _, err := tunnelClientConfig(tunnelSettings(), endpoint, stderr)
	if err != nil {
		return err
	}
	// A check, not a tunnel to report: no status record.
	cfg.State = nil
	ctx, cancel := context.WithTimeout(ctx, vscodePreflightTimeout)
	defer cancel()
	return vscodePreflightError(tunnelclient.Run(ctx, cfg, tunnelclient.Request{
		Agent:   agent,
		Project: project,
		SSH:     true,
		Stdio:   true,
		Stdin:   strings.NewReader(""),
		Stdout:  io.Discard,
	}), project, agent)
}

// vscodePreflightError maps the preflight tunnel's result to the command's
// error: a tunnel client error as it is, the preflight timeout as exit 6,
// anything else as exit 1.
func vscodePreflightError(err error, project, agent string) error {
	if err == nil {
		return nil
	}
	var te *tunnelclient.Error
	if errors.As(err, &te) {
		return te
	}
	if errors.Is(err, context.DeadlineExceeded) {
		return tunnelclient.Errorf(tunnelclient.ExitHubUnavailable, "checking the SSH tunnel to %s/%s timed out after %s", project, agent, vscodePreflightTimeout)
	}
	return tunnelclient.Errorf(tunnelclient.ExitError, "%v", err)
}

// vscodeLookPath finds the VS Code CLI; tests replace it.
var vscodeLookPath = exec.LookPath

// vscodeRunCode runs the VS Code CLI and waits for it to return; tests
// replace it. The CLI hands the window to VS Code and returns.
var vscodeRunCode = func(ctx context.Context, bin string, args []string, stdout, stderr io.Writer) error {
	c := exec.CommandContext(ctx, bin, args...)
	c.Stdout = stdout
	c.Stderr = stderr
	return c.Run()
}

// vscodeMain runs scion vscode for one agent reference.
func vscodeMain(ctx context.Context, env *sshCommandEnv, ref, folder string, prune bool) error {
	if !strings.HasPrefix(folder, "/") || hasControl(folder) {
		return tunnelclient.Errorf(tunnelclient.ExitUsage, "invalid --path %q: use an absolute path on the agent", folder)
	}
	hub, err := resolveSSHHub(env)
	if err != nil {
		return err
	}
	p := vscodePaths{home: env.home}
	if hub.label, err = vscodeHubLabel(p, hub); err != nil {
		return err
	}
	rctx, cancel := context.WithTimeout(ctx, sshHubRequestTimeout)
	defer cancel()
	entry, err := hub.conn.resolveSSHTarget(rctx, ref, env.project)
	if err != nil {
		return err
	}
	key, err := hub.conn.agentSSHHostKey(rctx, "", entry.agentID)
	if err != nil {
		return err
	}
	if key == "" {
		return tunnelclient.Errorf(tunnelclient.ExitError, "agent %s/%s has no SSH host key yet", entry.projectSlug, entry.agentSlug)
	}
	norm, err := normalizeSSHHostKey(key)
	if err != nil {
		return tunnelclient.Errorf(tunnelclient.ExitError, "agent %s/%s has an invalid SSH host key: %v", entry.projectSlug, entry.agentSlug, err)
	}
	block, err := renderSSHHostBlockKnown(env.exe, hub.hubArg, hub.label, entry.projectSlug, entry.agentSlug, vscodeKnownHostsRef)
	if err != nil {
		return tunnelclient.Errorf(tunnelclient.ExitError, "%v", err)
	}
	host := sshHostName(hub.label, entry.projectSlug, entry.agentSlug)

	var keep map[string]bool
	if prune {
		listing, err := hub.conn.collectSSHAgentListing(ctx)
		if err != nil {
			return err
		}
		if !listing.complete {
			return tunnelclient.Errorf(tunnelclient.ExitError, "the agent listing from hub %s is incomplete; nothing pruned", hub.endpoint)
		}
		keep = map[string]bool{}
		for _, a := range listing.agents {
			keep[sshHostName(hub.label, a.projectSlug, a.agentSlug)] = true
		}
	}

	if err := vscodePreflight(ctx, hub.hubArg, entry.projectSlug, entry.agentSlug, env.stderr); err != nil {
		return err
	}

	changed, err := updateVSCodeFiles(p, vscodeUpdate{host: host, block: block, key: norm, endpoint: hub.endpoint, keep: keep})
	if err != nil {
		return tunnelclient.Errorf(tunnelclient.ExitError, "%v", err)
	}
	if changed {
		_, _ = fmt.Fprintln(env.stdout, vscodeRecreatedLine)
	}
	if err := ensureVSCodeSettings(p); err != nil {
		return tunnelclient.Errorf(tunnelclient.ExitError, "%v", err)
	}
	return launchVSCode(ctx, env, p, host, folder)
}

// vscodeUpdate is one change to the scion vscode files: set host's block
// and pin for the hub at endpoint (normalized), and, when keep is not nil,
// drop the blocks and pins of that hub's other hosts that keep does not
// list. A block belongs to the hub its ProxyCommand pins with --hub.
type vscodeUpdate struct {
	host, block, key string
	endpoint         string
	keep             map[string]bool
}

// updateVSCodeFiles applies u to ~/.scion/vscode/ssh_config and known_hosts
// under an exclusive lock on the directory, so concurrent runs keep each
// other's entries. It reports whether u.host had a different pin before.
func updateVSCodeFiles(p vscodePaths, u vscodeUpdate) (changed bool, err error) {
	if err := ensureSSHDir(p.home, p.dir()); err != nil {
		return false, fmt.Errorf("creating %s: %w", p.dir(), err)
	}
	unlock, err := lockVSCodeDir(p.lockFile())
	if err != nil {
		return false, err
	}
	defer unlock()

	blocks := map[string]string{}
	if data, rerr := os.ReadFile(p.sshConfig()); rerr == nil {
		blocks = parseSSHHostBlocks(string(data))
	} else if !errors.Is(rerr, os.ErrNotExist) {
		return false, fmt.Errorf("reading %s: %w", p.sshConfig(), rerr)
	}
	keys, err := readKnownHosts(p.knownHosts())
	if err != nil {
		return false, fmt.Errorf("reading %s: %w", p.knownHosts(), err)
	}
	if existing, ok := blocks[u.host]; ok {
		if ep := vscodeBlockHub(existing); ep != "" && ep != u.endpoint {
			return false, fmt.Errorf("host %s in %s belongs to hub %s; run scion vscode again", u.host, p.sshConfig(), ep)
		}
	}
	old, hadPin := keys[u.host]
	blocks[u.host] = u.block
	keys[u.host] = u.key
	if u.keep != nil {
		for h, b := range blocks {
			if h != u.host && !u.keep[h] && vscodeBlockHub(b) == u.endpoint {
				delete(blocks, h)
				delete(keys, h)
			}
		}
	}
	if err := writeFileAtomic(p.sshConfig(), []byte(renderVSCodeSSHConfig(blocks)), sshFileMode); err != nil {
		return false, fmt.Errorf("writing %s: %w", p.sshConfig(), err)
	}
	if err := writeFileAtomic(p.knownHosts(), []byte(renderKnownHosts(keys)), sshFileMode); err != nil {
		return false, fmt.Errorf("writing %s: %w", p.knownHosts(), err)
	}
	return hadPin && old != u.key, nil
}

// lockVSCodeDir takes an exclusive advisory lock on path, which works
// across processes (as for context.yaml).
func lockVSCodeDir(path string) (func(), error) {
	f, err := os.OpenFile(path, os.O_CREATE|os.O_RDWR, sshFileMode)
	if err != nil {
		return nil, fmt.Errorf("open lock %s: %w", path, err)
	}
	if err := syscall.Flock(int(f.Fd()), syscall.LOCK_EX); err != nil {
		_ = f.Close()
		return nil, fmt.Errorf("lock %s: %w", path, err)
	}
	return func() {
		_ = syscall.Flock(int(f.Fd()), syscall.LOCK_UN)
		_ = f.Close()
	}, nil
}

// vscodeBlockHub returns the hub endpoint, normalized, that a Host block's
// ProxyCommand pins with --hub, or "" when it has none.
func vscodeBlockHub(block string) string {
	for _, line := range strings.Split(block, "\n") {
		fields := strings.Fields(line)
		if len(fields) == 0 || !strings.EqualFold(fields[0], "ProxyCommand") {
			continue
		}
		for i := 1; i+1 < len(fields); i++ {
			if fields[i] == "--hub" {
				return tunnelclient.NormalizeEndpoint(sshShellUnquote(fields[i+1]))
			}
		}
	}
	return ""
}

// sshShellUnquote reverses sshShellQuote for one word.
func sshShellUnquote(w string) string {
	if len(w) >= 2 && strings.HasPrefix(w, "'") && strings.HasSuffix(w, "'") {
		w = strings.ReplaceAll(w[1:len(w)-1], `'\''`, "'")
	}
	return strings.ReplaceAll(w, "%%", "%")
}

// vscodeHubLabel returns the hub label for the vscode files: the label an
// ssh-config include file or an existing vscode block records for this
// endpoint, else the first candidate no other endpoint holds in either.
func vscodeHubLabel(p vscodePaths, hub *sshHubTarget) (string, error) {
	files := append([]sshIncludeFileInfo{}, hub.files...)
	if data, err := os.ReadFile(p.sshConfig()); err == nil {
		files = append(files, vscodeLabelRecords(parseSSHHostBlocks(string(data)))...)
	} else if !errors.Is(err, os.ErrNotExist) {
		return "", tunnelclient.Errorf(tunnelclient.ExitError, "reading %s: %v", p.sshConfig(), err)
	}
	u, err := sshEndpointURL(hub.endpoint)
	if err != nil {
		return "", tunnelclient.Errorf(tunnelclient.ExitUsage, "%v", err)
	}
	label, err := resolveSSHHubLabel(hub.endpoint, u, files)
	if err != nil {
		return "", tunnelclient.Errorf(tunnelclient.ExitError, "%v", err)
	}
	return label, nil
}

// vscodeLabelRecords turns the vscode file's blocks into label records: the
// label of each Host name with the hub its ProxyCommand pins.
func vscodeLabelRecords(blocks map[string]string) []sshIncludeFileInfo {
	hosts := make([]string, 0, len(blocks))
	for h := range blocks {
		hosts = append(hosts, h)
	}
	sort.Strings(hosts)
	var out []sshIncludeFileInfo
	for _, h := range hosts {
		rest, ok := strings.CutPrefix(h, "scion.")
		label, _, _ := strings.Cut(rest, ".")
		ep := vscodeBlockHub(blocks[h])
		if !ok || label == "" || ep == "" {
			continue
		}
		out = append(out, sshIncludeFileInfo{label: label, endpoint: ep})
	}
	return out
}

// renderVSCodeSSHConfig writes the header and the blocks, sorted by host
// name.
func renderVSCodeSSHConfig(blocks map[string]string) string {
	names := make([]string, 0, len(blocks))
	for n := range blocks {
		names = append(names, n)
	}
	sort.Strings(names)
	var b strings.Builder
	b.WriteString(vscodeHeader + "\n")
	for _, n := range names {
		b.WriteString("\n")
		b.WriteString(blocks[n])
	}
	return b.String()
}

// ensureVSCodeSettings makes the scion user data directory's settings.json
// point remote.SSH.configFile at the scion-owned ssh config. A missing file
// is created; a plain JSON file gets that one key set and keeps the others.
// A file with comments is left as it is when it already holds the value,
// and is an error otherwise: rewriting it would drop the comments.
func ensureVSCodeSettings(p vscodePaths) error {
	want := p.sshConfig()
	path := p.settings()
	if err := ensureSSHDir(p.home, filepath.Dir(path)); err != nil {
		return fmt.Errorf("creating %s: %w", filepath.Dir(path), err)
	}
	data, err := os.ReadFile(path)
	if errors.Is(err, os.ErrNotExist) {
		return writeVSCodeSettings(path, map[string]any{vscodeConfigFileSetting: want})
	}
	if err != nil {
		return fmt.Errorf("reading %s: %w", path, err)
	}
	if t := strings.TrimSpace(string(data)); t == "" || t == "null" {
		return writeVSCodeSettings(path, map[string]any{vscodeConfigFileSetting: want})
	}
	var m map[string]any
	if json.Unmarshal(data, &m) == nil && m != nil {
		if m[vscodeConfigFileSetting] == want {
			return nil
		}
		m[vscodeConfigFileSetting] = want
		return writeVSCodeSettings(path, m)
	}
	var withComments map[string]any
	if json.Unmarshal(stripJSONComments(data), &withComments) == nil && withComments[vscodeConfigFileSetting] == want {
		return nil
	}
	return fmt.Errorf("%s is not plain JSON; set %s to %s in it, or remove the file", path, vscodeConfigFileSetting, want)
}

func writeVSCodeSettings(path string, m map[string]any) error {
	data, err := json.MarshalIndent(m, "", "  ")
	if err != nil {
		return err
	}
	if err := writeFileAtomic(path, append(data, '\n'), sshFileMode); err != nil {
		return fmt.Errorf("writing %s: %w", path, err)
	}
	return nil
}

// stripJSONComments removes // and /* */ comments and trailing commas
// outside strings, the extensions VS Code allows in settings.json.
func stripJSONComments(data []byte) []byte {
	var out []byte
	inString, afterBackslash := false, false
	for i := 0; i < len(data); i++ {
		c := data[i]
		if inString {
			out = append(out, c)
			switch {
			case afterBackslash:
				afterBackslash = false
			case c == '\\':
				afterBackslash = true
			case c == '"':
				inString = false
			}
			continue
		}
		switch {
		case c == '"':
			inString = true
			out = append(out, c)
		case c == '/' && i+1 < len(data) && data[i+1] == '/':
			for i < len(data) && data[i] != '\n' {
				i++
			}
			if i < len(data) {
				out = append(out, '\n')
			}
		case c == '/' && i+1 < len(data) && data[i+1] == '*':
			i += 2
			for i+1 < len(data) && (data[i] != '*' || data[i+1] != '/') {
				i++
			}
			i++
		case c == ']' || c == '}':
			j := len(out) - 1
			for j >= 0 && (out[j] == ' ' || out[j] == '\t' || out[j] == '\n' || out[j] == '\r') {
				j--
			}
			if j >= 0 && out[j] == ',' {
				out = append(out[:j], out[j+1:]...)
			}
			out = append(out, c)
		default:
			out = append(out, c)
		}
	}
	return out
}

// launchVSCode runs the VS Code CLI on host and folder with the scion user
// data directory. Any failure to find or start it is exit 1.
func launchVSCode(ctx context.Context, env *sshCommandEnv, p vscodePaths, host, folder string) error {
	bin, err := vscodeLookPath(vscodeCodeBinary)
	if err != nil {
		return tunnelclient.Errorf(tunnelclient.ExitError, "VS Code CLI %s not found on PATH", vscodeCodeBinary)
	}
	args := []string{vscodeUserDataFlag, p.userData(), "--remote", "ssh-remote+" + host, folder}
	if err := vscodeRunCode(ctx, bin, args, env.stdout, env.stderr); err != nil {
		var exitErr *exec.ExitError
		if errors.As(err, &exitErr) {
			return tunnelclient.Errorf(tunnelclient.ExitError, "%s exited with status %d", vscodeCodeBinary, exitErr.ExitCode())
		}
		return tunnelclient.Errorf(tunnelclient.ExitError, "starting %s: %v", vscodeCodeBinary, err)
	}
	return nil
}
