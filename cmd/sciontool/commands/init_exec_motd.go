const (
	execContainerMOTDPath          = "/etc/motd"
	execContainerProfileScriptPath = "/etc/profile.d/scion-exec-container.sh"
)

// execContainerProfileScript is sourced by interactive login shells (bash -l)
// via /etc/profile. It displays /etc/motd once per container boot (so the user
// sees it on first attach without repeating on respawned shells) and adds a
// subtle [exec] prefix to PS1. No environment values are interpolated into the
// script itself.
const execContainerProfileScript = `# Auto-generated by sciontool init for execution containers (SCION_HARNESS=shell).
case "$-" in
  *i*)
    if [ -r /etc/motd ] && [ ! -e /tmp/.scion-exec-motd-shown ]; then
      cat /etc/motd
      : > /tmp/.scion-exec-motd-shown 2>/dev/null || true
    fi
    if [ -n "${PS1-}" ]; then
      PS1="[exec] ${PS1}"
    fi
    ;;
esac
`

// sanitizeMOTDToken strips control characters (including CR/LF and ANSI
// escapes) and bounds the length of an agent identifier before interpolating
// it into the plain-text MOTD.
func sanitizeMOTDToken(s string) string {
	s = strings.TrimSpace(s)
	var b strings.Builder
	for _, r := range s {
		if unicode.IsControl(r) {
			continue
		}
		b.WriteRune(r)
		if b.Len() >= 64 {
			break
		}
	}
	return b.String()
}

// shellQuoteMOTDArg returns s unchanged when it consists solely of safe
// unquoted shell token characters, and otherwise wraps it in POSIX single
// quotes so pasting the command never splits on spaces or interprets shell
// metacharacters.
func shellQuoteMOTDArg(s string) string {
	safe := true
	for _, r := range s {
		if (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') || (r >= '0' && r <= '9') ||
			r == '-' || r == '_' || r == '.' || r == ':' || r == '/' || r == '@' {
			continue
		}
		safe = false
		break
	}
	if safe && s != "" {
		return s
	}
	return "'" + strings.ReplaceAll(s, "'", `'"'"'`) + "'"
}

// buildExecContainerMOTD formats the one-screen execution-container MOTD
// (design §3.5, §3.6, S9, D6; ptone/scion#8820).
func buildExecContainerMOTD(getenv func(string) string) string {
	agentName := sanitizeMOTDToken(getenv("SCION_AGENT_NAME"))
	if agentName == "" {
		agentName = sanitizeMOTDToken(getenv("SCION_AGENT_SLUG"))
	}
	header := "Scion Execution Container"
	registerArg := "<name>"
	if agentName != "" {
		header = fmt.Sprintf("Scion Execution Container (%s)", agentName)
		registerArg = shellQuoteMOTDArg(agentName)
	}

	var persistenceLine string
	switch strings.ToLower(strings.TrimSpace(getenv(api.EnvHomePersistent))) {
	case "true":
		persistenceLine = "Home persistence: enabled ($HOME survives restarts on this runtime)."
	case "false":
		persistenceLine = "WARNING: $HOME is NOT persistent on this runtime. Logins and files in $HOME\nwill be lost when this container stops or restarts."
	default:
		persistenceLine = "Home persistence: unknown (check whether this runtime persists $HOME)."
	}

	var transportLine string
	if transportauth.IsProxyMode(strings.TrimSpace(getenv(transportauth.EnvTransportMode))) {
		transportLine = "Hub requires transport auth: log in first (e.g. gcloud auth application-default login).\n"
	}

	return fmt.Sprintf(`======================================================================
%s
======================================================================
This is your execution container. Log in to the CLIs you want approved
commands to use (for example: gh auth login, gcloud auth login).

Security: Keep credentials in $HOME — never in /workspace (which may
be shared with other agents).

Log in to Scion (lets approved commands use the scion CLI as you):
  scion login

Register as your default execution container:
  scion exec-container set %s

%s%s
Detach with Ctrl-b d (typing exit starts a fresh shell).
======================================================================
`, header, registerArg, transportLine, persistenceLine)
}

// writeExecContainerMOTD writes the execution-container MOTD and login-shell
// profile snippet when SCION_HARNESS=shell. For all other harnesses it is a
// no-op. Failures (e.g. non-root container or read-only /etc) are logged and
// do not block container startup.
func writeExecContainerMOTD() {
	if err := writeExecContainerMOTDAt(os.Getenv, execContainerMOTDPath, execContainerProfileScriptPath); err != nil {
		log.Error("Failed to write execution container MOTD: %v", err)
	}
}

func writeExecContainerMOTDAt(getenv func(string) string, motdPath, profileScriptPath string) error {
	if getenv("SCION_HARNESS") != state.ShellHarnessName {
		return nil
	}
	motd := buildExecContainerMOTD(getenv)
	if err := os.WriteFile(motdPath, []byte(motd), 0644); err != nil {
		return fmt.Errorf("write %s: %w", motdPath, err)
	}
	if profileScriptPath != "" {
		if fi, err := os.Stat(filepath.Dir(profileScriptPath)); err == nil && fi.IsDir() {
			if err := os.WriteFile(profileScriptPath, []byte(execContainerProfileScript), 0644); err != nil {
				return fmt.Errorf("write %s: %w", profileScriptPath, err)
			}
		}
	}
	return nil
}
