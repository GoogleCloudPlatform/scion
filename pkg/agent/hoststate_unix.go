//go:build unix

package agent

import (
	"errors"
	"fmt"
	"os"
	"syscall"
)

// openNoFollow opens path read-only, refusing a symlink at path itself
// (O_NOFOLLOW). Symlinks in parent components are followed, since host
// paths can legitimately contain them.
func openNoFollow(path string) (*os.File, error) {
	f, err := os.OpenFile(path, os.O_RDONLY|syscall.O_NOFOLLOW|syscall.O_NONBLOCK, 0)
	if err != nil {
		if errors.Is(err, syscall.ELOOP) {
			return nil, fmt.Errorf("%w: %s", errHostStateSymlink, path)
		}
		return nil, err
	}
	return f, nil
}
