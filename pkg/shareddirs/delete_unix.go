// maxDeleteTreeDepth caps the recursion depth removeTreeContents will walk.
// A shared dir's contents come from an agent, not a trusted operator, so an
// adversarially deep directory chain (or one generated by a runaway process
// before deletion) must not be able to blow the goroutine stack or run
// unbounded; 4096 is far beyond any legitimate shared-dir layout while still
// comfortably below where recursion becomes a practical concern.
//
// A package var, not a const, so tests can lower it to exercise the cap
// against a real directory chain without constructing thousands of levels.
var maxDeleteTreeDepth = 4096

// DeleteProjectRoot removes <hostBase>/<subPathRoot>/<projectID> and
// everything under it (workspace, provisioning state, configuration, shared
// dirs), via the symlink-safe, fd-based openat/unlinkat walk of
// removeTreeContents. It is for a project root its caller has just created
// and must roll back (a failed shared workspace provisioning at project
// create); project deletion goes through DeleteTree (projectfs).
//
// Errors and tolerated cases: an unusable
// hostBase is an error; an absent subPathRoot or project dir is nothing to
// do; a structural component (subPathRoot or projectID) that is not a plain
// directory, most notably a symlink, is refused. Entries under the project
// dir are removed regardless of type, and a symlink there is unlinked, never
// followed.
func DeleteProjectRoot(hostBase, subPathRoot, projectID string) error {
	if !ValidProjectID(projectID) {
		return fmt.Errorf("invalid project ID %q", projectID)
	}
	baseFd, err := unix.Open(hostBase, unix.O_RDONLY|unix.O_DIRECTORY|unix.O_CLOEXEC, 0)
	if err != nil {
		if errors.Is(err, unix.ENOENT) {
			return fmt.Errorf("host base %q does not exist", hostBase)
		}
		return fmt.Errorf("open host base %q: %w", hostBase, err)
	}
	defer func() { _ = unix.Close(baseFd) }()

	subRootFd, existed, err := openExistingDirPathNoFollow(baseFd, subPathRoot)
	if err != nil {
		return fmt.Errorf("subpath_root %q: %w", subPathRoot, err)
	}
	if !existed {
		return nil
	}
	defer func() { _ = unix.Close(subRootFd) }()

	projectFd, existed, err := openExistingDirNoFollow(subRootFd, projectID)
	if err != nil {
		return fmt.Errorf("project dir %q: %w", projectID, err)
	}
	if !existed {
		return nil
	}
	walkErr := removeTreeContents(projectFd, 0)
	_ = unix.Close(projectFd)
	if walkErr != nil {
		return fmt.Errorf("remove contents of project %q: %w", projectID, walkErr)
	}
	if err := unix.Unlinkat(subRootFd, projectID, unix.AT_REMOVEDIR); err != nil && !errors.Is(err, unix.ENOENT) {
		return fmt.Errorf("remove project dir %q: %w", projectID, err)
	}
	return nil
}

// DeleteSharedDir removes exactly one shared dir's leaf --
// <hostBase>/<subPathRoot>/<projectID>/shared-dirs/<name> -- and its
// contents, via the same symlink-safe openat/unlinkat walk DeleteTree
// uses. It never touches shared-dirs/ itself or any sibling shared dir under
// it -- only the one named leaf.
//
// name is checked with ValidProjectID, reused here as the generic "safe
// single path segment" allow-list it already is (not a claim that a shared
// dir name is a project ID): both are slugs constrained to
// [A-Za-z0-9][A-Za-z0-9._-]{0,127}, and the HTTP-layer api.ValidateSharedDirs
// check (lowercase alphanumeric + hyphens) is already a strict subset of it,
// so a name that reached here legitimately can never be rejected by this
// defense-in-depth check.
//
// Returns an error if hostBase itself doesn't exist or can't be opened --
// an operator/deployment problem (e.g. an unmounted export), not a
// tolerable "nothing to do" case; a missing host base must not look like a
// successful delete. Returns nil (nothing to do) if subPathRoot, projectID,
// "shared-dirs", or the named leaf doesn't exist under an existing
// hostBase. Returns an error, naming the offending component, if any
// structural component exists but is not a plain directory -- most notably
// a symlink.
func DeleteSharedDir(hostBase, subPathRoot, projectID, name string) error {
	if !ValidProjectID(projectID) {
		return fmt.Errorf("invalid project ID %q", projectID)
	}
	if !ValidProjectID(name) {
		return fmt.Errorf("invalid shared dir name %q", name)
	}

	baseFd, err := unix.Open(hostBase, unix.O_RDONLY|unix.O_DIRECTORY|unix.O_CLOEXEC, 0)
	if err != nil {
		if errors.Is(err, unix.ENOENT) {
			return fmt.Errorf("host base %q does not exist", hostBase)
		}
		return fmt.Errorf("open host base %q: %w", hostBase, err)
	}
	defer func() { _ = unix.Close(baseFd) }()

	sharedDirsRel := filepath.Join(subPathRoot, projectID, "shared-dirs")
	sharedDirsFd, existed, err := openExistingDirPathNoFollow(baseFd, sharedDirsRel)
	if err != nil {
		return fmt.Errorf("shared-dirs for project %q: %w", projectID, err)
	}
	if !existed {
		return nil // nothing under shared-dirs/ at all -- nothing to do
	}
	defer func() { _ = unix.Close(sharedDirsFd) }()

	leafFd, existed, err := openExistingDirNoFollow(sharedDirsFd, name)
	if err != nil {
		return fmt.Errorf("shared dir %q: %w", name, err)
	}
	if !existed {
		return nil // this shared dir was never created, or already removed
	}

	if err := removeTreeContents(leafFd, 0); err != nil {
		_ = unix.Close(leafFd)
		return fmt.Errorf("remove shared dir %q contents: %w", name, err)
	}
	_ = unix.Close(leafFd)

	if err := unix.Unlinkat(sharedDirsFd, name, unix.AT_REMOVEDIR); err != nil && !errors.Is(err, unix.ENOENT) {
		return fmt.Errorf("remove shared dir %q: %w", name, err)
	}
	return nil
}

// ErrTreeRefused marks a DeleteTree error raised before anything was
// removed: an invalid path, an unusable host base, or a component that is a
// symlink or not a directory. Retrying cannot help with such an error;
// other errors (a removal that failed part-way, for example because a
// process was still writing) may clear on a retry.
var ErrTreeRefused = errors.New("tree deletion refused")

// DeleteTree removes <hostBase>/<relPath> and everything under it, via
// the symlink-safe, fd-based openat/unlinkat walk of removeTreeContents.
// relPath is a relative path of one or more components,
// none of them empty, "." or "..". Every component of relPath must be a
// plain directory: a symlink (or any other non-directory) at any of them is
// refused, never followed. Entries under the leaf are removed regardless of
// type, and a symlink there is unlinked, never followed.
//
// existed reports whether the leaf directory was there to remove. An
// absent component is nothing to do (existed false, no error), so repeated
// or concurrent calls converge. An unusable hostBase is an error: a missing
// mount must never look like a successful delete.
func DeleteTree(hostBase, relPath string) (existed bool, err error) {
	comps, err := splitRelPath(relPath)
	if err != nil {
		return false, fmt.Errorf("%w: %w", ErrTreeRefused, err)
	}
	baseFd, err := unix.Open(hostBase, unix.O_RDONLY|unix.O_DIRECTORY|unix.O_CLOEXEC, 0)
	if err != nil {
		if errors.Is(err, unix.ENOENT) {
			return false, fmt.Errorf("%w: host base %q does not exist", ErrTreeRefused, hostBase)
		}
		return false, fmt.Errorf("%w: open host base %q: %w", ErrTreeRefused, hostBase, err)
	}
	defer func() { _ = unix.Close(baseFd) }()

	parentFd := baseFd
	if len(comps) > 1 {
		fd, ok, err := openExistingDirPathNoFollow(baseFd, strings.Join(comps[:len(comps)-1], "/"))
		if err != nil {
			return false, fmt.Errorf("%w: %q: %w", ErrTreeRefused, relPath, err)
		}
		if !ok {
			return false, nil
		}
		parentFd = fd
		defer func() { _ = unix.Close(fd) }()
	}
	leaf := comps[len(comps)-1]
	leafFd, ok, err := openExistingDirNoFollow(parentFd, leaf)
	if err != nil {
		return false, fmt.Errorf("%w: %q: %w", ErrTreeRefused, relPath, err)
	}
	if !ok {
		return false, nil
	}
	walkErr := removeTreeContents(leafFd, 0)
	_ = unix.Close(leafFd)
	if walkErr != nil {
		return true, fmt.Errorf("remove contents of %q: %w", relPath, walkErr)
	}
	if err := unix.Unlinkat(parentFd, leaf, unix.AT_REMOVEDIR); err != nil && !errors.Is(err, unix.ENOENT) {
		return true, fmt.Errorf("remove %q: %w", relPath, err)
	}
	return true, nil
}

// RemoveDirIfEmpty removes the directory <hostBase>/<relPath> only when it
// is empty, walking every component without following a symlink (a symlink
// or non-directory at any component, the leaf included, is refused with
// ErrTreeRefused). existed reports whether the directory was there; notEmpty
// that it was kept because it still has entries. Nothing below it is ever
// removed.
func RemoveDirIfEmpty(hostBase, relPath string) (existed, notEmpty bool, err error) {
	comps, err := splitRelPath(relPath)
	if err != nil {
		return false, false, fmt.Errorf("%w: %w", ErrTreeRefused, err)
	}
	baseFd, err := unix.Open(hostBase, unix.O_RDONLY|unix.O_DIRECTORY|unix.O_CLOEXEC, 0)
	if err != nil {
		if errors.Is(err, unix.ENOENT) {
			return false, false, fmt.Errorf("%w: host base %q does not exist", ErrTreeRefused, hostBase)
		}
		return false, false, fmt.Errorf("%w: open host base %q: %w", ErrTreeRefused, hostBase, err)
	}
	defer func() { _ = unix.Close(baseFd) }()

	parentFd := baseFd
	if len(comps) > 1 {
		fd, ok, err := openExistingDirPathNoFollow(baseFd, strings.Join(comps[:len(comps)-1], "/"))
		if err != nil {
			return false, false, fmt.Errorf("%w: %q: %w", ErrTreeRefused, relPath, err)
		}
		if !ok {
			return false, false, nil
		}
		parentFd = fd
		defer func() { _ = unix.Close(fd) }()
	}
	leaf := comps[len(comps)-1]
	leafFd, ok, err := openExistingDirNoFollow(parentFd, leaf)
	if err != nil {
		return false, false, fmt.Errorf("%w: %q: %w", ErrTreeRefused, relPath, err)
	}
	if !ok {
		return false, false, nil
	}
	_ = unix.Close(leafFd)
	if err := unix.Unlinkat(parentFd, leaf, unix.AT_REMOVEDIR); err != nil {
		switch {
		case errors.Is(err, unix.ENOENT):
			return true, false, nil
		case errors.Is(err, unix.ENOTEMPTY), errors.Is(err, unix.EEXIST):
			return true, true, nil
		default:
			return true, false, fmt.Errorf("remove %q: %w", relPath, err)
		}
	}
	return true, false, nil
}

// WriteFileInTree writes data to <hostBase>/<relDir>/<name>, replacing the
// file, without following a symlink at any component: every component of
// relDir but the last must exist as a plain directory; the last is created
// (mode 0o755) when createLast is set and it is absent. name must be one
// plain path element; an existing name that is not a regular file is
// refused. Errors raised before anything was written are ErrTreeRefused.
func WriteFileInTree(hostBase, relDir, name string, data []byte, createLast bool) error {
	dirFd, err := openTreeDir(hostBase, relDir, createLast)
	if err != nil {
		return err
	}
	defer func() { _ = unix.Close(dirFd) }()
	if err := checkFileName(name); err != nil {
		return err
	}
	tmp := "." + name + ".tmp"
	_ = unix.Unlinkat(dirFd, tmp, 0)
	fd, err := unix.Openat(dirFd, tmp, unix.O_WRONLY|unix.O_CREAT|unix.O_EXCL|unix.O_NOFOLLOW|unix.O_CLOEXEC, 0o644)
	if err != nil {
		return fmt.Errorf("create %s/%s: %w", relDir, tmp, err)
	}
	f := os.NewFile(uintptr(fd), tmp)
	if _, err := f.Write(data); err != nil {
		_ = f.Close()
		_ = unix.Unlinkat(dirFd, tmp, 0)
		return fmt.Errorf("write %s/%s: %w", relDir, tmp, err)
	}
	if err := f.Close(); err != nil {
		_ = unix.Unlinkat(dirFd, tmp, 0)
		return fmt.Errorf("close %s/%s: %w", relDir, tmp, err)
	}
	var st unix.Stat_t
	if err := unix.Fstatat(dirFd, name, &st, unix.AT_SYMLINK_NOFOLLOW); err == nil && st.Mode&unix.S_IFMT != unix.S_IFREG {
		_ = unix.Unlinkat(dirFd, tmp, 0)
		return fmt.Errorf("%w: %s/%s exists and is not a regular file", ErrTreeRefused, relDir, name)
	}
	if err := unix.Renameat(dirFd, tmp, dirFd, name); err != nil {
		_ = unix.Unlinkat(dirFd, tmp, 0)
		return fmt.Errorf("rename %s/%s: %w", relDir, name, err)
	}
	return nil
}

// ReadFileInTree reads the small regular file <hostBase>/<relDir>/<name>
// (at most maxBytes) without following a symlink at any component. ok is
// false when any component or the file is absent. A file that is not a
// regular file, or is larger than maxBytes, is ErrTreeRefused.
func ReadFileInTree(hostBase, relDir, name string, maxBytes int64) (data []byte, ok bool, err error) {
	if err := checkFileName(name); err != nil {
		return nil, false, err
	}
	dirFd, err := openTreeDir(hostBase, relDir, false)
	if errors.Is(err, errTreeAbsent) {
		return nil, false, nil
	}
	if err != nil {
		return nil, false, err
	}
	defer func() { _ = unix.Close(dirFd) }()
	fd, err := unix.Openat(dirFd, name, unix.O_RDONLY|unix.O_NOFOLLOW|unix.O_NONBLOCK|unix.O_CLOEXEC, 0)
	if err != nil {
		if errors.Is(err, unix.ENOENT) {
			return nil, false, nil
		}
		return nil, false, fmt.Errorf("%w: open %s/%s: %w", ErrTreeRefused, relDir, name, err)
	}
	f := os.NewFile(uintptr(fd), name)
	defer func() { _ = f.Close() }()
	var st unix.Stat_t
	if err := unix.Fstat(fd, &st); err != nil {
		return nil, false, err
	}
	if st.Mode&unix.S_IFMT != unix.S_IFREG || st.Size > maxBytes {
		return nil, false, fmt.Errorf("%w: %s/%s is not a small regular file", ErrTreeRefused, relDir, name)
	}
	data, err = io.ReadAll(io.LimitReader(f, maxBytes))
	if err != nil {
		return nil, false, err
	}
	return data, true, nil
}

// RemoveFileInTree removes the file <hostBase>/<relDir>/<name> without
// following a symlink at any directory component (a symlink at name itself
// is unlinked, never followed). An absent file or directory is nothing to
// do.
func RemoveFileInTree(hostBase, relDir, name string) error {
	if err := checkFileName(name); err != nil {
		return err
	}
	dirFd, err := openTreeDir(hostBase, relDir, false)
	if errors.Is(err, errTreeAbsent) {
		return nil
	}
	if err != nil {
		return err
	}
	defer func() { _ = unix.Close(dirFd) }()
	if err := unix.Unlinkat(dirFd, name, 0); err != nil && !errors.Is(err, unix.ENOENT) {
		return fmt.Errorf("remove %s/%s: %w", relDir, name, err)
	}
	return nil
}

// ListDirInTree lists the entry names of the directory <hostBase>/<relDir>
// without following a symlink at any component. ok is false when a
// component is absent.
func ListDirInTree(hostBase, relDir string) (names []string, ok bool, err error) {
	dirFd, err := openTreeDir(hostBase, relDir, false)
	if errors.Is(err, errTreeAbsent) {
		return nil, false, nil
	}
	if err != nil {
		return nil, false, err
	}
	defer func() { _ = unix.Close(dirFd) }()
	names, err = readDirNames(dirFd)
	if err != nil {
		return nil, false, err
	}
	return names, true, nil
}

// DirExistsInTree reports whether <hostBase>/<relDir> exists as a plain
// directory, reached without following a symlink at any component.
func DirExistsInTree(hostBase, relDir string) (bool, error) {
	dirFd, err := openTreeDir(hostBase, relDir, false)
	if errors.Is(err, errTreeAbsent) {
		return false, nil
	}
	if err != nil {
		return false, err
	}
	_ = unix.Close(dirFd)
	return true, nil
}

// TreeDirState reports whether <hostBase>/<relDir> exists as a plain
// directory, reached without following a symlink at any component (as
// DirExistsInTree), and, when it does not, whether the host base itself has
// no entries at all. Both answers come from the one host-base descriptor:
// the walk below it never follows a symlink, and the emptiness read takes at
// most one name from that descriptor (no second path-based open). A read
// error is returned as an error, never as "empty".
func TreeDirState(hostBase, relDir string) (exists, baseEmpty bool, err error) {
	if _, err := splitRelPath(relDir); err != nil {
		return false, false, fmt.Errorf("%w: %w", ErrTreeRefused, err)
	}
	baseFd, err := unix.Open(hostBase, unix.O_RDONLY|unix.O_DIRECTORY|unix.O_CLOEXEC, 0)
	if err != nil {
		return false, false, fmt.Errorf("%w: open host base %q: %w", ErrTreeRefused, hostBase, err)
	}
	defer func() { _ = unix.Close(baseFd) }()
	fd, ok, err := openExistingDirPathNoFollow(baseFd, relDir)
	if err != nil {
		return false, false, fmt.Errorf("%w: %q: %w", ErrTreeRefused, relDir, err)
	}
	if ok {
		_ = unix.Close(fd)
		return true, false, nil
	}
	name, err := firstDirName(baseFd)
	if err != nil {
		return false, false, fmt.Errorf("read host base %q: %w", hostBase, err)
	}
	return false, name == "", nil
}

// firstDirName returns the first entry name of the already-open directory
// fd dirFd other than "." and "..", or "" when it has none, via raw getdents
// (unix.ReadDirent) on the fd alone. Unlike readDirNames, ENOENT (the
// directory removed under the fd) is an error here: the caller must not read
// a vanished directory as an empty one.
func firstDirName(dirFd int) (string, error) {
	buf := make([]byte, 4096)
	for {
		n, err := unix.ReadDirent(dirFd, buf)
		if err != nil {
			if errors.Is(err, unix.EINTR) {
				continue
			}
			return "", err
		}
		if n <= 0 {
			return "", nil
		}
		if _, _, names := unix.ParseDirent(buf[:n], 1, nil); len(names) > 0 {
			return names[0], nil
		}
	}
}

// errTreeAbsent is openTreeDir's "a component does not exist".
var errTreeAbsent = errors.New("tree component absent")

// openTreeDir opens the directory <hostBase>/<relDir> without following a
// symlink at any component, creating the last component when createLast is
// set. An absent component (when not created) is errTreeAbsent; an unusable
// host base or a refused component is ErrTreeRefused.
func openTreeDir(hostBase, relDir string, createLast bool) (int, error) {
	comps, err := splitRelPath(relDir)
	if err != nil {
		return -1, fmt.Errorf("%w: %w", ErrTreeRefused, err)
	}
	baseFd, err := unix.Open(hostBase, unix.O_RDONLY|unix.O_DIRECTORY|unix.O_CLOEXEC, 0)
	if err != nil {
		return -1, fmt.Errorf("%w: open host base %q: %w", ErrTreeRefused, hostBase, err)
	}
	defer func() { _ = unix.Close(baseFd) }()
	parentFd := baseFd
	if len(comps) > 1 {
		fd, ok, err := openExistingDirPathNoFollow(baseFd, strings.Join(comps[:len(comps)-1], "/"))
		if err != nil {
			return -1, fmt.Errorf("%w: %q: %w", ErrTreeRefused, relDir, err)
		}
		if !ok {
			return -1, errTreeAbsent
		}
		parentFd = fd
		defer func() { _ = unix.Close(fd) }()
	}
	leaf := comps[len(comps)-1]
	fd, ok, err := openExistingDirNoFollow(parentFd, leaf)
	if err != nil {
		return -1, fmt.Errorf("%w: %q: %w", ErrTreeRefused, relDir, err)
	}
	if ok {
		return fd, nil
	}
	if !createLast {
		return -1, errTreeAbsent
	}
	if err := unix.Mkdirat(parentFd, leaf, 0o755); err != nil && !errors.Is(err, unix.EEXIST) {
		return -1, fmt.Errorf("create %q: %w", relDir, err)
	}
	fd, ok, err = openExistingDirNoFollow(parentFd, leaf)
	if err != nil || !ok {
		return -1, fmt.Errorf("%w: %q: created but not openable: %v", ErrTreeRefused, relDir, err)
	}
	return fd, nil
}

// checkFileName refuses a name that is not one plain path element.
func checkFileName(name string) error {
	if name == "" || name == "." || name == ".." || strings.ContainsAny(name, "/\x00") {
		return fmt.Errorf("%w: invalid file name %q", ErrTreeRefused, name)
	}
	return nil
}

// splitRelPath splits a relative path into its components, refusing an
// absolute path and an empty, "." or ".." component.
func splitRelPath(relPath string) ([]string, error) {
	slashed := filepath.ToSlash(relPath)
	if slashed == "" || strings.HasPrefix(slashed, "/") || filepath.IsAbs(relPath) {
		return nil, fmt.Errorf("path %q is not a relative path", relPath)
	}
	comps := strings.Split(slashed, "/")
	for _, c := range comps {
		if c == "" || c == "." || c == ".." {
			return nil, fmt.Errorf("path %q is not a clean relative path", relPath)
		}
	}
	return comps, nil
}

// openExistingDirNoFollow opens the existing directory component `comp`
// under parentFd, refusing to follow it if it's a symlink (O_NOFOLLOW) or
// use it if it's not a directory (O_DIRECTORY) — but, unlike
// openOrCreateDirNoFollow in walk_unix.go, never creates it. Returns
// (-1, false, nil) if comp doesn't exist at all. comp must be a single path
// component: like openat(2) itself, O_NOFOLLOW here only refuses a symlink
// AT comp, not at an intermediate component if comp contains a "/" — see
// openExistingDirPathNoFollow for a relative path of arbitrarily many
// components. A "." or ".." comp is refused: O_NOFOLLOW does not stop ".."
// (a real parent entry), so opening it would leave parentFd's directory.
func openExistingDirNoFollow(parentFd int, comp string) (fd int, existed bool, err error) {
	if comp == "." || comp == ".." {
		return -1, false, &confinementError{fmt.Sprintf("path component %q; refusing", comp)}
	}
	const openFlags = unix.O_RDONLY | unix.O_DIRECTORY | unix.O_NOFOLLOW | unix.O_CLOEXEC
	fd, err = unix.Openat(parentFd, comp, openFlags, 0)
	if err == nil {
		return fd, true, nil
	}
	if errors.Is(err, unix.ENOENT) {
		return -1, false, nil
	}
	return -1, false, classifyComponentOpenError(parentFd, comp, err)
}

// openExistingDirPathNoFollow opens the existing, possibly multi-component
// relative path relPath under baseFd one component at a time via
// openExistingDirNoFollow, so a symlink at ANY component —
// not just the last — is refused. Returns (-1, false, nil) if any component
// along the way doesn't exist (matching openExistingDirNoFollow's
// "not existing at all is not an error" contract): there is nothing under
// that path, existing or not, for the caller to remove.
//
// A "." or ".." component is refused before anything is opened, so the walk
// stays under baseFd even when a caller passes a path that did not go
// through config.ValidateSubPathRoot.
func openExistingDirPathNoFollow(baseFd int, relPath string) (fd int, existed bool, err error) {
	comps := strings.Split(filepath.ToSlash(relPath), "/")
	for _, comp := range comps {
		if comp == "." || comp == ".." {
			return -1, false, &confinementError{fmt.Sprintf(
				"path %q has a %q component; refusing", relPath, comp)}
		}
	}
	currentFd := baseFd
	opened := false
	for _, comp := range comps {
		if comp == "" {
			continue
		}
		nextFd, exists, walkErr := openExistingDirNoFollow(currentFd, comp)
		if opened {
			_ = unix.Close(currentFd)
		}
		if walkErr != nil {
			return -1, false, walkErr
		}
		if !exists {
			return -1, false, nil
		}
		currentFd = nextFd
		opened = true
	}
	if !opened {
		return -1, false, fmt.Errorf("empty path")
	}
	return currentFd, true, nil
}

// removeTreeContents removes every entry under the directory referenced by
// dirFd, recursively, via unlinkat/rmdir relative to dirFd and the fds of
// any subdirectories it opens along the way — never through a symlink (a
// symlink entry is unlinked directly, never opened/followed/recursed into).
// It does not remove dirFd's own directory entry; the caller does that once
// this returns. ENOENT on any individual entry (or on the directory read
// itself — see readDirNames) is tolerated (concurrent deletion, e.g.
// another actor removing the same tree, or a raced individual cleanup)
// rather than treated as a failure of the whole operation.
//
// depth is the current recursion depth (0 at the top-level shared-dirs
// call), capped at maxDeleteTreeDepth: a subtree at the cap is logged and
// left in place, and the call continues on to its siblings. The subtree
// left behind is reported back as part of the aggregated error this
// returns, so the caller can log a partial cleanup rather than believe the
// tree is now empty.
func removeTreeContents(dirFd int, depth int) error {
	names, err := readDirNames(dirFd)
	if err != nil {
		return fmt.Errorf("read directory: %w", err)
	}
	var errs []error
	for _, name := range names {
		var st unix.Stat_t
		if err := unix.Fstatat(dirFd, name, &st, unix.AT_SYMLINK_NOFOLLOW); err != nil {
			if errors.Is(err, unix.ENOENT) {
				continue
			}
			return fmt.Errorf("stat %q: %w", name, err)
		}
		if st.Mode&unix.S_IFMT == unix.S_IFDIR {
			if depth+1 > maxDeleteTreeDepth {
				slog.Warn("server.shared_dir_storage: directory tree exceeds the delete depth cap; leaving this subtree in place",
					"name", name, "depth", depth+1, "cap", maxDeleteTreeDepth)
				errs = append(errs, fmt.Errorf("subtree %q is more than %d levels deep; left in place", name, maxDeleteTreeDepth))
				continue
			}
			childFd, err := unix.Openat(dirFd, name, unix.O_RDONLY|unix.O_DIRECTORY|unix.O_NOFOLLOW|unix.O_CLOEXEC, 0)
			if err != nil {
				if errors.Is(err, unix.ENOENT) {
					continue
				}
				return fmt.Errorf("open %q: %w", name, err)
			}
			walkErr := removeTreeContents(childFd, depth+1)
			_ = unix.Close(childFd)
			if walkErr != nil {
				// A deeper subtree hit the cap (or some other entry under it
				// failed); this directory is therefore not empty, so don't
				// try to rmdir it -- just record the reason and move on to
				// this level's remaining siblings.
				errs = append(errs, walkErr)
				continue
			}
			if err := unix.Unlinkat(dirFd, name, unix.AT_REMOVEDIR); err != nil && !errors.Is(err, unix.ENOENT) {
				return fmt.Errorf("remove dir %q: %w", name, err)
			}
			continue
		}
		// Regular file, symlink (unlinked directly, never followed), or
		// any other type (socket/fifo/device) — all removed the same way:
		// arbitrary leaf CONTENT is whatever an agent wrote and is safe to
		// delete regardless of type, as long as a symlink is never
		// traversed to get there, which Unlinkat never does.
		if err := unix.Unlinkat(dirFd, name, 0); err != nil && !errors.Is(err, unix.ENOENT) {
			return fmt.Errorf("remove %q: %w", name, err)
		}
	}
	return errors.Join(errs...)
}

// readDirNames reads every directory entry name from the already-open fd
// dirFd (excluding "." and ".."), via raw getdents (unix.ReadDirent),
// without any path resolution — the fd is all this ever touches.
//
// A concurrent actor (another deletion call racing this one) can rmdir the
// directory dirFd refers to between when the caller opened it and when this
// reads it; Linux's getdents64 reports that as ENOENT, not an empty read.
// Treated the same as "nothing left to read": zero names, no error -- "the
// directory is already gone" is exactly the outcome this whole function is
// trying to reach.
func readDirNames(dirFd int) ([]string, error) {
	var names []string
	buf := make([]byte, 8192)
	for {
		n, err := unix.ReadDirent(dirFd, buf)
		if err != nil {
			if errors.Is(err, unix.EINTR) {
				continue
			}
			if errors.Is(err, unix.ENOENT) {
				return names, nil
			}
			return nil, err
		}
		if n <= 0 {
			return names, nil
		}
		_, _, names = unix.ParseDirent(buf[:n], -1, names)
	}
}
