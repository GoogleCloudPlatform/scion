// Browser web sessions for hub-issued test identities (ptone/scion#4240,
// phase WS1).
//
// An issuer mints a single-use web-login code for one of its test
// identities (POST /api/v1/test-identities/{id}/web-login-code). A browser
// driver redeems the code once (POST /auth/test-identity/redeem, JSON body)
// and receives a web session as that identity. The session holds no hub
// access token and no refresh token: every API request through the web
// server gets a freshly minted access token that lives at most five minutes
// and never past the identity's expiry, so the per-request user-row block
// (testFixtureRejection) still runs on every call.
//
// Availability (testIdentityWebSessionGate):
//   - test identities are on (the member level);
//   - the hub has a hub-local web session key, generated by
//     `scion server test-infra mark` and read from the marker row at
//     startup (DEC-8). With no usable key, web sessions are unavailable and
//     the member tier still starts. There is never a fallback to a key
//     derived from the shared session secret;
//   - the hub is not in proxy auth mode. Proxy hubs need the driver binding
//     of phase WS2; until then redeem answers 403 there and any marked
//     session is cleared.
//
// A test identity web session is two cookies: the ordinary scion_sess
// session (uid, email, role, sessGen and the marker values) and the
// scion_ti marker cookie, signed and encrypted with keys expanded from the
// hub-local web session key only. A session counts as a test identity
// session only when scion_ti decodes with those keys and agrees with
// scion_sess (fixtureSessionValid). The human session store's keys never
// sign scion_ti, so a scion_sess cookie made with only the shared session
// keys is not a valid test identity session; it is cleared.
//
// Only kind=test_fixture identities (member and viewer) are admitted. The
// admin kinds get web sessions only behind their own gate (phase WS4).

// Test identity web session constants.
const (
	// testIdentityWebCodeTTL is how long a web-login code can be redeemed.
	testIdentityWebCodeTTL = 5 * time.Minute
	// testIdentityWebTokenTTL caps the access token minted per request for
	// a test identity web session.
	testIdentityWebTokenTTL = 5 * time.Minute
	// testIdentityWebCodePrefix starts every web-login code, so leaked
	// codes are easy to recognise.
	testIdentityWebCodePrefix = "scion_tiwc_"
	// testIdentityWebRedeemMaxBody bounds the redeem request body.
	testIdentityWebRedeemMaxBody = 1 << 10
	// testIdentitySessionCookie is the marker cookie name.
	testIdentitySessionCookie = "scion_ti"
	// testIdentityWebHashPrefixLen is the number of hex digits of the code
	// hash recorded in audit and logs (never the code).
	testIdentityWebHashPrefixLen = 8

	// Labels that expand the hub-local web session key into the cookie
	// hash and block keys. They are used nowhere else.
	testIdentityWebHashKeyLabel  = "scion-test-identity-web-session-hash-v1"
	testIdentityWebBlockKeyLabel = "scion-test-identity-web-session-block-v1"
)

// Session keys of a test identity web session (in scion_sess).
const (
	sessKeyTIMarker = "tiMarker" // code id of the redeemed code
	sessKeyTIExpiry = "tiExpiry" // identity expiry, Unix milliseconds
	sessKeyTIDriver = "tiDriver" // verified driver principal; "" in WS1
)

// Mutation audit types and details.reason values.
const (
	testIdentityWebCodeIssueMutation     = "test_identity_web_code_issue"
	testIdentityWebSessionCreateMutation = "test_identity_web_session_create"
	testIdentityWebSessionRefuseMutation = "test_identity_web_session_refused"

	// testIdentityWebReasonUnavailable is the details.reason of a 404 from
	// either route while web sessions are unavailable; details.cause names
	// why (testIdentityWebSessionGate).
	testIdentityWebReasonUnavailable = "test_identity_web_sessions_unavailable"

	testIdentityWebCauseDisabled  = "test_identities_disabled"
	testIdentityWebCauseNoKey     = "web_session_key_unavailable"
	testIdentityWebCauseProxyMode = "proxy_mode"

	testIdentityWebErrInvalidCode = "invalid_or_expired_code"
	testIdentityWebErrEnded       = "test_identity_session_ended"
)

// TestIdentityWebSessionKey is the hub-local web session key input of
// ServerConfig: the 64-byte key cmd read from the test infrastructure marker
// at startup, or, when there is none, Unavailable naming why (for example
// "marker_absent", "key_missing", "key_invalid", "marker_hub_mismatch",
// "marker_unreadable"). The key is never logged.
type TestIdentityWebSessionKey struct {
	Key         []byte
	Unavailable string
}

// String hides the key from %v and %+v formatting.
func (k TestIdentityWebSessionKey) String() string {
	if len(k.Key) == 0 {
		return fmt.Sprintf("TestIdentityWebSessionKey{unavailable: %q}", k.Unavailable)
	}
	return "TestIdentityWebSessionKey{present}"
}

// GoString hides the key from %#v formatting.
func (k TestIdentityWebSessionKey) GoString() string { return k.String() }

// testIdentityWebKeyLen is the required key length (testinfra.WebSessionKeyLen).
const testIdentityWebKeyLen = 64

// testIdentityWebState is the server-side state of test identity web
// sessions, fixed in New: the marker cookie codec, or nil and the reason the
// key is unusable.
type testIdentityWebState struct {
	codec       *securecookie.SecureCookie
	unavailable string
}

// deriveTestIdentityWebKeys expands the hub-local key into the 32-byte HMAC
// key and the 32-byte AES-256 key of the marker cookie, each with its own
// label.
func deriveTestIdentityWebKeys(key []byte) (hashKey, blockKey []byte) {
	h := sha256.Sum256(append([]byte(testIdentityWebHashKeyLabel+":"), key...))
	b := sha256.Sum256(append([]byte(testIdentityWebBlockKeyLabel+":"), key...))
	return h[:], b[:]
}

// newTestIdentityWebState builds the marker cookie codec from k. A missing,
// short, long or all-zero key leaves web sessions unavailable.
func newTestIdentityWebState(k TestIdentityWebSessionKey) testIdentityWebState {
	switch {
	case len(k.Key) == 0:
		reason := k.Unavailable
		if reason == "" {
			reason = "key_missing"
		}
		return testIdentityWebState{unavailable: reason}
	case len(k.Key) != testIdentityWebKeyLen || bytes.Equal(k.Key, make([]byte, testIdentityWebKeyLen)):
		return testIdentityWebState{unavailable: "key_invalid"}
	}
	hashKey, blockKey := deriveTestIdentityWebKeys(k.Key)
	codec := securecookie.New(hashKey, blockKey)
	codec.SetSerializer(securecookie.JSONEncoder{})
	// The cookie timestamp window is the longest identity lifetime; the
	// identity's own expiry is checked separately on every request.
	codec.MaxAge(int(testIdentityMaxLifetime / time.Second))
	return testIdentityWebState{codec: codec}
}

// testIdentityWebSessionGate reports whether test identity web sessions are
// available on this hub, and the cause when they are not.
func (s *Server) testIdentityWebSessionGate() (bool, string) {
	switch {
	case !s.testIdentities.enabled:
		return false, testIdentityWebCauseDisabled
	case s.testIdentityWeb.codec == nil:
		return false, testIdentityWebCauseNoKey
	case s.config.AuthMode == "proxy":
		return false, testIdentityWebCauseProxyMode
	}
	return true, ""
}

// logTestIdentityWebSessionState writes the startup log line for test
// identity web sessions. It never logs key material.
func (s *Server) logTestIdentityWebSessionState() {
	if !s.testIdentities.enabled {
		return
	}
	ok, cause := s.testIdentityWebSessionGate()
	if ok {
		slog.Info("Test identity web sessions are available: single-use web-login codes let a test identity hold a browser session on this hub")
		return
	}
	attrs := []any{"cause", cause}
	if cause == testIdentityWebCauseNoKey {
		attrs = append(attrs, "key_state", s.testIdentityWeb.unavailable)
	}
	slog.Warn("Test identity web sessions are unavailable on this hub; the member tier is unaffected", attrs...)
}

// testIdentityWebKindAdmitted reports whether u's kind may hold a web
// session in this release: kind=test_fixture only (member and viewer). The
// admin kinds are refused at mint, at redeem, and on every session check.
func testIdentityWebKindAdmitted(u *store.User) bool {
	return u != nil && u.IsTestFixture()
}

// writeTestIdentityWebUnavailable answers 404 with the unavailable reason.
func writeTestIdentityWebUnavailable(w http.ResponseWriter, cause string) {
	writeError(w, http.StatusNotFound, ErrCodeNotFound, "test identity web sessions are not available on this hub",
		map[string]interface{}{"reason": testIdentityWebReasonUnavailable, "cause": cause})
}

// newTestIdentityWebCode returns a fresh web-login code (256 random bits)
// and its hex SHA-256.
func newTestIdentityWebCode() (code, hash string, err error) {
	b := make([]byte, 32)
	if _, err := rand.Read(b); err != nil {
		return "", "", err
	}
	code = testIdentityWebCodePrefix + base64.RawURLEncoding.EncodeToString(b)
	return code, testIdentityWebCodeHash(code), nil
}

// testIdentityWebCodeHash returns the hex SHA-256 of code.
func testIdentityWebCodeHash(code string) string {
	sum := sha256.Sum256([]byte(code))
	return hex.EncodeToString(sum[:])
}

// testIdentityWebHashPrefix returns the audit-safe prefix of a code hash.
func testIdentityWebHashPrefix(hash string) string {
	if len(hash) < testIdentityWebHashPrefixLen {
		return hash
	}
	return hash[:testIdentityWebHashPrefixLen]
}

// TestIdentityWebCodeResponse is the response of POST
// /api/v1/test-identities/{id}/web-login-code. It is the only place the code
// ever appears.
type TestIdentityWebCodeResponse struct {
	Code      string    `json:"code"`
	CodeID    string    `json:"codeId"`
	ExpiresAt time.Time `json:"expiresAt"`
}

// handleIssueTestIdentityWebCode handles POST
// /api/v1/test-identities/{id}/web-login-code.
func (s *Server) handleIssueTestIdentityWebCode(w http.ResponseWriter, r *http.Request) {
	ctx := r.Context()
	caller, ok := s.testIdentityCaller(w, r)
	if !ok {
		return
	}
	if ok, cause := s.testIdentityWebSessionGate(); !ok {
		writeTestIdentityWebUnavailable(w, cause)
		return
	}
	// The body is optional and has no fields.
	var req struct{}
	if err := decodeTestIdentityBody(r, &req); err != nil {
		BadRequest(w, err.Error())
		return
	}

	id := r.PathValue("id")
	u, err := s.store.GetUser(ctx, id)
	// One answer for a missing user, a user of a kind that cannot hold a
	// web session, and an identity the caller did not issue, as for
	// re-issue: the route is no user-existence oracle.
	if errors.Is(err, store.ErrNotFound) || errors.Is(err, store.ErrInvalidInput) || (err == nil && (!testIdentityWebKindAdmitted(u) || !canManageTestIdentity(ctx, caller, u))) {
		NotFound(w, "test identity")
		return
	}
	if err != nil {
		writeErrorFromErr(w, err, "")
		return
	}
	now := s.testIdentities.clock()
	if u.ExpiresAt == nil || !now.Before(*u.ExpiresAt) {
		writeError(w, http.StatusConflict, ErrCodeConflict, "test identity has expired",
			map[string]interface{}{"reason": testIdentityReasonExpired})
		return
	}
	if u.Status != store.UserStatusActive {
		writeError(w, http.StatusConflict, ErrCodeConflict, "test identity is not active", nil)
		return
	}
	if !s.testIdentityAllow(w, testIdentityRateKey(ctx, caller)) {
		return
	}

	code, hash, err := newTestIdentityWebCode()
	if err != nil {
		InternalError(w)
		return
	}
	expiresAt := now.Add(testIdentityWebCodeTTL)
	if expiresAt.After(*u.ExpiresAt) {
		expiresAt = *u.ExpiresAt
	}
	auditActor := s.buildAuditActorFromContext(ctx)
	row := &store.TestIdentityLoginCode{
		UserID:             u.ID,
		CodeHash:           hash,
		IssuedBy:           caller.ID(),
		IssuerCredentialID: auditActor.CredentialID,
		ExpiresAt:          expiresAt,
		Created:            now,
	}
	err = s.store.WithTx(ctx, func(tx store.Store) error {
		if err := tx.ReplaceTestIdentityLoginCode(ctx, row); err != nil {
			return fmt.Errorf("store web-login code: %w", err)
		}
		summary, _ := json.Marshal(struct {
			UserID         string `json:"user_id"`
			CodeID         string `json:"code_id"`
			CodeExpiresAt  string `json:"code_expires_at"`
			IssuedBy       string `json:"issued_by"`
			CredentialKind string `json:"credential_kind"`
		}{u.ID, row.ID, expiresAt.UTC().Format(time.RFC3339), caller.ID(), auditActor.CredentialKind})
		record := &store.MutationAuditRecord{
			MutationType: testIdentityWebCodeIssueMutation,
			TargetType:   testIdentityAuditTargetType,
			TargetID:     u.ID,
			AfterSummary: string(summary),
			Timestamp:    now,
		}
		auditActor.ApplyActor(record)
		return s.testIdentities.hooks.writeAudit(ctx, tx, record)
	})
	if err != nil {
		switch {
		case errors.Is(err, store.ErrAlreadyExists), isTransientIssuanceConflict(err):
			w.Header().Set("Retry-After", "1")
			writeError(w, http.StatusTooManyRequests, ErrCodeRateLimited, "web-login code issuance is busy; retry shortly",
				map[string]interface{}{"reason": testIdentityReasonBusy})
		default:
			slog.ErrorContext(ctx, "test identity web-login code issue failed", "test_identity_id", u.ID, "error", err)
			InternalError(w)
		}
		return
	}
	slog.InfoContext(ctx, "test identity web-login code issued", "test_identity_id", u.ID, "code_id", row.ID,
		"issuer_id", caller.ID(), "code_hash_prefix", testIdentityWebHashPrefix(hash))
	w.Header().Set("Cache-Control", "no-store")
	writeJSON(w, http.StatusCreated, TestIdentityWebCodeResponse{Code: code, CodeID: row.ID, ExpiresAt: expiresAt})
}

