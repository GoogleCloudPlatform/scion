// SetTestIdentityWebSessions connects the web server to the hub's test
// identity state: the feature switch, the clock, the availability gate and
// the marker cookie codec. Without it the web server has no test identity
// web sessions: redeem answers 404 and every marked session is cleared.
func (ws *WebServer) SetTestIdentityWebSessions(s *Server) {
	ws.testIdentityHub = s
}

// testIdentityWebGate is the web server's view of
// Server.testIdentityWebSessionGate. It also refuses on its own proxy auth
// configuration, so either side being in proxy mode fails closed.
func (ws *WebServer) testIdentityWebGate() (bool, string) {
	if ws.testIdentityHub == nil {
		return false, testIdentityWebCauseDisabled
	}
	if ws.config.AuthMode == "proxy" {
		return false, testIdentityWebCauseProxyMode
	}
	return ws.testIdentityHub.testIdentityWebSessionGate()
}

// testIdentitiesEnabled reports the member-level switch, for
// testFixtureRejection.
func (ws *WebServer) testIdentitiesEnabled() bool {
	return ws.testIdentityHub != nil && ws.testIdentityHub.testIdentities.enabled
}

// testIdentityNow is the clock of every test identity session check: the
// hub's test identity clock, so tests can move it.
func (ws *WebServer) testIdentityNow() time.Time {
	if ws.testIdentityHub == nil {
		return time.Now()
	}
	return ws.testIdentityHub.testIdentities.clock()
}

// testIdentityCodec returns the marker cookie codec, or nil.
func (ws *WebServer) testIdentityCodec() *securecookie.SecureCookie {
	if ws.testIdentityHub == nil {
		return nil
	}
	return ws.testIdentityHub.testIdentityWeb.codec
}

// tiMarkerValue is the content of the scion_ti marker cookie.
type tiMarkerValue struct {
	UserID string `json:"u"`
	CodeID string `json:"c"`
	// Expiry is the identity expiry, Unix milliseconds.
	Expiry int64  `json:"e"`
	Driver string `json:"d"`
}

// readTestIdentityMarker decodes the request's marker cookie. present is
// true when the cookie exists at all; m is nil when it does not decode with
// this hub's codec.
func (ws *WebServer) readTestIdentityMarker(r *http.Request) (m *tiMarkerValue, present bool) {
	c, err := r.Cookie(testIdentitySessionCookie)
	if err != nil || c.Value == "" {
		return nil, false
	}
	codec := ws.testIdentityCodec()
	if codec == nil {
		return nil, true
	}
	var v tiMarkerValue
	if err := codec.Decode(testIdentitySessionCookie, c.Value, &v); err != nil {
		return nil, true
	}
	return &v, true
}

// testIdentityCookie returns a marker cookie with the session cookie's
// attributes.
func (ws *WebServer) testIdentityCookie(value string, maxAge int) *http.Cookie {
	c := &http.Cookie{
		Name:     testIdentitySessionCookie,
		Value:    value,
		Path:     "/",
		HttpOnly: true,
		Secure:   strings.HasPrefix(ws.config.BaseURL, "https://"),
		SameSite: http.SameSiteLaxMode,
		MaxAge:   maxAge,
	}
	if maxAge > 0 {
		c.Expires = time.Now().Add(time.Duration(maxAge) * time.Second)
	} else if maxAge < 0 {
		c.Expires = time.Unix(1, 0)
	}
	return c
}

// isTestIdentitySessionCandidate reports whether the request carries any
// test identity hint: a marker cookie, marker values in the session, or a
// session email in the reserved test identity domain. These inputs are
// caller-controlled, so they can only make a session a test identity
// session, never rule it out: classifyTestIdentitySession also decides
// from the user row. Only the classifier and proxyAuth's outright refusal
// use it.
func (ws *WebServer) isTestIdentitySessionCandidate(r *http.Request, session *sessions.Session) bool {
	if _, present := ws.readTestIdentityMarker(r); present {
		return true
	}
	if v, _ := session.Values[sessKeyTIMarker].(string); v != "" {
		return true
	}
	return isReservedTestIdentityEmail(sessionString(session, sessKeyUserEmail))
}

// tiSessionState is the outcome of classifyTestIdentitySession.
type tiSessionState int

const (
	// tiSessionNotFixture: the session user is an ordinary account (or
	// the session has no user); the caller continues as for any session.
	tiSessionNotFixture tiSessionState = iota
	// tiSessionUserMissing: the session names a user that does not exist
	// and nothing marks it as a test identity session; the caller keeps
	// its own handling for a deleted account.
	tiSessionUserMissing
	// tiSessionValid: a test identity web session that passes
	// fixtureSessionValid.
	tiSessionValid
	// tiSessionInvalid: a session that must be cleared.
	tiSessionInvalid
	// tiSessionStoreError: the user row could not be read; fail closed
	// with 500 and keep the session.
	tiSessionStoreError
	// tiSessionUnverifiable: test identities are on but no store is
	// wired, so the row cannot be read; deny without clearing.
	tiSessionUnverifiable
)

type tiSessionResult struct {
	state  tiSessionState
	reason string
	row    *store.User
	marker *tiMarkerValue
}

// classifyTestIdentitySession is the one decision every web session
// consumer makes before it honours a scion_sess session: sessionToBearer,
// sessionAuth, devAuth, /auth/me, the event stream, logout and redeem
// (proxyAuth refuses every test identity session outright). It is
// row-authoritative: whenever the session names a user it reads that
// user's row (or uses row, when the caller already read it), and the
// session is a test identity session when the row is kind test_fixture or
// in the reserved test identity domain, or when the request carries any
// test identity hint (a scion_ti cookie, marker values, a reserved-domain
// session email). Such a session is honoured only when fixtureSessionValid
// passes. The session's own email is never what admits it.
//
// On a store error the classifier answers tiSessionStoreError; every
// authority surface fails closed on it. /auth/me alone, which grants no
// authority, keeps its degraded session-fields answer for an unhinted
// session (handleAuthMe).
//
// With no store wired the row cannot be read. While test identities are
// on that is tiSessionUnverifiable (callers deny); while they are off,
// the session is treated as ordinary, and any test identity row is still
// refused by the hub's per-request user-row block (testFixtureRejection,
// test_identities_disabled).
func (ws *WebServer) classifyTestIdentitySession(r *http.Request, session *sessions.Session, row *store.User) tiSessionResult {
	uid, _ := session.Values[sessKeyUserID].(string)
	hinted := ws.isTestIdentitySessionCandidate(r, session)
	if uid == "" {
		if hinted {
			return tiSessionResult{state: tiSessionInvalid, reason: "no_session_user"}
		}
		return tiSessionResult{state: tiSessionNotFixture}
	}
	if row == nil {
		if ws.store == nil {
			switch {
			case hinted:
				return tiSessionResult{state: tiSessionInvalid, reason: "no_store"}
			case ws.testIdentitiesEnabled():
				return tiSessionResult{state: tiSessionUnverifiable, reason: "no_store"}
			default:
				return tiSessionResult{state: tiSessionNotFixture}
			}
		}
		// Fast path: a user already read as an ordinary account (neither
		// kind test_fixture nor a reserved-domain email: the cached value
		// is exactly the row test below, so a cached answer always equals
		// the uncached one) is answered without a row read when there is
		// no hint. The trigger set for a full read is exactly: a hint, a
		// cached test identity row, or no cache entry (a miss always reads
		// the row; it never yields NotFixture unread). The cache cannot
		// go stale: kind is Immutable (pkg/ent/schema/user.go), user IDs
		// are fresh UUIDs never reused, and an email never crosses the
		// reserved domain in either direction (CreateUser refuses it;
		// update builders keep an email on its side:
		// TestUpdateUser_EmailStaysOnItsSideOfTheFixtureDomain).
		if !hinted && ws.testIdentityKindCached(uid) == tiKindHuman {
			return tiSessionResult{state: tiSessionNotFixture}
		}
		u, err := ws.store.GetUser(r.Context(), uid)
		switch {
		case errors.Is(err, store.ErrNotFound), errors.Is(err, store.ErrInvalidInput):
			if hinted {
				return tiSessionResult{state: tiSessionInvalid, reason: "identity_not_found"}
			}
			return tiSessionResult{state: tiSessionUserMissing}
		case err != nil:
			return tiSessionResult{state: tiSessionStoreError, reason: "store_error"}
		}
		row = u
		ws.cacheTestIdentityKind(uid, row.IsTestFixture() || isReservedTestIdentityEmail(row.Email))
	}
	marker, _ := ws.readTestIdentityMarker(r)
	sessMarker, _ := session.Values[sessKeyTIMarker].(string)
	if !row.IsTestFixture() && !isReservedTestIdentityEmail(row.Email) &&
		!isReservedTestIdentityEmail(sessionString(session, sessKeyUserEmail)) && sessMarker == "" {
		// An ordinary account. A stray marker cookie (for example left
		// from an earlier test identity session in the same browser) is
		// ignored: it does not match this user and grants nothing.
		return tiSessionResult{state: tiSessionNotFixture, row: row}
	}
	if reason := ws.fixtureSessionValid(session, marker, row, ws.testIdentityNow()); reason != "" {
		return tiSessionResult{state: tiSessionInvalid, reason: reason, row: row}
	}
	return tiSessionResult{state: tiSessionValid, row: row, marker: marker}
}

// tiKind is a cached user kind for the classifier's fast path.
type tiKind int

const (
	tiKindUnknown tiKind = iota
	tiKindHuman
	tiKindFixture
)

// testIdentityKindCached returns the cached kind of uid. The cache reuses
// the authorization clamp's cache type and bound (testFixtureClampCache):
// only successful reads of an existing row are stored, a missing user and
// a read error never are.
func (ws *WebServer) testIdentityKindCached(uid string) tiKind {
	c := &ws.testIdentityKinds
	c.mu.Lock()
	defer c.mu.Unlock()
	v, ok := c.fixture[uid]
	switch {
	case !ok:
		return tiKindUnknown
	case v:
		return tiKindFixture
	default:
		return tiKindHuman
	}
}

// cacheTestIdentityKind records, after a successful row read, whether
// uid's row is a test identity row (kind test_fixture or a reserved-domain
// email).
func (ws *WebServer) cacheTestIdentityKind(uid string, fixture bool) {
	c := &ws.testIdentityKinds
	c.mu.Lock()
	defer c.mu.Unlock()
	if c.fixture == nil || len(c.fixture) >= testFixtureClampCacheMax {
		c.fixture = make(map[string]bool)
	}
	c.fixture[uid] = fixture
}

// isTestIdentitySession reports whether res is a test identity session
// (valid or not), which logout and redeem clear.
func (res tiSessionResult) isTestIdentitySession() bool {
	return res.state == tiSessionValid || res.state == tiSessionInvalid
}

// fixtureSessionValid returns "" when session (with its decoded marker
// cookie) is a valid test identity web session for row at now, and the
// refusal reason otherwise. Every condition is required:
//   - web sessions are available (member level on, hub-local key, not proxy
//     mode; WS1 refuses every marked session in proxy mode);
//   - the marker cookie decodes with this hub's key and names row, and the
//     session carries the same code id and expiry;
//   - row is an admitted kind (test_fixture), active, and passes
//     testFixtureRejection (feature on, not expired);
//   - now is before the session's identity expiry;
//   - the session generation equals the row's.
func (ws *WebServer) fixtureSessionValid(session *sessions.Session, marker *tiMarkerValue, row *store.User, now time.Time) string {
	if ok, cause := ws.testIdentityWebGate(); !ok {
		return "unavailable_" + cause
	}
	if marker == nil {
		return "marker_missing_or_invalid"
	}
	uid, _ := session.Values[sessKeyUserID].(string)
	sessMarker, _ := session.Values[sessKeyTIMarker].(string)
	sessExpiry, _ := session.Values[sessKeyTIExpiry].(int64)
	switch {
	case row == nil:
		return "identity_not_found"
	case uid == "" || uid != row.ID || marker.UserID != row.ID:
		return "user_mismatch"
	case sessMarker == "" || marker.CodeID != sessMarker:
		return "marker_mismatch"
	case marker.Expiry <= 0 || sessExpiry != marker.Expiry:
		return "expiry_mismatch"
	case marker.Driver != "":
		// No driver binding exists before WS2.
		return "driver_binding_unsupported"
	case !testIdentityWebKindAdmitted(row):
		return "kind_not_admitted"
	case row.Status != store.UserStatusActive:
		return "identity_not_active"
	}
	if reason := testFixtureRejection(row, ws.testIdentitiesEnabled(), now); reason != "" {
		return reason
	}
	if !now.Before(time.UnixMilli(marker.Expiry)) {
		return "session_expired"
	}
	cookieGen, _ := session.Values[sessKeySessionGeneration].(int64)
	if row.SessionGeneration != cookieGen {
		return "session_generation_mismatch"
	}
	return ""
}

