// clearTestIdentitySession deletes every session value, expires scion_sess
// and expires the marker cookie. It writes headers only.
func (ws *WebServer) clearTestIdentitySession(w http.ResponseWriter, r *http.Request, session *sessions.Session) {
	for key := range session.Values {
		delete(session.Values, key)
	}
	session.Options.MaxAge = -1
	if err := session.Save(r, w); err != nil {
		ws.logger().Warn("Failed to clear test identity session", "error", err)
	}
	http.SetCookie(w, ws.testIdentityCookie("", -1))
}

// dropTestIdentityValues removes the test identity values from a session
// that a login path (OAuth callback, test-login, proxy sign-in) is about to
// reuse for another user, and expires the marker cookie, so the new login
// is not read as a broken test identity session.
func (ws *WebServer) dropTestIdentityValues(w http.ResponseWriter, session *sessions.Session) {
	_, hadMarker := session.Values[sessKeyTIMarker]
	delete(session.Values, sessKeyTIMarker)
	delete(session.Values, sessKeyTIExpiry)
	delete(session.Values, sessKeyTIDriver)
	if hadMarker {
		ws.expireTestIdentityMarker(w)
	}
}

// expireTestIdentityMarker expires the marker cookie only.
func (ws *WebServer) expireTestIdentityMarker(w http.ResponseWriter) {
	http.SetCookie(w, ws.testIdentityCookie("", -1))
}

// testIdentityAccessToken mints the per-request access token of a valid
// test identity web session: the identity's own claims with client type
// web, living at most testIdentityWebTokenTTL and never past the session or
// identity expiry. It returns "" when nothing is left of either.
func (ws *WebServer) testIdentityAccessToken(res tiSessionResult) (string, error) {
	if ws.userTokenSvc == nil || res.row == nil || res.marker == nil || res.row.ExpiresAt == nil {
		return "", errors.New("test identity session token: not available")
	}
	now := ws.testIdentityNow()
	ttl := testIdentityWebTokenTTL
	if rem := time.UnixMilli(res.marker.Expiry).Sub(now); rem < ttl {
		ttl = rem
	}
	if rem := res.row.ExpiresAt.Sub(now); rem < ttl {
		ttl = rem
	}
	ttl = ttl.Truncate(time.Second)
	if ttl < time.Second {
		return "", errors.New("test identity session token: session ends within a second")
	}
	tok, _, err := ws.userTokenSvc.GenerateAccessTokenWithTTL(res.row.ID, res.row.Email, res.row.DisplayName, res.row.Role, ClientTypeWeb, ttl)
	return tok, err
}

