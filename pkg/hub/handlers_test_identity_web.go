// serveTestIdentitySessionEnded answers a request whose test identity
// session has ended: 401 with a static page for a browser, JSON otherwise.
func (ws *WebServer) serveTestIdentitySessionEnded(w http.ResponseWriter, r *http.Request) {
	w.Header().Set("Cache-Control", "no-store")
	if isBrowserRequest(r) {
		w.Header().Set("Content-Type", "text/html; charset=utf-8")
		w.WriteHeader(http.StatusUnauthorized)
		_, _ = io.WriteString(w, testIdentitySessionEndedPage)
		return
	}
	writeError(w, http.StatusUnauthorized, testIdentityWebErrEnded, "the test identity session has ended", nil)
}

