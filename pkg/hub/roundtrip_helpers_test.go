package hub

import (
	"io"
	"net/http"
	"strings"
)

// roundTripFunc and httpJSONResponse are shared test helpers for stubbing
// http.RoundTripper across both the !no_sqlite and no_sqlite test builds, so
// this file intentionally carries no build tag.

type roundTripFunc func(*http.Request) (*http.Response, error)

func (f roundTripFunc) RoundTrip(req *http.Request) (*http.Response, error) {
	return f(req)
}

func httpJSONResponse(status int, body string) *http.Response {
	return &http.Response{
		StatusCode: status,
		Status:     http.StatusText(status),
		Header:     make(http.Header),
		Body:       io.NopCloser(strings.NewReader(body)),
	}
}
