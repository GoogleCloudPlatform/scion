// updateGolden rewrites golden files from the hub's actual output:
//
//	go test ./pkg/hub -run TestCreateAgent_InheritedValuesGolden -update
//
// It is package-wide: a future golden test in this package must reuse it
// rather than register a second "update" flag, which would panic at init
// (one flag per package).
var updateGolden = flag.Bool("update", false, "rewrite golden files in testdata from the hub's output")

const inheritedGoldenPath = "testdata/agent-create-inherited-golden.json"

// inheritedGoldenFile is testdata/agent-create-inherited-golden.json. sources
// is the input, written by hand; dispatched is generated by this test with
// -update. The web's create form reads the same file: its inherited
// placeholders must equal dispatched for each case, so the two sides cannot
// drift.
type inheritedGoldenFile struct {
	Description string                `json:"description"`
	Cases       []inheritedGoldenCase `json:"cases"`
}

type inheritedGoldenCase struct {
	Tier       string            `json:"tier"`
	Sources    json.RawMessage   `json:"sources"`
	Dispatched map[string]string `json:"dispatched"`
}

// inheritedSources is the part of a case's sources this test applies.
type inheritedSources struct {
	Template struct {
		Config *store.TemplateConfig `json:"config"`
	} `json:"template"`
	ProjectSettings json.RawMessage `json:"projectSettings"`
	HubSettings     struct {
		DefaultModel           string `json:"defaultModel"`
		AutoExposePortsEnabled *bool  `json:"autoExposePortsEnabled"`
	} `json:"hubSettings"`
}

// TestCreateAgent_InheritedValuesGolden creates an agent with no config keys
// from each case's sources (a template, project settings saved through the
// settings API, and hub defaults) and records what the hub dispatches. With
// -update it writes that into the golden's dispatched values; otherwise it
// checks them. It also checks that the settings and public-settings APIs
// return the sources as the golden states them, since that is what the web
// reads.
//
// Scope: the hub-side dispatch only. Values the broker resolves on its own
// (a template's image, the --model argument) are not covered here.
func TestCreateAgent_InheritedValuesGolden(t *testing.T) {
	raw, err := os.ReadFile(filepath.FromSlash(inheritedGoldenPath))
	require.NoError(t, err)
	var golden inheritedGoldenFile
	require.NoError(t, json.Unmarshal(raw, &golden))
	require.Len(t, golden.Cases, 3, "one case per tier: template, project, hub")

	for i := range golden.Cases {
		tc := &golden.Cases[i]
		t.Run(tc.Tier, func(t *testing.T) {
			var src inheritedSources
			require.NoError(t, json.Unmarshal(tc.Sources, &src))
			dispatched := dispatchInheritedCase(t, tc.Tier, src)
			if *updateGolden {
				tc.Dispatched = dispatched
				return
			}
			assert.Equal(t, tc.Dispatched, dispatched,
				"rerun with -update if the hub's behaviour changed on purpose")
		})
	}

	// Write only when every case regenerated: a failed case keeps its old
	// dispatched values, and the file must not mix them with new ones.
	if *updateGolden && !t.Failed() {
		out, err := json.MarshalIndent(golden, "", "  ")
		require.NoError(t, err)
		require.NoError(t, os.WriteFile(filepath.FromSlash(inheritedGoldenPath), append(out, '\n'), 0o644))
	}
}

// dispatchInheritedCase applies src, creates an agent with no config keys and
// returns what the hub dispatched, by the web form's field key.
func dispatchInheritedCase(t *testing.T, tier string, src inheritedSources) map[string]string {
	t.Helper()
	srv, s, project, mockClient := setupThinkingLevelDispatch(t)
	ctx := context.Background()
	// Wire the hub's auto-expose default as the server's own dispatcher
	// does, so the hub tier reaches the request.
	disp := NewHTTPAgentDispatcherWithClient(s, mockClient, false, slog.Default())
	disp.SetAutoExposePortsDefaultProvider(srv.autoExposePortsDefault)
	srv.SetDispatcher(disp)

	// Hub tier.
	srv.mu.Lock()
	srv.config.AgentDefaults.DefaultModel = src.HubSettings.DefaultModel
	srv.config.AutoExposePortsDefault = src.HubSettings.AutoExposePortsEnabled
	srv.mu.Unlock()

	pub := doRequest(t, srv, http.MethodGet, "/api/v1/settings/public", nil)
	require.Equal(t, http.StatusOK, pub.Code, pub.Body.String())
	var pubBody map[string]interface{}
	require.NoError(t, json.Unmarshal(pub.Body.Bytes(), &pubBody))
	if src.HubSettings.DefaultModel != "" {
		assert.Equal(t, src.HubSettings.DefaultModel, pubBody["defaultModel"])
	}
	if src.HubSettings.AutoExposePortsEnabled != nil {
		assert.Equal(t, *src.HubSettings.AutoExposePortsEnabled, pubBody["autoExposePortsEnabled"])
	}

	// Project tier, through the settings API the web reads.
	put := doRequest(t, srv, http.MethodPut, "/api/v1/projects/"+project.ID+"/settings", src.ProjectSettings)
	require.Equal(t, http.StatusOK, put.Code, put.Body.String())
	get := doRequest(t, srv, http.MethodGet, "/api/v1/projects/"+project.ID+"/settings", nil)
	require.Equal(t, http.StatusOK, get.Code, get.Body.String())
	var want, got map[string]interface{}
	require.NoError(t, json.Unmarshal(src.ProjectSettings, &want))
	require.NoError(t, json.Unmarshal(get.Body.Bytes(), &got))
	for k, v := range want {
		assert.Equal(t, v, got[k], "GET project settings must return %s as the golden states it", k)
	}

	// Template tier.
	tmpl := &store.Template{
		ID:          tid("template-inherited-" + tier),
		Name:        "inherited-" + tier,
		Slug:        "inherited-" + tier,
		Harness:     "claude",
		ContentHash: "d00dfeed",
		Scope:       store.TemplateScopeGlobal,
		Status:      store.TemplateStatusActive,
		Config:      src.Template.Config,
	}
	require.NoError(t, s.CreateTemplate(ctx, tmpl))

	rec := doRequest(t, srv, http.MethodPost, "/api/v1/agents", CreateAgentRequest{
		Name:      "inherited-" + tier,
		ProjectID: project.ID,
		Template:  tmpl.ID,
		Task:      "do something",
	})
	require.Equal(t, http.StatusCreated, rec.Code, "body: %s", rec.Body.String())
	var resp CreateAgentResponse
	require.NoError(t, json.Unmarshal(rec.Body.Bytes(), &resp))
	require.NotNil(t, resp.Agent)
	require.NotNil(t, resp.Agent.AppliedConfig)

	require.True(t, mockClient.createCalled, "agent should have been dispatched to the broker")
	req := mockClient.lastCreateReq
	require.NotNil(t, req)
	require.NotNil(t, req.Config)

	dispatched := map[string]string{}
	set := func(key, v string) {
		if v != "" {
			dispatched[key] = v
		}
	}
	set("config.model", req.ResolvedEnv["SCION_MODEL"])
	set("config.thinking_level", req.ResolvedEnv["SCION_THINKING_LEVEL"])
	set("config.auth_selectedType", req.Config.HarnessAuth)
	if v := req.ResolvedEnv["SCION_AUTO_EXPOSE_PORTS"]; v != "" {
		dispatched["autoExpose"] = v
	} else if d := req.Config.HubAgentDefaults; d != nil && d.AutoExposePorts != nil {
		dispatched["autoExpose"] = strconv.FormatBool(*d.AutoExposePorts)
	}
	if ic := req.InlineConfig; ic != nil {
		if ic.MaxTurns > 0 {
			dispatched["config.max_turns"] = strconv.Itoa(ic.MaxTurns)
		}
		if ic.MaxModelCalls > 0 {
			dispatched["config.max_model_calls"] = strconv.Itoa(ic.MaxModelCalls)
		}
		set("config.max_duration", ic.MaxDuration)
		if r := ic.Resources; r != nil {
			set("config.resources.requests.cpu", r.Requests.CPU)
			set("config.resources.requests.memory", r.Requests.Memory)
			set("config.resources.limits.cpu", r.Limits.CPU)
			set("config.resources.limits.memory", r.Limits.Memory)
			set("config.resources.disk", r.Disk)
		}
		if ic.Telemetry != nil && ic.Telemetry.Enabled != nil {
			dispatched["config.telemetry"] = strconv.FormatBool(*ic.Telemetry.Enabled)
		}
	}
	// Every agent gets a role and a message mode; record them only where
	// the case's sources set one, the values the web can know.
	var ps map[string]interface{}
	require.NoError(t, json.Unmarshal(src.ProjectSettings, &ps))
	if _, ok := ps["defaultAgentRole"]; ok {
		dispatched["agentRole"] = resp.Agent.AppliedConfig.AgentRole
	}
	if src.Template.Config != nil && src.Template.Config.MessageMode != "" {
		dispatched["messageMode"] = resp.Agent.MessageMode
	}
	return dispatched
}
