package authzop

// chatOperations lists the catalog operations for native chat, one per
// entry point. Every chat route is registered only when native chat is
// enabled.
//
// A chat write acts on the caller's behalf, so a user access token needs
// inbox:write for it in addition to the target check every caller passes,
// and inbox:read to read the caller's own DMs, read state and preferences.
// The record's project decides the token boundary: a thread's project, the
// project of a DM's peer agent, an agent's project. A record with no
// project needs a hub boundary. On the conversation routes a refusal
// answers as not found (Thread not found); the reason is logged. Only an
// interactive session, a dev credential, a federated user or a user access
// token reaches these routes.
