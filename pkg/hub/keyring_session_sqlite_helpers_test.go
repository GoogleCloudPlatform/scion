package hub

import (
	"bytes"
	"net/http/httptest"
	"testing"

	"github.com/GoogleCloudPlatform/scion/pkg/store"
	"github.com/stretchr/testify/require"
)

// keyringSessionToken mints user's web access token on srv at srv's current
// ring time. With a keyring, user JWTs are signed by the signing ring, so no
// token can be minted once the active generation reaches its sign_until;
// tests that close issuance mint the session first and keep using it, as an
// existing browser session would.
func keyringSessionToken(t *testing.T, srv *Server, user *store.User) string {
	t.Helper()
	token, _, _, err := srv.userTokenService.GenerateTokenPair(user.ID, user.Email, user.DisplayName, user.Role, ClientTypeWeb)
	require.NoError(t, err)
	return token
}

// requestWithToken sends a request to srv with the bearer token and a raw body.
func requestWithToken(t *testing.T, srv *Server, token, method, path string, body []byte) *httptest.ResponseRecorder {
	t.Helper()
	req := httptest.NewRequest(method, path, bytes.NewReader(body))
	req.Header.Set("Authorization", "Bearer "+token)
	rec := httptest.NewRecorder()
	srv.Handler().ServeHTTP(rec, req)
	return rec
}
