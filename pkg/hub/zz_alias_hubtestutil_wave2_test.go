// The declarations below keep the names of test helpers that moved to
// github.com/GoogleCloudPlatform/scion/pkg/hub/internal/hubtestutil
// (generated by hack/hubshard/extract export), so the tests of this
// package need no edits. Code outside this package uses hubtestutil directly.

func alwaysAuthorized(p0 context.Context, p1 string) bool {
	return hubtestutil.AlwaysAuthorized(p0, p1)
}

type apiErrorBody = hubtestutil.APIErrorBody

func captureSlog(t *testing.T) *bytes.Buffer {
	t.Helper()
	return hubtestutil.CaptureSlog(t)
}

func captureSlogDefault(t *testing.T) *bytes.Buffer {
	t.Helper()
	return hubtestutil.CaptureSlogDefault(t)
}

func decodeAPIError(t *testing.T, body []byte) apiErrorBody {
	t.Helper()
	return hubtestutil.DecodeAPIError(t, body)
}

func decodeErrorMessage(t *testing.T, body []byte) string {
	t.Helper()
	return hubtestutil.DecodeErrorMessage(t, body)
}

func decodeItems(t *testing.T, raw json.RawMessage) []map[string]json.RawMessage {
	t.Helper()
	return hubtestutil.DecodeItems(t, raw)
}

func decodeJSONBody(t *testing.T, rec *httptest.ResponseRecorder, v interface{}) {
	t.Helper()
	hubtestutil.DecodeJSONBody(t, rec, v)
}

func decodeObject(t *testing.T, body []byte) map[string]json.RawMessage {
	t.Helper()
	return hubtestutil.DecodeObject(t, body)
}

func emptyKoanf() *koanf.Koanf {
	return hubtestutil.EmptyKoanf()
}

func errorBody(t *testing.T, rec *httptest.ResponseRecorder) (string, map[string]interface{}) {
	t.Helper()
	return hubtestutil.ErrorBody(t, rec)
}

func findRecord(records []slog.Record, msg string) (slog.Record, bool) {
	return hubtestutil.FindRecord(records, msg)
}

func installSentinelLogCapture(t *testing.T) *bytes.Buffer {
	t.Helper()
	return hubtestutil.InstallSentinelLogCapture(t)
}

func intPtr(i int) *int {
	return hubtestutil.IntPtr(i)
}

func itoa(n int) string {
	return hubtestutil.Itoa(n)
}

func newEnvKoanf(t *testing.T, flat map[string]interface{}) *koanf.Koanf {
	t.Helper()
	return hubtestutil.NewEnvKoanf(t, flat)
}

func newFileKoanf(t *testing.T, flat map[string]interface{}) *koanf.Koanf {
	t.Helper()
	return hubtestutil.NewFileKoanf(t, flat)
}

func recordAttr(r slog.Record, key string) (slog.Value, bool) {
	return hubtestutil.RecordAttr(r, key)
}

func recordAttrs(r slog.Record) map[string]any {
	return hubtestutil.RecordAttrs(r)
}

func require_NoError(t *testing.T, err error) {
	t.Helper()
	hubtestutil.RequireNoError(t, err)
}

func strPtr(s string) *string {
	return hubtestutil.StrPtr(s)
}

const testDevToken = hubtestutil.DevToken

func waitClosed(t *testing.T, ch <-chan struct{}, within time.Duration, what string) {
	t.Helper()
	hubtestutil.WaitClosed(t, ch, within, what)
}

func withCursor(query, cursor string) string {
	return hubtestutil.WithCursor(query, cursor)
}
