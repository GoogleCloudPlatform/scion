package daemon

import "syscall"

// detachedSysProcAttr starts the daemon in a new process group, so a
// console Ctrl+C aimed at the launching CLI does not reach it.
func detachedSysProcAttr() *syscall.SysProcAttr {
	return &syscall.SysProcAttr{CreationFlags: syscall.CREATE_NEW_PROCESS_GROUP}
}
