package api

// ValidResetHomeID reports whether id is usable as a home reset ID
// (StartOptions.ResetHomeID): 1 to 64 characters of A-Z, a-z, 0-9 and '-'.
// The ID becomes part of a directory name, so nothing else is accepted.
func ValidResetHomeID(id string) bool {
	if len(id) == 0 || len(id) > 64 {
		return false
	}
	for i := 0; i < len(id); i++ {
		c := id[i]
		switch {
		case c >= 'a' && c <= 'z', c >= 'A' && c <= 'Z', c >= '0' && c <= '9', c == '-':
		default:
			return false
		}
	}
	return true
}
