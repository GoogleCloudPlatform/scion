// TestInfraMarker is the single-row table test_infra_marker: the datastore's
// own record that an operator deliberately designated this database as the
// test-infrastructure database of one hub (ptone/scion#4240, admin tier
// phase A0, gate condition G6).
//
// The only writer is the offline host command
// `scion server test-infra mark` (cmd/server_test_infra.go, through
// pkg/testinfra). No hub route and no store.Store method writes it; the hub
// only reads it once, at startup: the test admin gate reads it when
// --enable-test-admin-identities is set, and the test-identity web session
// key is read from it when --enable-test-identities is set. There is exactly
// one row, id "test-infra-marker".
//
// Every field is immutable: re-designating a database is a deliberate
// operator act (delete the row on the host, then mark again), never an
// update.
type TestInfraMarker struct {
	ent.Schema
}

// Fields of the TestInfraMarker.
func (TestInfraMarker) Fields() []ent.Field {
	return []ent.Field{
		field.String("id").
			NotEmpty().
			Immutable().
			Comment("Fixed singleton id: test-infra-marker"),
		field.String("hub_id").
			NotEmpty().
			Immutable().
			Comment("Resolved hub id (PersistentHubID or server.hub.hub_id) this database is designated for"),
		field.String("class").
			NotEmpty().
			Immutable().
			Comment("Hub class; the only value written is \"test\""),
		field.Time("created_at").
			Immutable().
			Comment("Wall clock of the marking host"),
		field.String("created_by_host").
			Default("").
			Immutable().
			Comment("Host name the offline mark command ran on"),
		field.JSON("attested", json.RawMessage{}).
			Optional().
			Immutable().
			Comment("Operator-attested substrate facts (bucket, secret-backend project, broker ids); declared, not verified"),
		// web_session_key is the hub-local key for test-identity web
		// session cookies (phase WS1, DEC-8): 64 bytes from crypto/rand,
		// generated by the mark command and never derived from any other
		// input. The hub reads it once at startup and expands it into the
		// cookie hash and block keys with their own labels. Deleting the
		// row destroys it; marking again generates a new one, which
		// invalidates every test-identity web session cookie. Sensitive:
		// ent never prints it.
		field.Bytes("web_session_key").
			Optional().
			Sensitive().
			Immutable().
			Comment("Hub-local test-identity web session key (64 random bytes); never logged or returned"),
	}
}

// Annotations of the TestInfraMarker.
func (TestInfraMarker) Annotations() []schema.Annotation {
	return []schema.Annotation{
		entsql.Annotation{Table: "test_infra_marker"},
	}
}
