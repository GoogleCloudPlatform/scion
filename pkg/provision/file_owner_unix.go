package provision

import (
	"os"
	"syscall"
)

// fileOwner returns the owning uid and gid of info, when the platform
// reports them.
func fileOwner(info os.FileInfo) (uid, gid uint32, ok bool) {
	st, ok := info.Sys().(*syscall.Stat_t)
	if !ok {
		return 0, 0, false
	}
	return st.Uid, st.Gid, true
}
