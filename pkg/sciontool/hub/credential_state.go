// The credential state is what sciontool init knows about its own agent
// credential: which credential it holds (identified without its value)
// and how the hub last answered requests made with it. Init publishes it
// in a root-owned file for sciontool doctor, which otherwise only sees the
// credential file.
//
// The published state never holds a credential value, a value prefix, a
// claim set, a response body or any other free text: only the
// credential's jti, issue and expiry times and a short SHA-256 prefix,
// fixed outcome names, status codes and times.

// Who refused a request, as told by its response.
const (
	RefusedByNone    = ""
	RefusedByHub     = "hub"     // the hub's own agent-credential check
	RefusedByProxy   = "proxy"   // a platform proxy in front of the hub
	RefusedByUnknown = "unknown" // refused, but the source was not recorded
)

// ClassifyRejection reports who rejected resp: RefusedByProxy for a
// redirect to a Google sign-in page, or a 401/403 that is marked as
// generated by IAP or is not the hub's JSON error object; RefusedByHub for
// a 401/403 with the hub's JSON error object; RefusedByNone otherwise.
// body is only examined, never kept.
func ClassifyRejection(resp *http.Response, body []byte) string {
	if resp == nil {
		return RefusedByNone
	}
	if resp.StatusCode >= 300 && resp.StatusCode < 400 {
		if loc := resp.Header.Get("Location"); strings.Contains(loc, "accounts.google.com") {
			return RefusedByProxy
		}
		return RefusedByNone
	}
	if resp.StatusCode != http.StatusUnauthorized && resp.StatusCode != http.StatusForbidden {
		return RefusedByNone
	}
	if strings.EqualFold(resp.Header.Get("X-Goog-IAP-Generated-Response"), "true") {
		return RefusedByProxy
	}
	var hubErr struct {
		Error json.RawMessage `json:"error"`
	}
	if json.Unmarshal(body, &hubErr) == nil && len(hubErr.Error) > 0 {
		return RefusedByHub
	}
	return RefusedByProxy
}

// Outcomes recorded in an OutcomeRecord.
const (
	// OutcomeSent: a heartbeat got a status below 400. The client follows
	// redirects, so this shows the request was answered, not that the hub
	// accepted the credential.
	OutcomeSent = "sent"
	// OutcomeRefused: 401 or 403.
	OutcomeRefused = "refused"
	// OutcomePaused: the heartbeat was not sent because status writes are
	// paused after the credential was refused (see writeGate).
	OutcomePaused = "paused"
	// OutcomeFailed: no answer, or another error status.
	OutcomeFailed = "failed"
	// OutcomeRefreshed: a token refresh returned a new credential.
	OutcomeRefreshed = "refreshed"
	// OutcomeAccepted: a credential check was accepted.
	OutcomeAccepted = "accepted"
	// OutcomeUnchecked: a credential check got no usable answer.
	OutcomeUnchecked = "unchecked"
)

// CredentialIdentity names a credential without its value.
type CredentialIdentity struct {
	// JTI is the jti claim, if it is short and plain (see safeJTI).
	JTI string `json:"jti,omitempty"`
	// IssuedAt and Expiry are the iat and exp claims; zero if absent.
	IssuedAt time.Time `json:"iat,omitzero"`
	Expiry   time.Time `json:"exp,omitzero"`
	// FP is the first 8 hex digits of the value's SHA-256.
	FP string `json:"fp,omitempty"`
}

// OutcomeRecord is the result of one request made with a credential.
type OutcomeRecord struct {
	At      time.Time `json:"at"`
	Outcome string    `json:"outcome"`
	// Status is the final HTTP status, 0 when there was none.
	Status int `json:"status,omitempty"`
	// FP is the short fingerprint of the credential the request presented
	// (for a paused heartbeat: of the credential whose refusal set the
	// pause).
	FP string `json:"fp,omitempty"`
	// RefusedBy is set for OutcomeRefused and OutcomePaused.
	RefusedBy string `json:"refused_by,omitempty"`
}

// CredentialState is the published state. Version 1.
type CredentialState struct {
	Version       int                `json:"version"`
	Instance      string             `json:"instance,omitempty"`
	InitStartedAt time.Time          `json:"init_started_at,omitzero"`
	UpdatedAt     time.Time          `json:"updated_at"`
	Seq           uint64             `json:"seq"`
	Credential    CredentialIdentity `json:"credential"`
	Heartbeat     *OutcomeRecord     `json:"heartbeat,omitempty"`
	Refresh       *OutcomeRecord     `json:"refresh,omitempty"`
	Check         *OutcomeRecord     `json:"check,omitempty"`
}

// credentialStateVersion is CredentialState.Version.
const credentialStateVersion = 1

// credentialStateMaxBytes bounds the published file.
const credentialStateMaxBytes = 16 << 10

// credState holds a client's credential state. Lock order: tokenMu, then
// mu; never the reverse. Recording only copies values under mu and wakes
// the writer; it does no I/O and calls nothing.
type credState struct {
	mu      sync.Mutex
	st      CredentialState
	changed chan struct{} // buffered(1); created on first use
}

// CredentialIdentityOf describes token without its value, as the
// credential state does.
func CredentialIdentityOf(token string) CredentialIdentity {
	info := InspectToken(token)
	return CredentialIdentity{
		JTI:      safeJTI(info.ID),
		IssuedAt: info.IssuedAt,
		Expiry:   info.Expiry,
		FP:       info.Fingerprint.Short(),
	}
}

// safeJTI returns jti if it is at most 64 characters of [A-Za-z0-9._-],
// otherwise "".
func safeJTI(jti string) string {
	if len(jti) > 64 {
		return ""
	}
	for _, r := range jti {
		switch {
		case r >= 'a' && r <= 'z', r >= 'A' && r <= 'Z', r >= '0' && r <= '9', r == '.', r == '_', r == '-':
		default:
			return ""
		}
	}
	return jti
}

// shortFP is the short fingerprint of token.
func shortFP(token string) string {
	return TokenFingerprint(token).Short()
}

// update applies f to the state under mu, bumps the sequence number and
// wakes the writer.
func (s *credState) update(f func(st *CredentialState)) {
	s.mu.Lock()
	f(&s.st)
	s.st.Seq++
	s.st.UpdatedAt = time.Now().UTC()
	if s.changed == nil {
		s.changed = make(chan struct{}, 1)
	}
	ch := s.changed
	s.mu.Unlock()
	select {
	case ch <- struct{}{}:
	default:
	}
}

// recordCredential records token as the in-memory credential. Callers may
// hold tokenMu.
func (c *Client) recordCredential(token string) {
	id := CredentialIdentityOf(token)
	c.cstate.update(func(st *CredentialState) { st.Credential = id })
}

// recordHeartbeat records the result of a heartbeat.
func (c *Client) recordHeartbeat(res writeResult, err error) {
	rec := OutcomeRecord{At: time.Now().UTC(), Status: res.status, FP: res.fp}
	switch {
	case errors.Is(err, ErrHubWritesPaused):
		rec.Outcome = OutcomePaused
		rec.Status = 0
		rec.FP, rec.RefusedBy = c.writes.pausedBy()
		if rec.RefusedBy == RefusedByNone {
			rec.RefusedBy = RefusedByUnknown
		}
	case res.status == http.StatusUnauthorized || res.status == http.StatusForbidden:
		rec.Outcome = OutcomeRefused
		rec.RefusedBy = res.refusedBy
		if rec.RefusedBy == RefusedByNone {
			rec.RefusedBy = RefusedByUnknown
		}
	case err == nil && res.status > 0 && res.status < 400:
		rec.Outcome = OutcomeSent
	default:
		rec.Outcome = OutcomeFailed
	}
	c.cstate.update(func(st *CredentialState) { st.Heartbeat = &rec })
}

// recordRefresh records the result of a token refresh that presented the
// credential with short fingerprint fp.
func (c *Client) recordRefresh(fp string, status int, refusedBy string, ok bool) {
	rec := OutcomeRecord{At: time.Now().UTC(), Status: status, FP: fp}
	switch {
	case ok:
		rec.Outcome = OutcomeRefreshed
	case status == http.StatusUnauthorized || status == http.StatusForbidden:
		rec.Outcome = OutcomeRefused
		rec.RefusedBy = refusedBy
		if rec.RefusedBy == RefusedByNone {
			rec.RefusedBy = RefusedByUnknown
		}
	default:
		rec.Outcome = OutcomeFailed
	}
	c.cstate.update(func(st *CredentialState) { st.Refresh = &rec })
}

// recordCheck records the result of a check of the client's own
// credential (CheckCurrentCredentialAccepted). The check cannot tell the
// hub from a proxy, so a refusal is RefusedByUnknown.
func (c *Client) recordCheck(token string, err error) {
	rec := OutcomeRecord{At: time.Now().UTC(), FP: shortFP(token)}
	switch {
	case err == nil:
		rec.Outcome = OutcomeAccepted
	case errors.Is(err, ErrCandidateRefused):
		rec.Outcome = OutcomeRefused
		rec.RefusedBy = RefusedByUnknown
	default:
		rec.Outcome = OutcomeUnchecked
	}
	c.cstate.update(func(st *CredentialState) { st.Check = &rec })
}

// CredentialStateSnapshot returns a copy of the client's credential state.
func (c *Client) CredentialStateSnapshot() CredentialState {
	if c == nil {
		return CredentialState{}
	}
	c.cstate.mu.Lock()
	defer c.cstate.mu.Unlock()
	st := c.cstate.st
	for _, p := range []**OutcomeRecord{&st.Heartbeat, &st.Refresh, &st.Check} {
		if *p != nil {
			r := **p
			*p = &r
		}
	}
	st.Version = credentialStateVersion
	return st
}

// credentialStateChanged returns the channel recording wakes.
func (c *Client) credentialStateChanged() <-chan struct{} {
	c.cstate.mu.Lock()
	defer c.cstate.mu.Unlock()
	if c.cstate.changed == nil {
		c.cstate.changed = make(chan struct{}, 1)
	}
	return c.cstate.changed
}

// Where the state is published. Package vars for the test seams below;
// production code never changes them.
var (
	credentialStateDir  = "/run/scion"
	credentialStateBase = "/"
	// credentialStateOwner is the uid that must own the file and every
	// directory above it. Init publishes only when running as this uid.
	credentialStateOwner = 0
	// credentialStateOverridden is set by SetCredentialStateDirForTest.
	credentialStateOverridden bool
)

const (
	credentialStateFileName = "credential-state.json"
	credentialStateTmpGlob  = credentialStateFileName + ".tmp-"
)

// SetCredentialStateDirForTest publishes the credential state in dir,
// requiring dir and every directory from base down to it to be owned by
// the test's own uid instead of root. Test only; it returns a restore
// function.
func SetCredentialStateDirForTest(dir, base string) func() {
	if !testing.Testing() {
		panic("scion/hub: SetCredentialStateDirForTest called outside a test")
	}
	oDir, oBase, oOwner, oOver := credentialStateDir, credentialStateBase, credentialStateOwner, credentialStateOverridden
	credentialStateDir, credentialStateBase, credentialStateOwner, credentialStateOverridden = dir, base, os.Getuid(), true
	return func() {
		credentialStateDir, credentialStateBase, credentialStateOwner, credentialStateOverridden = oDir, oBase, oOwner, oOver
	}
}

// CredentialStatePath returns the path of the published state.
func CredentialStatePath() string {
	return filepath.Join(credentialStateDir, credentialStateFileName)
}

// canPublishCredentialState reports whether this process may publish: it
// runs as the owner uid (root in production). Elsewhere, for example when
// init runs as the agent user, the workload could change the file, so
// nothing is published.
func canPublishCredentialState() bool {
	if testing.Testing() && !credentialStateOverridden {
		return false
	}
	return os.Geteuid() == credentialStateOwner
}

// openCredentialStateDir returns a descriptor of the state directory after
// checking it and every directory from the base down to it. If create is
// true, a missing state directory is created (0755) first.
func openCredentialStateDir(create bool) (int, error) {
	owner := stateOwnerUID()
	dirFd, _, err := dirfd.OpenParentNoFollowOwnedBy(credentialStateBase, CredentialStatePath(), owner)
	if err == nil {
		return dirFd, nil
	}
	if !create || !errors.Is(err, syscall.ENOENT) {
		return -1, err
	}
	parentFd, dirName, perr := dirfd.OpenParentNoFollowOwnedBy(credentialStateBase, credentialStateDir, owner)
	if perr != nil {
		return -1, perr
	}
	mkErr := unix.Mkdirat(parentFd, dirName, 0o755)
	_ = syscall.Close(parentFd)
	if mkErr != nil && !errors.Is(mkErr, syscall.EEXIST) {
		return -1, mkErr
	}
	dirFd, _, err = dirfd.OpenParentNoFollowOwnedBy(credentialStateBase, CredentialStatePath(), owner)
	if err == nil && mkErr == nil {
		// Searchable by doctor whatever the umask was.
		_ = syscall.Fchmod(dirFd, 0o755)
	}
	return dirFd, err
}

// stateOwnerUID is credentialStateOwner as a uid.
func stateOwnerUID() uint32 {
	return uint32(credentialStateOwner) //nolint:gosec // a uid, never negative
}

// writeCredentialState writes st to the state file: a new temp file
// (O_EXCL, no-follow, unique name) in the checked directory, renamed over
// the file. Mode 0644: the state holds no value.
func writeCredentialState(st CredentialState) error {
	data, err := json.Marshal(st)
	if err != nil {
		return err
	}
	if len(data) > credentialStateMaxBytes {
		return fmt.Errorf("credential state too large")
	}
	dirFd, err := openCredentialStateDir(true)
	if err != nil {
		return err
	}
	defer func() { _ = syscall.Close(dirFd) }()
	var rnd [8]byte
	if _, err := rand.Read(rnd[:]); err != nil {
		return err
	}
	tmp := credentialStateTmpGlob + hex.EncodeToString(rnd[:])
	f, err := dirfd.CreateExclAt(dirFd, tmp, 0o644)
	if err != nil {
		return err
	}
	_, werr := f.Write(data)
	if werr == nil {
		werr = f.Chmod(0o644)
	}
	if cerr := f.Close(); werr == nil {
		werr = cerr
	}
	if werr == nil {
		werr = dirfd.RenameAt(dirFd, tmp, credentialStateFileName)
	}
	if werr != nil {
		_ = dirfd.UnlinkAt(dirFd, tmp)
	}
	return werr
}

// writeCredentialStateFn is writeCredentialState; a test seam.
var writeCredentialStateFn = writeCredentialState

// removeCredentialState unlinks the state file, so a state that could not
// be updated is never read as current.
func removeCredentialState() {
	dirFd, err := openCredentialStateDir(false)
	if err != nil {
		return
	}
	defer func() { _ = syscall.Close(dirFd) }()
	_ = dirfd.UnlinkAt(dirFd, credentialStateFileName)
}

// removeCredentialStateTemps unlinks temp files left by an earlier run.
func removeCredentialStateTemps() {
	dirFd, err := openCredentialStateDir(false)
	if err != nil {
		return
	}
	defer func() { _ = syscall.Close(dirFd) }()
	dup, err := syscall.Dup(dirFd)
	if err != nil {
		return
	}
	d := os.NewFile(uintptr(dup), credentialStateDir)
	defer func() { _ = d.Close() }()
	names, err := d.Readdirnames(-1)
	if err != nil {
		return
	}
	for _, n := range names {
		if strings.HasPrefix(n, credentialStateTmpGlob) {
			_ = dirfd.UnlinkAt(dirFd, n)
		}
	}
}

// newInstanceID returns a random ID for this init run.
func newInstanceID() string {
	var b [8]byte
	if _, err := rand.Read(b[:]); err != nil {
		return ""
	}
	return hex.EncodeToString(b[:])
}

// PublishCredentialState publishes c's credential state for sciontool
// doctor, when this process may (see canPublishCredentialState): it writes
// the current state at once, before returning, so a file left by an
// earlier run is never read as this run's, and then keeps the file up to
// date from a single writer goroutine until ctx ends. A failed write
// removes the file. It returns false when this process does not publish
// (it does not run as root, or c is nil).
//
// The file can only be trusted where the workload cannot become root.
// Losing the last update when the process exits is harmless: doctor runs
// only while init runs, and the next start writes a new file at once.
func PublishCredentialState(ctx context.Context, c *Client) bool {
	if c == nil || !canPublishCredentialState() {
		return false
	}
	c.cstate.update(func(st *CredentialState) {
		st.Instance = newInstanceID()
		st.InitStartedAt = time.Now().UTC()
	})
	removeCredentialStateTemps()
	changed := c.credentialStateChanged()
	w := &credentialStateWriter{client: c}
	if !w.writeLatest() {
		log.Error("Could not publish the credential state; sciontool doctor will report it as unavailable")
	}
	go func() {
		for {
			select {
			case <-ctx.Done():
				return
			case <-changed:
				w.writeLatest()
			}
		}
	}()
	return true
}

// credentialStateWriter writes the latest state; one per client.
type credentialStateWriter struct {
	client  *Client
	lastSeq uint64
	failing bool
}

// writeLatest writes the client's current state unless it was already
// written. It reports whether the file holds the current state.
func (w *credentialStateWriter) writeLatest() bool {
	st := w.client.CredentialStateSnapshot()
	if st.Seq != 0 && st.Seq <= w.lastSeq {
		return true
	}
	if err := writeCredentialStateFn(st); err != nil {
		removeCredentialState()
		if !w.failing {
			log.Error("Could not update the credential state file: %v", err)
		}
		w.failing = true
		return false
	}
	w.failing = false
	w.lastSeq = st.Seq
	return true
}

// Read outcomes of ReadCredentialState.
const (
	CredentialStateOK          = "ok"
	CredentialStateUnavailable = "unavailable"
	CredentialStateUntrusted   = "untrusted"
)

// ReadCredentialState reads the published state. status is
// CredentialStateOK, CredentialStateUnavailable (no file) or
// CredentialStateUntrusted, with a fixed reason: the file or a directory
// above it is not owned by root or is writable by others, is a symlink,
// is not a single-link regular file, is too large or is not readable.
func ReadCredentialState() (st CredentialState, status, reason string) {
	owner := stateOwnerUID()
	dirFd, leaf, err := dirfd.OpenParentNoFollowOwnedBy(credentialStateBase, CredentialStatePath(), owner)
	if err != nil {
		if errors.Is(err, syscall.ENOENT) {
			return st, CredentialStateUnavailable, ""
		}
		if errors.Is(err, dirfd.ErrNotOwned) {
			return st, CredentialStateUntrusted, "a directory above it is not owned by root or is writable by others"
		}
		return st, CredentialStateUntrusted, "a directory above it is not readable or is a symlink"
	}
	defer func() { _ = syscall.Close(dirFd) }()
	f, err := dirfd.OpenAt(dirFd, leaf, syscall.O_RDONLY|syscall.O_NOFOLLOW|syscall.O_NONBLOCK, 0)
	if err != nil {
		if errors.Is(err, syscall.ENOENT) {
			return st, CredentialStateUnavailable, ""
		}
		return st, CredentialStateUntrusted, "the file is a symlink or is not readable"
	}
	defer func() { _ = f.Close() }()
	var fst syscall.Stat_t
	if err := syscall.Fstat(int(f.Fd()), &fst); err != nil {
		return st, CredentialStateUntrusted, "the file is not readable"
	}
	switch {
	case fst.Mode&syscall.S_IFMT != syscall.S_IFREG:
		return st, CredentialStateUntrusted, "the file is not a regular file"
	case fst.Uid != owner || fst.Mode&0o022 != 0:
		return st, CredentialStateUntrusted, "the file is not owned by root or is writable by others"
	case fst.Nlink != 1:
		return st, CredentialStateUntrusted, "the file has more than one link"
	case fst.Size > credentialStateMaxBytes:
		return st, CredentialStateUntrusted, "the file is too large"
	}
	data, err := io.ReadAll(io.LimitReader(f, credentialStateMaxBytes+1))
	if err != nil || len(data) > credentialStateMaxBytes {
		return st, CredentialStateUntrusted, "the file is not readable"
	}
	if err := json.Unmarshal(data, &st); err != nil || st.Version != credentialStateVersion {
		return CredentialState{}, CredentialStateUntrusted, "the file is not a readable state"
	}
	return st, CredentialStateOK, ""
}

// ReadTokenFileWithModTime is ReadTokenFile that also returns the file's
// modification time, from the same guarded read. ok is false when there is
// no usable value. An oversized file is warned about, as ReadTokenFile
// does.
func ReadTokenFileWithModTime() (token string, modTime time.Time, ok bool) {
	path := TokenFilePath()
	dirFd, leaf, err := dirfd.OpenParentNoFollow(path)
	if err != nil {
		return "", time.Time{}, false
	}
	defer func() { _ = syscall.Close(dirFd) }()
	value, st, err := readTokenAtStat(dirFd, leaf, path)
	if err != nil {
		if errors.Is(err, dirfd.ErrTooLarge) {
			// As ReadTokenFile; err already names the path.
			warnTokenFile("Ignoring token file: %v", err)
		}
		return "", time.Time{}, false
	}
	value = strings.TrimSpace(value)
	if value == "" {
		return "", time.Time{}, false
	}
	return value, statModTime(&st), true
}
