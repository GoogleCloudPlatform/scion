//go:build unix

package config

import (
	"syscall"
	"testing"
)

// setTestUmask sets the process umask for the duration of t and restores the
// previous value on cleanup. Not safe for t.Parallel(): umask is process-wide.
func setTestUmask(t *testing.T, mask int) {
	t.Helper()
	prev := syscall.Umask(mask)
	t.Cleanup(func() { syscall.Umask(prev) })
}
